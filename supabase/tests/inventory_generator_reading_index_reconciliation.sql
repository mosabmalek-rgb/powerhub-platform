do $assert_indexes$
declare v_index text;
begin
  foreach v_index in array array[
    'generators_created_at_idx',
    'meter_readings_approval_operation_uidx',
    'meter_readings_opening_baseline_idx',
    'meter_readings_status_idx',
    'meter_readings_status_reading_at_idx',
    'meter_readings_subscriber_date_idx',
    'meter_readings_subscriber_id_idx',
    'meter_readings_tenant_reading_at_id_desc_idx'
  ] loop
    if not exists (
      select 1 from pg_indexes
      where schemaname='public' and indexname=v_index
    ) then
      raise exception 'EXPECTED_INDEX_MISSING: %', v_index;
    end if;
  end loop;

  if not exists (
    select 1
    from pg_index i
    join pg_class idx on idx.oid=i.indexrelid
    join pg_class tbl on tbl.oid=i.indrelid
    where idx.relname='meter_readings_approval_operation_uidx'
      and tbl.relname='meter_readings'
      and i.indisunique
      and pg_get_expr(i.indpred,i.indrelid) ilike '%approval_client_operation_id IS NOT NULL%'
  ) then
    raise exception 'APPROVAL_OPERATION_UNIQUENESS_NOT_PARTIAL_OR_MISSING';
  end if;

  if not exists (
    select 1 from pg_trigger t
    join pg_class c on c.oid=t.tgrelid
    where c.relname='generators'
      and t.tgname='generators_set_updated_at'
      and not t.tgisinternal
  ) then
    raise exception 'GENERATOR_UPDATED_AT_TRIGGER_MISSING';
  end if;
end
$assert_indexes$;

do $assert_trigger_execution$
declare v_id bigint; v_before timestamptz; v_after timestamptz;
begin
  insert into public.generators(updated_at) values(now()-interval '1 hour')
  returning id,updated_at into v_id,v_before;
  update public.generators set created_at=created_at where id=v_id;
  select updated_at into v_after from public.generators where id=v_id;
  if v_after is null or v_after <= v_before or v_after <> now() then
    raise exception 'GENERATOR_UPDATED_AT_TRIGGER_NOT_EXECUTED';
  end if;
end
$assert_trigger_execution$;

select 'generator/reading index and updated_at trigger reconciliation passed' as result;
