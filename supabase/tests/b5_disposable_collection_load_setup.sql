CREATE OR REPLACE FUNCTION public.b5_collect_one(p_worker int,p_iteration int)
RETURNS text LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public,pg_temp
AS $do$
DECLARE v_k integer;v_invoice bigint;v_amount numeric;v_id bigint;v_replay boolean;ts timestamptz;
 v_key uuid;
BEGIN
 IF current_database()<>'powerhub_b5_synthetic_collection_test' OR
   p_worker NOT BETWEEN 1 AND 4 OR p_iteration NOT BETWEEN 1 AND 250
 THEN RAISE EXCEPTION 'B5_COLLECTION_SCOPE_INVALID'; END IF;
 v_k:=(p_worker-1)*250+p_iteration;
 IF v_k=1000 THEN v_k:=1; END IF;
 v_invoice:=10000+v_k;
 v_amount:=CASE WHEN v_k IN (100,300,500,700,900) THEN 1.5 ELSE 1 END;
 v_key:=md5('B5-collection:'||v_k)::uuid;
 ts:=clock_timestamp();
 SELECT payment_id,replayed INTO v_id,v_replay FROM public.powerhub_create_payment(
  1,10,7,v_invoice,v_invoice,'B5-COL-'||v_k,v_amount,'cash',301,
  NULL,NULL,'B5-REF-'||v_k,NULL,NULL,NULL,v_key);
 IF v_id IS NULL OR v_replay IS DISTINCT FROM (p_worker=4 AND p_iteration=250)
 THEN RAISE EXCEPTION 'B5_COLLECTION_REPLAY_OR_RESULT_FAILED'; END IF;
 INSERT INTO public.b5_collection_samples(
  worker,iteration,backend_pid,replay,payment_id,elapsed_ms)
 VALUES(p_worker,p_iteration,pg_backend_pid(),v_replay,v_id,
  round(extract(epoch from clock_timestamp()-ts)::numeric*1000,3));
 RETURN 'COLLECTION_OK';
END $do$;
REVOKE ALL ON FUNCTION public.b5_collect_one(integer,integer) FROM PUBLIC,anon,authenticated;
