create table public.expenses (
  id bigint generated by default as identity primary key
);
create table public.account_transactions (
  id bigint generated by default as identity primary key
);

create or replace function public.powerhub_create_expense_with_account(
  p_tenant_id bigint,
  p_site_id bigint,
  p_user_id bigint,
  p_generator_id bigint,
  p_company_account_id bigint,
  p_category text,
  p_description text,
  p_amount numeric,
  p_reference_no text
)
returns table(expense_id bigint,transaction_id bigint)
language plpgsql
as $$
declare
  v_expense_id bigint;
  v_transaction_id bigint;
begin
  insert into public.expenses default values returning id into v_expense_id;
  insert into public.account_transactions default values returning id into v_transaction_id;
  return query select v_expense_id,v_transaction_id;
end $$;
revoke all on function public.powerhub_create_expense_with_account(bigint,bigint,bigint,bigint,bigint,text,text,numeric,text) from public,anon,authenticated;
grant execute on function public.powerhub_create_expense_with_account(bigint,bigint,bigint,bigint,bigint,text,text,numeric,text) to service_role;

