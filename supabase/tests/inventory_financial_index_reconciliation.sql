do $assert_trigger$
declare v_id bigint; v_before timestamptz; v_after timestamptz;
begin
  if not exists (
    select 1 from pg_trigger t join pg_class c on c.oid=t.tgrelid
    where c.relname='company_accounts'
      and t.tgname='company_accounts_set_updated_at'
      and not t.tgisinternal
  ) then
    raise exception 'COMPANY_ACCOUNT_UPDATED_AT_TRIGGER_MISSING';
  end if;
  insert into public.company_accounts(tenant_id,updated_at)
    values(1,now()-interval '1 hour') returning id,updated_at into v_id,v_before;
  update public.company_accounts set tenant_id=tenant_id where id=v_id;
  select updated_at into v_after from public.company_accounts where id=v_id;
  if v_after is null or v_after<=v_before or v_after<>now() then
    raise exception 'COMPANY_ACCOUNT_UPDATED_AT_TRIGGER_NOT_EXECUTED';
  end if;
end
$assert_trigger$;

