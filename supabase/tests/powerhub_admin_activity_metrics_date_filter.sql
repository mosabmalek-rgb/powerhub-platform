DO $filtered$
DECLARE
  v_today date := (pg_catalog.clock_timestamp() AT TIME ZONE 'Asia/Gaza')::date;
  v_seven jsonb;
  v_thirty jsonb;
  v_today_only jsonb;
  v_all jsonb;
BEGIN
  v_seven := public.powerhub_admin_get_activity_metrics(v_today - 6, v_today);
  IF (v_seven->'paymentDocumentation'->>'totalRequests')::bigint <> 4
     OR (v_seven->'paymentDocumentation'->>'pendingRequests')::bigint <> 1
     OR (v_seven->'paymentDocumentation'->>'approvedRequests')::bigint <> 2
     OR (v_seven->'paymentDocumentation'->>'rejectedRequests')::bigint <> 1
     OR (v_seven->'paymentDocumentation'->>'approvedAmountInPeriod')::numeric <> 100 THEN
    RAISE EXCEPTION 'SEVEN_DAY_PAYMENT_FILTER_MISMATCH: %', v_seven->'paymentDocumentation';
  END IF;

  IF (v_seven->'search'->>'searchesInPeriod')::bigint <> 3
     OR (v_seven->'search'->>'noResultSearchesInPeriod')::bigint <> 1
     OR (v_seven->'search'->>'generatorResultHitsInPeriod')::bigint <> 1
     OR (v_seven->'search'->>'subscriberResultHitsInPeriod')::bigint <> 2
     OR (v_seven->'search'->>'ownerResultHitsInPeriod')::bigint <> 1
     OR (v_seven->'search'->>'noResultRatePercentInPeriod')::numeric <> 33.33 THEN
    RAISE EXCEPTION 'SEVEN_DAY_SEARCH_FILTER_MISMATCH: %', v_seven->'search';
  END IF;

  v_thirty := public.powerhub_admin_get_activity_metrics(v_today - 29, v_today);
  IF (v_thirty->'paymentDocumentation'->>'totalRequests')::bigint <> 5
     OR (v_thirty->'paymentDocumentation'->>'approvedAmountInPeriod')::numeric <> 140 THEN
    RAISE EXCEPTION 'THIRTY_DAY_FILTER_MISMATCH: %', v_thirty;
  END IF;

  v_today_only := public.powerhub_admin_get_activity_metrics(v_today, v_today);
  IF (v_today_only->'paymentDocumentation'->>'totalRequests')::bigint <> 0
     OR (v_today_only->'search'->>'searchesInPeriod')::bigint <> 3 THEN
    RAISE EXCEPTION 'SINGLE_DAY_FILTER_MISMATCH: %', v_today_only;
  END IF;

  v_all := public.powerhub_admin_get_activity_metrics(NULL, NULL);
  IF (v_all->'paymentDocumentation'->>'totalRequests')::bigint <> 6
     OR (v_all->'paymentDocumentation'->>'approvedAmountInPeriod')::numeric <> 140
     OR (v_all->'search'->>'searchesInPeriod')::bigint <> 3
     OR (v_all->'period'->>'fromDate') IS NOT NULL
     OR (v_all->'period'->>'toDate') IS NOT NULL THEN
    RAISE EXCEPTION 'ALL_TIME_FILTER_MISMATCH: %', v_all;
  END IF;
END
$filtered$;

