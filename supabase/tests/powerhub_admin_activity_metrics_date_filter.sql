     OR has_function_privilege('authenticated','public.powerhub_admin_get_activity_metrics(date,date)','EXECUTE')
     OR NOT has_function_privilege('service_role','public.powerhub_admin_get_activity_metrics(date,date)','EXECUTE') THEN
    RAISE EXCEPTION 'ADMIN_ACTIVITY_DATE_FILTER_RPC_ACL_MISMATCH';
  END IF;
END
