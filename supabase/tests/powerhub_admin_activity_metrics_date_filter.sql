DO $filtered$
DECLARE
  v_today date := (pg_catalog.clock_timestamp() AT TIME ZONE 'Asia/Gaza')::date;
  v_seven jsonb;
  v_thirty jsonb;
  v_ninety jsonb;
  v_today_only jsonb;
  v_all jsonb;
  v_expected_payment record;
BEGIN
  SELECT
    count(*)::bigint AS total_requests,
    count(*) FILTER (WHERE status = 'pending')::bigint AS pending_requests,
    count(*) FILTER (WHERE status = 'approved')::bigint AS approved_requests,
    count(*) FILTER (WHERE status = 'rejected')::bigint AS rejected_requests,
    coalesce(sum(payment_amount) FILTER (WHERE status = 'approved'), 0)::numeric AS approved_amount
  INTO v_expected_payment
  FROM public.payment_documentation_requests
  WHERE submitted_at >= (v_today - 6)::timestamp AT TIME ZONE 'Asia/Gaza'
    AND submitted_at < (v_today + 1)::timestamp AT TIME ZONE 'Asia/Gaza';

  v_seven := public.powerhub_admin_get_activity_metrics(v_today - 6, v_today);
  IF (v_seven->'paymentDocumentation'->>'totalRequests')::bigint <> v_expected_payment.total_requests
     OR (v_seven->'paymentDocumentation'->>'pendingRequests')::bigint <> v_expected_payment.pending_requests
     OR (v_seven->'paymentDocumentation'->>'approvedRequests')::bigint <> v_expected_payment.approved_requests
     OR (v_seven->'paymentDocumentation'->>'rejectedRequests')::bigint <> v_expected_payment.rejected_requests
     OR (v_seven->'paymentDocumentation'->>'approvedAmountInPeriod')::numeric <> v_expected_payment.approved_amount THEN
    RAISE EXCEPTION 'SEVEN_DAY_PAYMENT_FILTER_MISMATCH: %', v_seven->'paymentDocumentation';
  END IF;

  IF (v_seven->'search'->>'searchesInPeriod')::bigint <> 3
     OR (v_seven->'search'->>'noResultSearchesInPeriod')::bigint <> 1
     OR (v_seven->'search'->>'generatorResultHitsInPeriod')::bigint <> 1
     OR (v_seven->'search'->>'subscriberResultHitsInPeriod')::bigint <> 2
     OR (v_seven->'search'->>'ownerResultHitsInPeriod')::bigint <> 1
     OR (v_seven->'search'->>'noResultRatePercentInPeriod')::numeric <> 33.33 THEN
    RAISE EXCEPTION 'SEVEN_DAY_SEARCH_FILTER_MISMATCH: %', v_seven->'search';
  END IF;

  v_thirty := public.powerhub_admin_get_activity_metrics(v_today - 29, v_today);
  IF (v_thirty->'paymentDocumentation'->>'totalRequests')::bigint <>
       (SELECT count(*) FROM public.payment_documentation_requests
        WHERE submitted_at >= (v_today - 29)::timestamp AT TIME ZONE 'Asia/Gaza'
          AND submitted_at < (v_today + 1)::timestamp AT TIME ZONE 'Asia/Gaza')
     OR (v_thirty->'search'->>'searchesInPeriod')::bigint <> 3 THEN
    RAISE EXCEPTION 'THIRTY_DAY_FILTER_MISMATCH: %', v_thirty;
  END IF;

  v_ninety := public.powerhub_admin_get_activity_metrics(v_today - 89, v_today);
  IF (v_ninety->'paymentDocumentation'->>'totalRequests')::bigint <>
       (SELECT count(*) FROM public.payment_documentation_requests
        WHERE submitted_at >= (v_today - 89)::timestamp AT TIME ZONE 'Asia/Gaza'
          AND submitted_at < (v_today + 1)::timestamp AT TIME ZONE 'Asia/Gaza')
     OR (v_ninety->'search'->>'searchesInPeriod')::bigint <> 3 THEN
    RAISE EXCEPTION 'NINETY_DAY_FILTER_MISMATCH: %', v_ninety;
  END IF;

  v_today_only := public.powerhub_admin_get_activity_metrics(v_today, v_today);
  IF (v_today_only->'search'->>'searchesInPeriod')::bigint <> 3
     OR (v_today_only->'paymentDocumentation'->>'totalRequests')::bigint <>
       (SELECT count(*) FROM public.payment_documentation_requests
        WHERE submitted_at >= v_today::timestamp AT TIME ZONE 'Asia/Gaza'
          AND submitted_at < (v_today + 1)::timestamp AT TIME ZONE 'Asia/Gaza') THEN
    RAISE EXCEPTION 'SINGLE_DAY_FILTER_MISMATCH: %', v_today_only;
  END IF;

  v_all := public.powerhub_admin_get_activity_metrics(NULL, NULL);
  IF (v_all->'paymentDocumentation'->>'totalRequests')::bigint <>
       (SELECT count(*) FROM public.payment_documentation_requests)
     OR (v_all->'search'->>'searchesInPeriod')::bigint < 3
     OR (v_all->'period'->>'fromDate') IS NOT NULL
     OR (v_all->'period'->>'toDate') IS NOT NULL THEN
    RAISE EXCEPTION 'ALL_TIME_FILTER_MISMATCH: %', v_all;
  END IF;
END
$filtered$;

