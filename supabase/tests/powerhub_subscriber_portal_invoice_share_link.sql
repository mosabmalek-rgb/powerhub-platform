DO $assertions$
DECLARE
  v_payload jsonb;
  v_share record;
  v_link_count integer;
  v_hash text := repeat('a', 64);
  v_owner text;
  v_config text[];
BEGIN
  -- A valid identity works with Palestinian country-code phone normalization.
  v_payload := public.powerhub_subscriber_portal_invoice(
    'main', 'SUB-100', '+970595000000', 'INV-100'
  );
  IF v_payload IS NULL
     OR v_payload #>> '{subscriber,subscriberNo}' <> 'SUB-100'
     OR v_payload #>> '{invoice,invoiceNo}' <> 'INV-100' THEN
    RAISE EXCEPTION 'VALID_PORTAL_INVOICE_LOOKUP_FAILED';
  END IF;

  -- The alternate 00-prefixed Palestinian dialing form resolves identically.
  v_payload := public.powerhub_subscriber_portal_invoice(
    'main', 'SUB-100', '00970595000000', 'INV-100'
  );
  IF v_payload IS NULL THEN
    RAISE EXCEPTION 'CANONICAL_PHONE_VARIANT_LOOKUP_FAILED';
  END IF;

  -- A subscriber from another tenant/site cannot be selected through Alpha.
  v_payload := public.powerhub_subscriber_portal_invoice(
    'main', 'SUB-200', '0595111111', 'INV-200'
  );
  IF v_payload IS NOT NULL THEN
    RAISE EXCEPTION 'CROSS_TENANT_SUBSCRIBER_LOOKUP_WAS_ALLOWED';
  END IF;

  -- Archived subscribers must not be discoverable through the public portal.
  v_payload := public.powerhub_subscriber_portal_invoice(
    'main', 'SUB-ARCHIVED', '0595333333', 'INV-ARCHIVED'
  );
  IF v_payload IS NOT NULL THEN
    RAISE EXCEPTION 'ARCHIVED_SUBSCRIBER_LOOKUP_WAS_ALLOWED';
  END IF;

  -- A malformed portal tenant/site relationship must fail closed even when a
  -- matching subscriber and invoice exist under the mismatched tenant ID.
  v_payload := public.powerhub_subscriber_portal_invoice(
    'broken', 'SUB-MISMATCH', '0595222222', 'INV-MISMATCH'
  );
  IF v_payload IS NOT NULL THEN
    RAISE EXCEPTION 'PORTAL_TENANT_SITE_MISMATCH_WAS_ALLOWED';
  END IF;

  -- The valid path stores only the token hash and binds the row to the derived
  -- tenant/site/invoice, not caller-supplied IDs.
  SELECT * INTO v_share
  FROM public.powerhub_create_portal_invoice_share_link(
    'main', 'SUB-100', '+970595000000', 'INV-100', v_hash, 'aaaaaaaa'
  );
  IF v_share.share_link_id IS NULL OR v_share.site_id <> 10 OR v_share.tenant_id <> 100 THEN
    RAISE EXCEPTION 'PORTAL_SHARE_LINK_SCOPE_ASSERTION_FAILED';
  END IF;

  SELECT count(*)::integer INTO v_link_count
  FROM public.invoice_share_links
  WHERE token_hash = v_hash AND tenant_id = 100 AND invoice_id = 2101
    AND expires_at > now() AND expires_at <= now() + interval '7 days';
  IF v_link_count <> 1 THEN
    RAISE EXCEPTION 'PORTAL_SHARE_LINK_PERSISTENCE_ASSERTION_FAILED';
  END IF;

  -- A malformed portal must not create a link, even if its settings row points
  -- at a different tenant that contains matching synthetic records.
  BEGIN
    PERFORM public.powerhub_create_portal_invoice_share_link(
      'broken', 'SUB-MISMATCH', '0595222222', 'INV-MISMATCH', repeat('b', 64), 'bbbbbbbb'
    );
    RAISE EXCEPTION 'EXPECTED_MISMATCHED_PORTAL_TO_BE_REJECTED';
  EXCEPTION WHEN SQLSTATE 'P0001' THEN
    IF SQLERRM NOT IN ('PORTAL_INVOICE_NOT_FOUND', 'PORTAL_NOT_AVAILABLE') THEN
      RAISE;
    END IF;
  END;
  SELECT count(*)::integer INTO v_link_count FROM public.invoice_share_links;
  IF v_link_count <> 1 THEN
    RAISE EXCEPTION 'MISMATCHED_PORTAL_CREATED_A_SHARE_LINK';
  END IF;

  -- Feature entitlement is re-evaluated by the database before link creation.
  UPDATE public.test_payment_feature_access SET allowed = false WHERE tenant_id = 100;
  BEGIN
    PERFORM public.powerhub_create_portal_invoice_share_link(
      'main', 'SUB-100', '0595000000', 'INV-100', repeat('c', 64), 'cccccccc'
    );
    RAISE EXCEPTION 'EXPECTED_PAYMENT_DOCUMENTATION_ENTITLEMENT_DENIAL';
  EXCEPTION WHEN SQLSTATE 'P0001' THEN
    IF SQLERRM <> 'PAYMENT_DOCUMENTATION_NOT_AVAILABLE' THEN RAISE; END IF;
  END;
  UPDATE public.test_payment_feature_access SET allowed = true WHERE tenant_id = 100;

  -- A paid invoice cannot receive a new public payment-documentation link.
  BEGIN
    PERFORM public.powerhub_create_portal_invoice_share_link(
      'main', 'SUB-100', '0595000000', 'INV-PAID', repeat('d', 64), 'dddddddd'
    );
    RAISE EXCEPTION 'EXPECTED_PAID_INVOICE_TO_BE_REJECTED';
  EXCEPTION WHEN SQLSTATE 'P0001' THEN
    IF SQLERRM <> 'INVOICE_ALREADY_PAID' THEN RAISE; END IF;
  END;

  -- Token material is validated before any lookup or insert.
  BEGIN
    PERFORM public.powerhub_create_portal_invoice_share_link(
      'main', 'SUB-100', '0595000000', 'INV-100', 'not-a-sha256-hash', 'bad'
    );
    RAISE EXCEPTION 'EXPECTED_INVALID_TOKEN_TO_BE_REJECTED';
  EXCEPTION WHEN SQLSTATE 'P0001' THEN
    IF SQLERRM <> 'INVALID_SHARE_TOKEN' THEN RAISE; END IF;
  END;

  -- Both public-facing RPCs remain SECURITY DEFINER but service-role only.
  SELECT pg_get_userbyid(p.proowner), p.proconfig
    INTO v_owner, v_config
  FROM pg_proc p
  WHERE p.oid = 'public.powerhub_subscriber_portal_invoice(text,text,text,text)'::regprocedure;
  IF v_owner <> 'postgres'
     OR NOT ('search_path=""' = ANY(coalesce(v_config, ARRAY[]::text[])))
     OR NOT (SELECT prosecdef FROM pg_proc WHERE oid = 'public.powerhub_subscriber_portal_invoice(text,text,text,text)'::regprocedure)
     OR has_function_privilege('anon', 'public.powerhub_subscriber_portal_invoice(text,text,text,text)', 'EXECUTE')
     OR has_function_privilege('authenticated', 'public.powerhub_subscriber_portal_invoice(text,text,text,text)', 'EXECUTE')
     OR NOT has_function_privilege('service_role', 'public.powerhub_subscriber_portal_invoice(text,text,text,text)', 'EXECUTE') THEN
    RAISE EXCEPTION 'PORTAL_INVOICE_RPC_ACL_ASSERTION_FAILED';
  END IF;

  SELECT pg_get_userbyid(p.proowner), p.proconfig
    INTO v_owner, v_config
  FROM pg_proc p
  WHERE p.oid = 'public.powerhub_create_portal_invoice_share_link(text,text,text,text,text,text)'::regprocedure;
  IF v_owner <> 'postgres'
     OR NOT ('search_path=""' = ANY(coalesce(v_config, ARRAY[]::text[])))
     OR NOT (SELECT prosecdef FROM pg_proc WHERE oid = 'public.powerhub_create_portal_invoice_share_link(text,text,text,text,text,text)'::regprocedure)
     OR has_function_privilege('anon', 'public.powerhub_create_portal_invoice_share_link(text,text,text,text,text,text)', 'EXECUTE')
     OR has_function_privilege('authenticated', 'public.powerhub_create_portal_invoice_share_link(text,text,text,text,text,text)', 'EXECUTE')
     OR NOT has_function_privilege('service_role', 'public.powerhub_create_portal_invoice_share_link(text,text,text,text,text,text)', 'EXECUTE') THEN
    RAISE EXCEPTION 'PORTAL_SHARE_RPC_ACL_ASSERTION_FAILED';
  END IF;
END
