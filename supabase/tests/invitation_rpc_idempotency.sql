-- Two actual PostgreSQL sessions race for the same platform invitation key.
do $platform_invitation_concurrency$
declare
  v_operation_id text := 'platform-op-concurrent-001';
  v_lock_key bigint;
  v_sql text;
  v_waiting integer := 0;
  v_attempt integer;
  v_a record;
  v_b record;
  v_count integer;
  v_audit_count integer;
begin
  v_lock_key := pg_catalog.hashtextextended('platform-access-invite:'||v_operation_id,0);
  perform pg_advisory_lock(v_lock_key);

  perform dblink_connect(
    'platform_invite_parallel_a',
    'host=/var/run/postgresql dbname='||current_database()||
    ' user='||current_user||' application_name=platform_invite_parallel_a'
  );
  perform dblink_connect(
    'platform_invite_parallel_b',
    'host=/var/run/postgresql dbname='||current_database()||
    ' user='||current_user||' application_name=platform_invite_parallel_b'
  );

  v_sql := format(
    'select id,email,platform_role,status,expires_at,replayed '||
    'from public.powerhub_admin_invite_platform_access(1,%L,%L,%L,now()+interval ''2 days'',%L,%L)',
    'concurrent-platform@example.test','platform_admin',repeat('c',64),
    v_operation_id,'platform-concurrent-fingerprint'
  );

  if dblink_send_query('platform_invite_parallel_a',v_sql)<>1
     or dblink_send_query('platform_invite_parallel_b',v_sql)<>1 then
    raise exception 'PLATFORM_INVITATION_CONCURRENT_DISPATCH_FAILED';
  end if;

  for v_attempt in 1..100 loop
    select count(*)::integer into v_waiting
    from pg_stat_activity
    where application_name in ('platform_invite_parallel_a','platform_invite_parallel_b')
      and wait_event_type='Lock';
    exit when v_waiting=2;
    perform pg_sleep(0.05);
  end loop;

  if v_waiting<>2 then
    perform pg_advisory_unlock(v_lock_key);
    raise exception 'PLATFORM_INVITATION_CALLS_DID_NOT_REACH_LOCK waiters=%',v_waiting;
  end if;

  perform pg_advisory_unlock(v_lock_key);

  select * into v_a
  from dblink_get_result('platform_invite_parallel_a') as result(
    id bigint,email text,platform_role text,status text,expires_at timestamptz,replayed boolean
  );
  select * into v_b
  from dblink_get_result('platform_invite_parallel_b') as result(
    id bigint,email text,platform_role text,status text,expires_at timestamptz,replayed boolean
  );

  perform dblink_disconnect('platform_invite_parallel_a');
  perform dblink_disconnect('platform_invite_parallel_b');

  if v_a.id<>v_b.id or v_a.email<>'concurrent-platform@example.test'
     or v_b.email<>'concurrent-platform@example.test'
     or v_a.replayed=v_b.replayed then
    raise exception 'PLATFORM_INVITATION_CONCURRENT_REPLAY_MISMATCH a=% b=%',
      row_to_json(v_a),row_to_json(v_b);
  end if;

  select count(*) into v_count from public.platform_access_invitations
  where client_operation_id=v_operation_id;
  select count(*) into v_audit_count from public.platform_security_events
  where metadata->>'clientOperationId'=v_operation_id;
  if v_count<>1 or v_audit_count<>1 then
    raise exception 'PLATFORM_INVITATION_CONCURRENT_DUPLICATION rows=% audit=%',v_count,v_audit_count;
  end if;
end;
$platform_invitation_concurrency$;

