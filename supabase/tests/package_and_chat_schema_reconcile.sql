DECLARE v_result record; v_count integer;
BEGIN
 IF (SELECT package_code FROM public.tenant_subscriptions WHERE id=1)<>'basic'
    OR (SELECT package_code FROM public.tenants WHERE id=1)<>'basic' THEN
   RAISE EXCEPTION 'PACKAGE_RECONCILE_LEGACY_PLAN_BACKFILL_FAILED';
 END IF;
 IF (SELECT current_package_code FROM public.subscription_upgrade_requests WHERE id=1)<>'basic'
    OR (SELECT requested_package_code FROM public.subscription_upgrade_requests WHERE id=1)<>'professional' THEN
   RAISE EXCEPTION 'PACKAGE_RECONCILE_UPGRADE_REQUEST_RENAME_FAILED';
 END IF;
 IF NOT (SELECT is_enabled FROM public.platform_settings WHERE setting_key='subscription_package_catalog') THEN
   RAISE EXCEPTION 'PACKAGE_RECONCILE_CATALOG_DISABLED';
 END IF;
 IF public.powerhub_catalog_package('basic')->>'code'<>'basic'
    OR NOT public.powerhub_validate_package_code('professional') THEN
   RAISE EXCEPTION 'PACKAGE_RECONCILE_CATALOG_RPC_FAILED';
 END IF;
 IF pg_get_function_result('public.powerhub_admin_subscription_upgrade_requests()'::regprocedure)
    NOT LIKE '%current_package_code text, requested_package_code text%' THEN
   RAISE EXCEPTION 'PACKAGE_RECONCILE_ADMIN_LIST_OUT_CONTRACT_FAILED';
 END IF;
 IF pg_get_function_result('public.powerhub_admin_review_subscription_upgrade_request(bigint,bigint,text,text)'::regprocedure)
    NOT LIKE '%package_code text, replayed boolean%' THEN
   RAISE EXCEPTION 'PACKAGE_RECONCILE_ADMIN_REVIEW_OUT_CONTRACT_FAILED';
 END IF;
 IF has_function_privilege('anon','public.powerhub_admin_subscription_upgrade_requests()','EXECUTE')
    OR has_function_privilege('authenticated','public.powerhub_admin_review_subscription_upgrade_request(bigint,bigint,text,text)','EXECUTE')
    OR NOT has_function_privilege('service_role','public.powerhub_admin_review_subscription_upgrade_request(bigint,bigint,text,text)','EXECUTE') THEN
   RAISE EXCEPTION 'PACKAGE_RECONCILE_SERVER_RPC_ACL_FAILED';
 END IF;
 IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='chat_knowledge_articles' AND column_name='search_aliases')
    OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='chat_knowledge_articles' AND column_name='audience')
    OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='chat_knowledge_articles' AND column_name='source') THEN
   RAISE EXCEPTION 'PACKAGE_RECONCILE_CHAT_KNOWLEDGE_COLUMNS_MISSING';
 END IF;
 SELECT count(*) INTO v_count FROM public.subscription_upgrade_requests;
 IF v_count<>1 THEN RAISE EXCEPTION 'PACKAGE_RECONCILE_EXISTING_REQUEST_ROWS_CHANGED'; END IF;
