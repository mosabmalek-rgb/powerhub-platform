CREATE OR REPLACE FUNCTION private.chat_rls_can_select_conversation(
  p_conversation_id bigint,
  p_tenant_id bigint
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
  SELECT EXISTS (
    SELECT 1
    FROM public.chat_conversations c
    JOIN public.chat_participants cp
      ON cp.conversation_id = c.id
     AND cp.tenant_id = c.tenant_id
    WHERE c.id = p_conversation_id
      AND c.tenant_id = p_tenant_id
      AND cp.user_id = nullif(current_setting('app.user_id', true), '')::bigint
      AND cp.left_at IS NULL
      AND p_tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint
  );
$function$;

ALTER FUNCTION private.chat_rls_can_select_conversation(bigint, bigint) OWNER TO postgres;

ALTER TABLE public.chat_message_attachments ENABLE ROW LEVEL SECURITY;
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;

CREATE POLICY chat_attachments_select_authorized_conversation
ON public.chat_message_attachments
FOR SELECT
TO authenticated
USING (private.chat_rls_can_select_conversation(conversation_id, tenant_id));

CREATE POLICY chat_storage_select_authorized_attachment
ON storage.objects
FOR SELECT
TO authenticated
USING (
  bucket_id = 'powerhub-private'
  AND EXISTS (
    SELECT 1
    FROM public.chat_message_attachments a
    WHERE a.storage_bucket = storage.objects.bucket_id
      AND a.storage_path = storage.objects.name
      AND private.chat_rls_can_select_conversation(a.conversation_id, a.tenant_id)
  )
);

GRANT USAGE ON SCHEMA storage, private, public TO anon, authenticated, service_role;
GRANT SELECT ON public.chat_message_attachments TO anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON storage.objects TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE storage.objects_id_seq TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION private.chat_rls_can_select_conversation(bigint, bigint) TO authenticated;

-- User 100, member only of tenant 10, can see exactly tenant 10's chat file.
SET LOCAL ROLE authenticated;
SELECT set_config('app.user_id', '100', true);
SELECT set_config('app.tenant_id', '10', true);
DO $tenant_a$
DECLARE v_count bigint;
BEGIN
  SELECT count(*) INTO v_count FROM storage.objects;
  IF v_count <> 1 THEN
    RAISE EXCEPTION 'TENANT_A_STORAGE_SCOPE_MISMATCH: expected 1 object, got %', v_count;
  END IF;
END
$tenant_a$;

-- Changing only the claimed tenant context cannot expose another tenant's file.
SELECT set_config('app.tenant_id', '20', true);
DO $cross_tenant$
DECLARE v_count bigint;
BEGIN
  SELECT count(*) INTO v_count FROM storage.objects;
  IF v_count <> 0 THEN
    RAISE EXCEPTION 'CROSS_TENANT_STORAGE_ACCESS: expected 0 objects, got %', v_count;
  END IF;
END
$cross_tenant$;

-- The authenticated browser role cannot insert objects directly.
DO $write_denied$
BEGIN
  BEGIN
    INSERT INTO storage.objects(bucket_id, name)
    VALUES ('powerhub-private', 'chat/10/1000/5000/forged.jpg');
    RAISE EXCEPTION 'DIRECT_STORAGE_INSERT_UNEXPECTEDLY_ALLOWED';
  EXCEPTION
    WHEN insufficient_privilege THEN NULL;
  END;
END
$write_denied$;

-- No UPDATE or DELETE policy means these operations affect zero objects.
SELECT set_config('app.tenant_id', '10', true);
DO $mutations$
DECLARE v_count bigint;
BEGIN
  UPDATE storage.objects
     SET name = 'chat/10/1000/5000/overwritten.jpg'
   WHERE bucket_id = 'powerhub-private'
     AND name = 'chat/10/1000/5000/tenant-a.jpg';
  GET DIAGNOSTICS v_count = ROW_COUNT;
  IF v_count <> 0 THEN
    RAISE EXCEPTION 'DIRECT_STORAGE_UPDATE_UNEXPECTEDLY_ALLOWED';
  END IF;

  DELETE FROM storage.objects
   WHERE bucket_id = 'powerhub-private'
     AND name = 'chat/10/1000/5000/tenant-a.jpg';
  GET DIAGNOSTICS v_count = ROW_COUNT;
  IF v_count <> 0 THEN
    RAISE EXCEPTION 'DIRECT_STORAGE_DELETE_UNEXPECTEDLY_ALLOWED';
  END IF;
END
$mutations$;

RESET ROLE;

