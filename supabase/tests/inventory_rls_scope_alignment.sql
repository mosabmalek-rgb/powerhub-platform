do $assert_policy_acl$
declare v_table text; v_policy text;
begin
  foreach v_table in array array['account_transactions','audit_logs','company_accounts','expenses','generators','meter_readings'] loop
    v_policy := case v_table
      when 'account_transactions' then 'account_transactions_tenant_isolation'
      when 'audit_logs' then 'audit_logs_tenant_isolation'
      when 'company_accounts' then 'company_accounts_tenant_isolation'
      when 'expenses' then 'expenses_tenant_isolation'
      when 'generators' then 'generators_tenant_isolation'
      else 'meter_readings_tenant_isolation'
    end;
    if not exists(select 1 from pg_policies p where p.schemaname='public' and p.tablename=v_table and p.policyname=v_policy and p.roles='{authenticated}' and p.cmd='ALL') then
      raise exception 'POLICY_NOT_AUTHENTICATED_ONLY_OR_MISSING_ON_%',v_table;
    end if;
    if not has_table_privilege('anon',format('public.%I',v_table),'SELECT') or not has_table_privilege('authenticated',format('public.%I',v_table),'SELECT') then
      raise exception 'READ_GRANT_REMOVED_ON_%',v_table;
    end if;
    foreach v_policy in array array['INSERT','UPDATE','DELETE','TRUNCATE'] loop
      if has_table_privilege('anon',format('public.%I',v_table),v_policy) or has_table_privilege('authenticated',format('public.%I',v_table),v_policy) then
        raise exception 'DIRECT_DML_REMAINS_ON_%',v_table;
      end if;
      if not has_table_privilege('service_role',format('public.%I',v_table),v_policy) then
        raise exception 'SERVICE_ROLE_DML_REMOVED_ON_%',v_table;
      end if;
    end loop;
  end loop;
  if has_function_privilege('anon','powerhub_private.current_tenant_ids()','EXECUTE') or not has_function_privilege('authenticated','powerhub_private.current_tenant_ids()','EXECUTE') then
    raise exception 'CURRENT_TENANT_IDS_HELPER_ACL_FAILED';
  end if;
  if has_function_privilege('anon','powerhub_private.is_platform_user()','EXECUTE') or not has_function_privilege('authenticated','powerhub_private.is_platform_user()','EXECUTE') then
    raise exception 'PLATFORM_USER_HELPER_ACL_FAILED';
  end if;
  if has_function_privilege('anon','powerhub_private.has_tenant_access(bigint)','EXECUTE') or not has_function_privilege('authenticated','powerhub_private.has_tenant_access(bigint)','EXECUTE') then
    raise exception 'TENANT_ACCESS_HELPER_ACL_FAILED';
  end if;
  if has_function_privilege('anon','powerhub_private.is_platform_admin()','EXECUTE') or not has_function_privilege('authenticated','powerhub_private.is_platform_admin()','EXECUTE') then
    raise exception 'PLATFORM_ADMIN_HELPER_ACL_FAILED';
  end if;
end
