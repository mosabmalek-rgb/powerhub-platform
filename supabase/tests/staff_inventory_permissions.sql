create table public.tenants (id bigint primary key, name text not null);
create table public.users (
  id bigint primary key,
  name text,
  role text not null default 'user',
  platform_role text,
  account_status text not null default 'active'
);
create table public.sites (
  id bigint primary key,
  tenant_id bigint not null references public.tenants(id),
  name text not null
);
create table public.custom_permission_roles (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id),
  permissions jsonb not null default '[]'::jsonb,
  is_active boolean not null default true
);
create table public.staff_profiles (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  tenant_id bigint references public.tenants(id) on delete cascade,
  site_id bigint references public.sites(id) on delete cascade,
  role text not null check (role in ('owner','manager','accountant','collector','technician','viewer')),
  custom_role_id bigint references public.custom_permission_roles(id) on delete set null,
  permissions jsonb,
  suspension_started_at timestamptz,
  suspension_ends_at timestamptz,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id,site_id,role)
);
create table public.platform_role_policies (
  id bigint generated by default as identity primary key,
  role text not null check (role in ('owner','manager','accountant','collector','technician','viewer')),
  capability text not null check (capability in (
    'manageSubscribers','manageGenerators','recordReadings','accessFieldApp','approveReadings',
    'manageTariffs','issueInvoices','collectPayments','approvePaymentDocumentation',
    'manageExpenses','managePayroll','manageTeam','manageMessaging','viewAudit'
  )),
  is_allowed boolean not null default true,
  updated_by_user_id bigint references public.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  unique (role,capability)
);

