do $test_existing$
declare
  v_rows integer;
  v_before integer;
  v_after integer;
begin
  select count(*) into v_before from public.notification_messages;
  select count(*) into v_rows
  from public.powerhub_queue_selected_invoice_sms(1,10,20,array[101,102,103,104,105,106,107]::bigint[])
  where queued = false;
  if v_rows <> 7 then
    raise exception 'existing invoice SMS rows were not all preserved: expected 7, got %', v_rows;
  end if;
  select count(*) into v_after from public.notification_messages;
  if v_after <> v_before then
    raise exception 'ordinary bulk queue unexpectedly inserted/reset a notification';
  end if;
  if exists (
    select 1
    from public.notification_messages n
    join public.invoices i on i.id=n.invoice_id
    where n.payload->>'sentinel' <> case n.status
      when 'pending' then 'pending-not-reset'
      when 'processing' then 'processing-not-reset'
      when 'submitted' then 'submitted-not-reset'
      when 'delivered' then 'delivered-not-reset'
      when 'read' then 'read-not-reset'
      when 'failed' then 'failed-not-reset'
      when 'needs_review' then 'review-not-reset'
    end
  ) then
    raise exception 'existing notification payload changed during ordinary queueing';
  end if;
  if has_function_privilege('anon','public.powerhub_queue_selected_invoice_sms(bigint,bigint,bigint,bigint[])','EXECUTE')
     or has_function_privilege('authenticated','public.powerhub_queue_selected_invoice_sms(bigint,bigint,bigint,bigint[])','EXECUTE')
     or not has_function_privilege('service_role','public.powerhub_queue_selected_invoice_sms(bigint,bigint,bigint,bigint[])','EXECUTE') then
    raise exception 'queue RPC grants are incorrect';
  end if;
end
$test_existing$;

do $test_new_queue$
declare
  v_notification_id bigint;
  v_invoice_id bigint;
  v_queued boolean;
  v_message_count integer;
  v_rendered text;
begin
  select notification_id, invoice_id, queued
    into v_notification_id, v_invoice_id, v_queued
  from public.powerhub_queue_selected_invoice_sms(1,10,20,array[110]::bigint[]);
  if v_invoice_id <> 110 or v_queued is not true then
    raise exception 'missing SMS row was not queued: invoice %, queued %', v_invoice_id, v_queued;
  end if;

  select count(*), max(payload->>'renderedText')
    into v_message_count, v_rendered
  from public.notification_messages
  where invoice_id=110 and tenant_id=10 and channel='sms' and event_type='invoice_issued';
  if v_message_count <> 1 then
    raise exception 'expected exactly one queued SMS row for invoice 110, got %', v_message_count;
  end if;
  if v_rendered <> 'إلى مشترك اختبار|PH-110|10.0|2026-09|10.0|2026-10-20|90|100|10|30.0' then
    raise exception 'unified invoice template variables were not rendered correctly: %', v_rendered;
  end if;

  select notification_id, invoice_id, queued
    into v_notification_id, v_invoice_id, v_queued
  from public.powerhub_queue_selected_invoice_sms(1,10,20,array[110]::bigint[]);
  if v_invoice_id <> 110 or v_queued is not false then
    raise exception 'second queue call was not treated as already queued: invoice %, queued %', v_invoice_id, v_queued;
  end if;

  select count(*) into v_message_count
  from public.notification_messages
  where invoice_id=110 and tenant_id=10 and channel='sms' and event_type='invoice_issued';
  if v_message_count <> 1 then
    raise exception 'repeated queue call duplicated invoice SMS: % rows', v_message_count;
  end if;
end
$test_new_queue$;

