CREATE OR REPLACE FUNCTION private.powerhub_current_user_id()
RETURNS bigint
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=''
AS $function$
  SELECT u.id FROM public.users u WHERE u.auth_user_id=auth.uid() LIMIT 1
$function$;
ALTER FUNCTION private.powerhub_current_user_id() OWNER TO postgres;

CREATE OR REPLACE FUNCTION private.powerhub_is_platform_admin()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=''
AS $function$
  SELECT EXISTS(
    SELECT 1 FROM public.users u
    WHERE u.id=private.powerhub_current_user_id()
      AND u.platform_role IN ('platform_owner','platform_admin','finance_admin')
      AND u.account_status='active'
  )
$function$;
ALTER FUNCTION private.powerhub_is_platform_admin() OWNER TO postgres;

