-- Stand-in for the shared trigger installed by the already-tested Adaptive Delta
-- Realtime migration. It keeps the same opaque payload and topic fan-out contract.
CREATE OR REPLACE FUNCTION private.powerhub_broadcast_delta_scope_revision()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path=''
AS $function$
BEGIN
  IF TG_OP='UPDATE'
     AND NEW.last_cursor IS NOT DISTINCT FROM OLD.last_cursor
     AND NEW.retained_from_cursor IS NOT DISTINCT FROM OLD.retained_from_cursor THEN
    RETURN NEW;
  END IF;
  INSERT INTO realtime.messages(payload,event,topic,private)
  VALUES
    ('{"version":1}'::jsonb,'powerhub_delta_changed',
     'powerhub:tenant:'||NEW.tenant_id::text||':site:'||NEW.site_id::text,true),
    ('{"version":1}'::jsonb,'powerhub_delta_changed',
     'powerhub:tenant:'||NEW.tenant_id::text||':all',true);
  RETURN NEW;
END
$function$;
ALTER FUNCTION private.powerhub_broadcast_delta_scope_revision() OWNER TO postgres;
REVOKE ALL ON FUNCTION private.powerhub_broadcast_delta_scope_revision() FROM PUBLIC,anon,authenticated;

CREATE TRIGGER powerhub_sync_scope_state_broadcast_delta
AFTER INSERT OR UPDATE OF last_cursor,retained_from_cursor
ON public.powerhub_sync_scope_state
FOR EACH ROW EXECUTE FUNCTION private.powerhub_broadcast_delta_scope_revision();

