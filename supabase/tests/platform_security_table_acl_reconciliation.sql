DO $acl_contract$
DECLARE
  v_table text;
  v_policy_count integer;
BEGIN
  FOREACH v_table IN ARRAY ARRAY['platform_security_events','platform_security_settings'] LOOP
    IF has_table_privilege('anon',format('public.%I',v_table),'SELECT')
       OR has_table_privilege('anon',format('public.%I',v_table),'INSERT')
       OR has_table_privilege('authenticated',format('public.%I',v_table),'INSERT')
       OR has_table_privilege('authenticated',format('public.%I',v_table),'UPDATE')
       OR has_table_privilege('authenticated',format('public.%I',v_table),'DELETE') THEN
      RAISE EXCEPTION
        'PLATFORM_SECURITY_TABLE_CLIENT_GRANTS_NOT_RESTRICTED: table=% anon_select=% anon_insert=% auth_insert=% auth_update=% auth_delete=%',
        v_table,
        has_table_privilege('anon',format('public.%I',v_table),'SELECT'),
        has_table_privilege('anon',format('public.%I',v_table),'INSERT'),
        has_table_privilege('authenticated',format('public.%I',v_table),'INSERT'),
        has_table_privilege('authenticated',format('public.%I',v_table),'UPDATE'),
        has_table_privilege('authenticated',format('public.%I',v_table),'DELETE');
    END IF;
    IF NOT has_table_privilege('authenticated',format('public.%I',v_table),'SELECT')
       OR NOT has_table_privilege('service_role',format('public.%I',v_table),'SELECT')
       OR NOT has_table_privilege('service_role',format('public.%I',v_table),'INSERT')
       OR NOT has_table_privilege('service_role',format('public.%I',v_table),'UPDATE')
       OR NOT has_table_privilege('service_role',format('public.%I',v_table),'DELETE') THEN
      RAISE EXCEPTION 'PLATFORM_SECURITY_TABLE_SERVER_GRANTS_MISSING: %',v_table;
    END IF;
    SELECT count(*) INTO v_policy_count FROM pg_policies
      WHERE schemaname='public' AND tablename=v_table;
    IF v_policy_count <> 2 THEN
      RAISE EXCEPTION 'PLATFORM_SECURITY_TABLE_POLICY_COUNT_MISMATCH: % (% policies)',v_table,v_policy_count;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public'
        AND tablename=v_table AND permissive='RESTRICTIVE'
        AND qual LIKE '%powerhub_is_platform_management_admin%'
        AND with_check LIKE '%powerhub_is_platform_management_admin%') THEN
      RAISE EXCEPTION 'PLATFORM_SECURITY_TABLE_RESTRICTIVE_GUARD_MISSING: %',v_table;
    END IF;
  END LOOP;
END
$acl_contract$;

