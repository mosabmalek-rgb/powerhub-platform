CREATE OR REPLACE FUNCTION powerhub_private.current_user_id()
RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER SET search_path=''
AS $function$
  SELECT u.id FROM public.users u WHERE u.auth_user_id=auth.uid() LIMIT 1
$function$;
