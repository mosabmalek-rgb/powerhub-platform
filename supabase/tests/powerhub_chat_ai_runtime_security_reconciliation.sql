CREATE OR REPLACE FUNCTION private.chat_feature_enabled_for_tenant(p_tenant_id bigint,p_conversation_type text)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=''
AS $function$
  SELECT coalesce((
    SELECT fc.is_active
    FROM public.feature_catalog fc
    WHERE fc.feature_key = CASE p_conversation_type
      WHEN 'assistant' THEN 'powerhub_ai_assistant'
      WHEN 'support' THEN 'support_chat'
      ELSE NULL
    END
  ),false)
$function$;

CREATE OR REPLACE FUNCTION private.chat_rls_can_select_conversation(p_conversation_id bigint,p_tenant_id bigint)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=''
AS $function$
  SELECT EXISTS (
    SELECT 1
    FROM public.chat_conversations c
    JOIN public.chat_participants cp
      ON cp.conversation_id=c.id AND cp.tenant_id=c.tenant_id
    JOIN public.tenant_members tm
      ON tm.tenant_id=c.tenant_id AND tm.user_id=cp.user_id
    WHERE c.id=p_conversation_id
      AND c.tenant_id=p_tenant_id
      AND cp.user_id=powerhub_private.current_user_id()
      AND cp.left_at IS NULL
      AND tm.is_active=true
      AND tm.membership_status='active'
      AND (tm.expires_at IS NULL OR tm.expires_at>now())
      AND private.chat_feature_enabled_for_tenant(c.tenant_id,c.conversation_type)
  )
$function$;
REVOKE ALL ON FUNCTION private.chat_rls_can_select_conversation(bigint,bigint) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION private.chat_rls_can_select_conversation(bigint,bigint) TO authenticated;

