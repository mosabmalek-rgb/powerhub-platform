   WHERE auth_user_id = '8a594902-3521-4276-9bed-f6f53c8ee838';
  IF NOT FOUND THEN RAISE EXCEPTION 'BOOTSTRAP_TARGET_MISSING'; END IF;
  IF v_target.role <> 'admin'
     OR v_target.platform_role <> 'platform_admin'
     OR v_target.account_status <> 'active' THEN
    RAISE EXCEPTION 'BOOTSTRAP_ROLE_CONTRACT_FAILED';
  END IF;
  IF v_target.must_change_password IS DISTINCT FROM false
     OR v_target.temporary_password_issued_at IS NOT NULL THEN
    RAISE EXCEPTION 'BOOTSTRAP_CHANGED_PASSWORD_FLAGS';
  END IF;
  IF (SELECT role FROM public.users WHERE auth_user_id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa') <> 'user' THEN
    RAISE EXCEPTION 'BOOTSTRAP_CHANGED_UNRELATED_USER';
