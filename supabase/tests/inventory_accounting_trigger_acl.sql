DO $assert_locked_period$
BEGIN
  BEGIN
    UPDATE public.inventory_items SET accounting_treatment='capital_asset' WHERE id=1;
    RAISE EXCEPTION 'INVENTORY_LOCKED_ACCOUNTING_CHANGE_WAS_ALLOWED';
  EXCEPTION WHEN SQLSTATE 'P0001' THEN
    IF SQLERRM<>'FINANCIAL_PERIOD_LOCKED' THEN RAISE; END IF;
  END;
  IF (SELECT accounting_treatment FROM public.inventory_items WHERE id=1)<>'expense_on_issue' THEN
    RAISE EXCEPTION 'INVENTORY_LOCKED_ACCOUNTING_VALUE_CHANGED';
  END IF;
END
$assert_locked_period$;

