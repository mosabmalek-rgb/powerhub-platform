CREATE OR REPLACE FUNCTION public.b5_expense_one(p_worker int,p_iteration int)
RETURNS text LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public,pg_temp
AS $do$
DECLARE v_k integer;v_category text;v_amount numeric;v_id bigint;v_tx bigint;v_replay boolean;
 v_key uuid;ts timestamptz;
BEGIN
 IF current_database()<>'powerhub_b5_synthetic_expense_test' OR
 p_worker NOT BETWEEN 1 AND 4 OR p_iteration NOT BETWEEN 1 AND 250
 THEN RAISE EXCEPTION 'B5_EXPENSE_BAD_SCOPE'; END IF;
 v_k:=(p_worker-1)*250+p_iteration;
 IF v_k=1000 THEN v_k:=1; END IF;
 v_category:=CASE WHEN v_k%10<4 THEN 'fuel' WHEN v_k%10<7 THEN 'maintenance'
 WHEN v_k%10=7 THEN 'parts' WHEN v_k%10=8 THEN 'transport' ELSE 'other' END;
 v_amount:=CASE WHEN v_k IN (100,300,500,700,900) THEN 1.5 ELSE 1 END;
 v_key:=md5('B5-expense:'||v_k)::uuid;ts:=clock_timestamp();
 SELECT expense_id,transaction_id,replayed INTO v_id,v_tx,v_replay
 FROM public.powerhub_create_expense_classified_idempotent(
   1,10,7,15,301,v_category,
   'B5 synthetic expense number '||v_k,v_amount,'B5-EXP-'||v_k,v_key,'operating');
 IF v_id IS NULL OR v_tx IS NULL OR v_replay IS DISTINCT FROM
    (p_worker=4 AND p_iteration=250)
 THEN RAISE EXCEPTION 'B5_EXPENSE_RESULT_OR_REPLAY_DRIFT'; END IF;
 INSERT INTO public.b5_expense_samples(worker,iteration,backend_pid,replay,expense_id,
   transaction_id,category,elapsed_ms)
 VALUES(p_worker,p_iteration,pg_backend_pid(),v_replay,v_id,v_tx,v_category,
   round(extract(epoch from clock_timestamp()-ts)::numeric*1000,3));
 RETURN 'EXPENSE_OK';
END $do$;
REVOKE ALL ON FUNCTION public.b5_expense_one(integer,integer) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.b5_expense_one(integer,integer) TO service_role;
