do $test_package_catalog$
declare
  v_plan_id bigint;
  v_price numeric;
  v_currency text;
  v_qty integer;
  v_active boolean;
begin
  select id into v_plan_id
    from public.powerhub_admin_create_sms_credit_package(1,'sms-1000','حزمة 1000','اختبار',1000,12,' ils ',true);
  select price_amount,currency,included_messages,is_active into v_price,v_currency,v_qty,v_active
    from public.platform_sms_plans where id=v_plan_id;
  if v_price<>12 or v_currency<>'ILS' or v_qty<>1000 or not v_active then
    raise exception 'SMS_PACKAGE_CREATE_DATA_WRONG';
  end if;

  perform * from public.powerhub_admin_update_sms_credit_package(
    1,v_plan_id,p_name=>'حزمة 1500',p_messages=>1500
  );
  select price_amount,currency,included_messages into v_price,v_currency,v_qty
    from public.platform_sms_plans where id=v_plan_id;
  if v_price<>12 or v_currency<>'ILS' or v_qty<>1500 then
    raise exception 'SMS_PACKAGE_UPDATE_RESET_UNCHANGED_PRICE_OR_CURRENCY';
  end if;

  if (select count(*) from public.platform_security_events
      where metadata->>'action' in ('sms_credit_package_created','sms_credit_package_updated'))<>2 then
    raise exception 'SMS_PACKAGE_SECURITY_AUDIT_MISSING';
  end if;

  begin
    perform * from public.powerhub_admin_create_sms_credit_package(3,'forbidden','ممنوع',null,100,1,'ILS',true);
    raise exception 'UNPRIVILEGED_USER_CREATED_SMS_PACKAGE';
  exception when others then
    if sqlerrm='UNPRIVILEGED_USER_CREATED_SMS_PACKAGE' then raise; end if;
    if sqlerrm<>'FORBIDDEN_PLATFORM_ROLE' then raise; end if;
  end;
end
