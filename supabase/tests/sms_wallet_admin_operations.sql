do $test_claim_balance_guards$
declare
  v_no_credit_id bigint;
  v_provider_limited_id bigint;
  v_unsubscribed_id bigint;
  v_legacy_first_id bigint;
  v_legacy_second_id bigint;
  v_claim_id bigint;
  v_segments integer;
  v_caught boolean;
  v_total bigint;
begin
  -- A previously credited wallet remains readable without an active subscription,
  -- but it must not authorize sending when subscription eligibility is absent.
  insert into public.subscribers(id,tenant_id,site_id,full_name,phone)
  values(1301,13,131,'مشترك بلا اشتراك نشط','+970599000013');

  -- Give this negative eligibility test a fully configured fake provider account,
  -- so it reaches the intended subscription guard instead of failing earlier on
  -- missing provider configuration. No network call is made by the claim RPC.
  insert into public.tenant_tweetsms_accounts(
    tenant_id,monthly_limit,is_active,api_endpoint,credential_ciphertext,credential_iv,sender_name
  ) values(13,100,true,'https://invalid.example.test/sms','fake-ciphertext','fake-iv','TEST');

  -- An explicit tenant-level enable must never override the active-subscription
  -- requirement for SMS dispatch.
  insert into public.tenant_feature_controls(tenant_id,feature_key,status,limit_mode,manual_limit)
  values(13,'sms','enabled','manual',1000);

  insert into public.notification_messages(
    tenant_id,subscriber_id,channel,event_type,status,payload,recipient
  ) values(13,1301,'sms','invoice_issued','pending','{"renderedText":"inactive-subscription-test"}'::jsonb,'+970599000013')
  returning id into v_unsubscribed_id;

  select total_messages into v_total from public.powerhub_get_sms_quota(13);
  if v_total<>70 then raise exception 'WALLET_BALANCE_HIDDEN_WITHOUT_ACTIVE_SUBSCRIPTION'; end if;
  v_caught:=false;
  begin
    perform * from public.powerhub_claim_sms_notification(1,v_unsubscribed_id);
  exception when others then
    if sqlerrm='SMS_FEATURE_DISABLED' then v_caught:=true; else raise; end if;
  end;
  if not v_caught then raise exception 'SMS_SENT_WITHOUT_ACTIVE_SUBSCRIPTION'; end if;
  if (select status from public.notification_messages where id=v_unsubscribed_id)<>'pending' then
    raise exception 'INACTIVE_SUBSCRIPTION_CLAIM_MUTATED_MESSAGE';
  end if;

  -- All provider credentials are fake values in this disposable database. This
  -- invokes the SQL queue-claim RPC only; no provider/network call is performed.
  insert into public.tenant_subscriptions(tenant_id,package_code,status,ends_at,created_at)
  values(15,'basic','active',now()+interval '30 days',now());

  insert into public.subscribers(id,tenant_id,site_id,full_name,phone)
  values(1501,15,151,'مشترك بلا رصيد','+970599000015');

  insert into public.tenant_tweetsms_accounts(
    tenant_id,monthly_limit,is_active,api_endpoint,credential_ciphertext,credential_iv,sender_name
  ) values
    (10,4,true,'https://invalid.example.test/sms','fake-ciphertext','fake-iv','TEST'),
    (15,100,true,'https://invalid.example.test/sms','fake-ciphertext','fake-iv','TEST')
  on conflict(tenant_id) do update set
    monthly_limit=excluded.monthly_limit,is_active=excluded.is_active,
    api_endpoint=excluded.api_endpoint,credential_ciphertext=excluded.credential_ciphertext,
    credential_iv=excluded.credential_iv,sender_name=excluded.sender_name,
    sms_dispatch_lease_notification_id=null,sms_dispatch_lease_until=null;

  insert into public.notification_messages(
    tenant_id,subscriber_id,channel,event_type,status,payload,recipient
  ) values(15,1501,'sms','invoice_issued','pending','{"renderedText":"no-credit-test"}'::jsonb,'+970599000015')
  returning id into v_no_credit_id;

  v_caught:=false;
  begin
    perform * from public.powerhub_claim_sms_notification(1,v_no_credit_id);
  exception when others then
    if sqlerrm='SMS_WALLET_BALANCE_EXCEEDED' then v_caught:=true; else raise; end if;
  end;
  if not v_caught then raise exception 'SMS_WITHOUT_WALLET_CREDIT_WAS_CLAIMED'; end if;
  if (select status from public.notification_messages where id=v_no_credit_id)<>'pending' then
    raise exception 'FAILED_NO_CREDIT_CLAIM_MUTATED_MESSAGE';
  end if;

  -- Old queued messages are excluded until an actual provider request starts.
  -- Once one is sent, provider_request_started_at must charge the wallet even
  -- when created_at predates the accounting cutover.
  insert into public.tenant_sms_recharge_ledger(
    tenant_id,provider_mode,status,requested_messages,credited_messages,idempotency_key,
    requested_by_user_id,processed_by_user_id,confirmed_at,note
  ) values(15,'manual','manual_confirmed',1,1,'30000000-0000-0000-0000-000000000001'::uuid,1,1,now(),'رصيد اختبار الرسالة القديمة');

  insert into public.notification_messages(
    tenant_id,subscriber_id,channel,event_type,status,payload,recipient,created_at
  ) values(15,1501,'sms','invoice_issued','pending','{"renderedText":"legacy-first"}'::jsonb,'+970599000015','2026-09-01T00:00:00Z')
  returning id into v_legacy_first_id;

  select notification_id,attempt_number into v_claim_id,v_segments
  from public.powerhub_claim_sms_notification(1,v_legacy_first_id);
  if v_claim_id<>v_legacy_first_id then raise exception 'LEGACY_FIRST_MESSAGE_NOT_CLAIMED'; end if;
  -- The disposable fixture has the claim RPC but intentionally does not import
  -- the worker lifecycle migrations. Mark the claimed row as provider-started and
  -- submitted directly; no external provider is called.
  update public.notification_messages
  set provider_request_started_at=now(),status='submitted',updated_at=now()
  where id=v_legacy_first_id and status='processing' and attempts=v_segments;
  if not found then raise exception 'LEGACY_FIRST_MESSAGE_NOT_MARKED_SUBMITTED'; end if;
  update public.tenant_tweetsms_accounts
  set sms_dispatch_lease_notification_id=null,sms_dispatch_lease_until=null
  where tenant_id=15 and sms_dispatch_lease_notification_id=v_legacy_first_id;

  insert into public.notification_messages(
    tenant_id,subscriber_id,channel,event_type,status,payload,recipient,created_at
  ) values(15,1501,'sms','invoice_issued','pending','{"renderedText":"legacy-second"}'::jsonb,'+970599000015','2026-09-02T00:00:00Z')
  returning id into v_legacy_second_id;

  v_caught:=false;
  begin
    perform * from public.powerhub_claim_sms_notification(1,v_legacy_second_id);
  exception when others then
    if sqlerrm='SMS_WALLET_BALANCE_EXCEEDED' then v_caught:=true; else raise; end if;
  end;
  if not v_caught then raise exception 'LEGACY_QUEUED_MESSAGE_BYPASSED_WALLET_AFTER_CUTOVER'; end if;
  if (select status from public.notification_messages where id=v_legacy_second_id)<>'pending' then
    raise exception 'LEGACY_WALLET_REJECTION_MUTATED_MESSAGE';
  end if;

  insert into public.notification_messages(
    tenant_id,subscriber_id,channel,event_type,status,payload,recipient
  ) values(10,1001,'sms','invoice_issued','pending','{"renderedText":"provider-limit-test"}'::jsonb,'+970599000001')
  returning id into v_provider_limited_id;

  v_caught:=false;
  begin
    perform * from public.powerhub_claim_sms_notification(1,v_provider_limited_id);
  exception when others then
    if sqlerrm='SMS_PROVIDER_MONTHLY_LIMIT_EXCEEDED' then v_caught:=true; else raise; end if;
  end;
  if not v_caught then raise exception 'SMS_PROVIDER_MONTHLY_LIMIT_WAS_BYPASSED'; end if;
  if (select status from public.notification_messages where id=v_provider_limited_id)<>'pending' then
    raise exception 'FAILED_PROVIDER_LIMIT_CLAIM_MUTATED_MESSAGE';
  end if;

  update public.tenant_tweetsms_accounts set monthly_limit=100 where tenant_id=10;
  select notification_id,segment_count into v_claim_id,v_segments
  from public.powerhub_claim_sms_notification(1,v_provider_limited_id);
  if v_claim_id<>v_provider_limited_id or v_segments<>1 then
    raise exception 'VALID_WALLET_CLAIM_RESULT_WRONG';
  end if;
  if (select status from public.notification_messages where id=v_provider_limited_id)<>'processing' then
    raise exception 'VALID_SMS_CLAIM_DID_NOT_MARK_PROCESSING';
  end if;
end
