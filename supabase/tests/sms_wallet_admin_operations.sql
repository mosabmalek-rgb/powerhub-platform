  select ledger_id into v_id
  from public.powerhub_admin_create_sms_recharge_request(1,10,100,'اختبار شحن', '10000000-0000-0000-0000-000000000001'::uuid);

  select id,status,credited_messages into v_retry_id,v_status,v_credit
  from public.tenant_sms_recharge_ledger where id=v_id;
  if v_status<>'pending' or v_credit<>0 then
    raise exception 'RECHARGE_REQUEST_GRANTED_CREDIT_BEFORE_CONFIRMATION';
  end if;

  select ledger_id into v_retry_id
  from public.powerhub_admin_create_sms_recharge_request(1,10,100,'إعادة المحاولة','10000000-0000-0000-0000-000000000001'::uuid);
  if v_retry_id<>v_id or (select count(*) from public.tenant_sms_recharge_ledger where tenant_id=10)<>1 then
    raise exception 'RECHARGE_IDEMPOTENCY_CREATED_DUPLICATE';
  end if;

  v_caught:=false;
  begin
    perform * from public.powerhub_admin_create_sms_recharge_request(1,10,200,'طلب إضافي','10000000-0000-0000-0000-000000000002'::uuid);
  exception when others then
    if sqlerrm='SMS_RECHARGE_REQUEST_PENDING' then v_caught:=true; else raise; end if;
  end;
  if not v_caught then raise exception 'DUPLICATE_PENDING_RECHARGE_ALLOWED'; end if;

  v_caught:=false;
  begin
    perform * from public.powerhub_admin_confirm_sms_recharge(1,v_id,'manual_confirmed',101,null,null,null);
  exception when others then
    if sqlerrm='SMS_RECHARGE_CREDIT_EXCEEDS_REQUEST' then v_caught:=true; else raise; end if;
  end;
  if not v_caught then raise exception 'RECHARGE_CONFIRMED_ABOVE_REQUESTED_QUANTITY'; end if;
  if (select status from public.tenant_sms_recharge_ledger where id=v_id)<>'pending'
     or (select credited_messages from public.tenant_sms_recharge_ledger where id=v_id)<>0 then
    raise exception 'INVALID_CREDIT_ATTEMPT_MUTATED_LEDGER';
  end if;

  select replayed into v_replayed
  from public.powerhub_admin_confirm_sms_recharge(1,v_id,'manual_confirmed',80,null,null,null);
  if v_replayed then raise exception 'FIRST_RECHARGE_CONFIRMATION_MARKED_AS_REPLAY'; end if;

  select status,credited_messages into v_status,v_credit
  from public.tenant_sms_recharge_ledger where id=v_id;
  if v_status<>'manual_confirmed' or v_credit<>80 then
    raise exception 'RECHARGE_CONFIRMATION_NOT_CREDITED';
  end if;

  select replayed into v_replayed
  from public.powerhub_admin_confirm_sms_recharge(1,v_id,'manual_confirmed',80,null,null,null);
  if not v_replayed then raise exception 'REPEATED_CONFIRMATION_NOT_IDEMPOTENT'; end if;

  -- Simulate a retry after the original response was lost and an administrator
  -- already confirmed the request. The original ledger row/state must be returned.
  select ledger_id,status into v_retry_id,v_status
  from public.powerhub_admin_create_sms_recharge_request(
    1,10,100,'إعادة المحاولة بعد الحسم','10000000-0000-0000-0000-000000000001'::uuid
  );
  if v_retry_id<>v_id or v_status<>'manual_confirmed' then
    raise exception 'FINALIZED_IDEMPOTENT_REQUEST_REPLAY_FAILED';
  end if;

  v_caught:=false;
  begin
    perform * from public.powerhub_admin_confirm_sms_recharge(1,v_id,'failed',0,null,null,'تعارض اختبار');
  exception when others then
    if sqlerrm='SMS_RECHARGE_ALREADY_FINALIZED' then v_caught:=true; else raise; end if;
  end;
  if not v_caught then raise exception 'FINALIZED_RECHARGE_ACCEPTED_CONFLICTING_STATUS'; end if;

  if (select sum(credited_messages) from public.tenant_sms_recharge_ledger where tenant_id=10)<>80 then
    raise exception 'RECHARGE_CREDITED_MORE_THAN_ONCE';
  end if;
  if (select count(*) from public.audit_logs where tenant_id=10)<>2 then
    raise exception 'RECHARGE_REQUEST_OR_CONFIRM_AUDIT_MISSING';
  end if;

  insert into public.notification_messages(tenant_id,subscriber_id,channel,event_type,status,segment_count,created_at,payload,recipient)
  values(10,1001,'sms','invoice_issued','delivered',4,now(),'{"renderedText":"مقاطع مستهلكة بعد التفعيل"}'::jsonb,'+970599000001');
  select total_messages,used_segments,remaining_messages into v_total,v_used,v_remaining
