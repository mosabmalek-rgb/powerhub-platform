-- Exercise the wallet accounting cutover rule: pre-existing tenants are seeded
-- at activation time; a new tenant uses the first subscription's created_at,
-- and later subscriptions must never reset that first timestamp.

insert into public.tenants(id,name,created_at) values(20,'مولد جديد','2026-09-01T00:00:00Z');
insert into public.tenant_subscriptions(tenant_id,created_at) values(20,'2026-09-10T00:00:00Z');
do $test_wallet_start$
declare
  v_start timestamptz;
  v_existing timestamptz;
begin
  select accounting_started_at into v_start from public.tenant_sms_wallets where tenant_id=20;
  if v_start<>'2026-09-10T00:00:00Z'::timestamptz then
    raise exception 'NEW_WALLET_NOT_ANCHORED_TO_FIRST_SUBSCRIPTION';
  end if;
  update public.tenant_subscriptions set created_at='2026-10-01T00:00:00Z' where tenant_id=20;
  if (select accounting_started_at from public.tenant_sms_wallets where tenant_id=20)<>v_start then
    raise exception 'RENEWAL_RESET_WALLET_ACCOUNTING_START';
  end if;
  select accounting_started_at into v_existing from public.tenant_sms_wallets where tenant_id=10;
  if v_existing<'2026-10-19T00:00:00Z'::timestamptz then
    raise exception 'EXISTING_WALLET_DID_NOT_START_AT_CUTOVER';
  end if;
end
