do $test_pending_and_idempotency$
declare
  v_id bigint;
  v_retry_id bigint;
  v_status text;
  v_credit integer;
  v_replayed boolean;
  v_caught boolean;
  v_total bigint;
  v_used bigint;
  v_remaining bigint;
