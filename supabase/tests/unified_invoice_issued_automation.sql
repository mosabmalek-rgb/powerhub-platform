create or replace function public.powerhub_format_message_amount(
  p_tenant_id bigint, p_site_id bigint, p_amount numeric
) returns text
language sql stable security definer set search_path=public,pg_temp
as $function$
  select case
    when p_amount is null then ''
    when exists (
      select 1 from public.site_billing_policies p
      where p.tenant_id=p_tenant_id and p.site_id=p_site_id
        and (coalesce(p.automatic_fraction_discount_enabled,false) or coalesce(p.fraction_carry_enabled,false))
    ) then trunc(p_amount,0)::text
    else round(p_amount,1)::text
  end;
$function$;

