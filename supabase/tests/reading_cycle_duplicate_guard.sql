do $test$
declare
  v_first_id bigint;
begin
  -- Different calendar days inside a single monthly cycle must conflict.
  insert into public.meter_readings (tenant_id, subscriber_id, reading_at)
  values (1, 101, '2026-11-03 10:00:00+02')
  returning id into v_first_id;

  begin
    insert into public.meter_readings (tenant_id, subscriber_id, reading_at)
    values (1, 101, '2026-11-24 10:00:00+02');
    raise exception 'expected cycle-wide duplicate rejection';
  exception when unique_violation then
    if sqlerrm <> 'READING_ALREADY_EXISTS_IN_CYCLE' then raise; end if;
  end;

  -- The next configured cycle is allowed for the same subscriber.
  insert into public.meter_readings (tenant_id, subscriber_id, reading_at)
  values (1, 101, '2026-12-01 10:00:00+02');

  -- A rejected reading does not occupy the cycle.
  insert into public.meter_readings (tenant_id, subscriber_id, reading_at, status)
  values (1, 102, '2026-11-02 10:00:00+02', 'rejected');
  insert into public.meter_readings (tenant_id, subscriber_id, reading_at, status)
  values (1, 102, '2026-11-19 10:00:00+02', 'pending_review');

  -- Opening baselines do not occupy a cycle, regardless of insertion order.
  insert into public.meter_readings (tenant_id, subscriber_id, reading_at, status, is_opening_baseline)
  values (1, 103, '2026-11-01 08:00:00+02', 'approved', true);
  insert into public.meter_readings (tenant_id, subscriber_id, reading_at, status)
  values (1, 103, '2026-11-07 10:00:00+02', 'pending_review');

  -- Updating a previously valid row into an occupied cycle must be rejected.
  insert into public.meter_readings (tenant_id, subscriber_id, reading_at)
  values
    (1, 104, '2026-10-05 10:00:00+02'),
    (1, 104, '2026-11-05 10:00:00+02');
  begin
    update public.meter_readings
       set reading_at = '2026-11-08 10:00:00+02'
     where tenant_id = 1 and subscriber_id = 104
       and reading_at = '2026-10-05 08:00:00+00';
    raise exception 'expected update into occupied cycle to be rejected';
  exception when unique_violation then
    if sqlerrm <> 'READING_ALREADY_EXISTS_IN_CYCLE' then raise; end if;
  end;

  -- Rejected -> pending transition is guarded, not just INSERT.
  insert into public.meter_readings (tenant_id, subscriber_id, reading_at, status)
  values
    (1, 105, '2026-11-02 10:00:00+02', 'rejected'),
    (1, 105, '2026-11-03 10:00:00+02', 'pending_review');
  begin
    update public.meter_readings
       set status = 'pending_review'
     where tenant_id = 1 and subscriber_id = 105
       and reading_at = '2026-11-02 08:00:00+00';
    raise exception 'expected rejected-to-pending transition to be rejected';
  exception when unique_violation then
    if sqlerrm <> 'READING_ALREADY_EXISTS_IN_CYCLE' then raise; end if;
  end;

  -- The same calendar dates in another tenant/site and subscriber stay isolated.
  insert into public.meter_readings (tenant_id, subscriber_id, reading_at)
  values (2, 201, '2026-11-03 10:00:00+02');

  -- Weekly cycles are evaluated by the configured Saturday anchor, not by day.
  insert into public.meter_readings (tenant_id, subscriber_id, reading_at)
  values (1, 112, '2026-11-07 10:00:00+02');
  begin
    insert into public.meter_readings (tenant_id, subscriber_id, reading_at)
    values (1, 112, '2026-11-12 10:00:00+02');
    raise exception 'expected weekly-cycle duplicate rejection';
  exception when unique_violation then
    if sqlerrm <> 'READING_ALREADY_EXISTS_IN_CYCLE' then raise; end if;
  end;

  -- Keep the database trigger inaccessible as a callable browser RPC.
  if has_function_privilege('anon', 'public.powerhub_enforce_single_reading_per_cycle()', 'EXECUTE')
     or has_function_privilege('authenticated', 'public.powerhub_enforce_single_reading_per_cycle()', 'EXECUTE')
     or not has_function_privilege('service_role', 'public.powerhub_enforce_single_reading_per_cycle()', 'EXECUTE') then
    raise exception 'reading-cycle trigger function ACL is incorrect';
  end if;
end
$test$;
