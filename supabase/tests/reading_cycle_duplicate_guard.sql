  tenant_id bigint not null,
  site_id bigint not null,
  cycle_type text not null,
  weekly_start_day integer not null,
  monthly_start_day integer not null,
  timezone text not null default 'Asia/Gaza',
  primary key (tenant_id, site_id)
);

create table public.subscribers (
  id bigint primary key,
  tenant_id bigint not null,
  site_id bigint not null
);

create table public.meter_readings (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null,
  subscriber_id bigint not null references public.subscribers(id),
  reading_at timestamptz not null,
  status text not null default 'pending_review',
  is_opening_baseline boolean not null default false
);

