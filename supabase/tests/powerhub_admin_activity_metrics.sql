DO $metrics$
DECLARE
  v jsonb;
BEGIN
  v := public.powerhub_admin_get_activity_metrics();

  IF (v->'paymentDocumentation'->>'totalRequests')::bigint <> 4
     OR (v->'paymentDocumentation'->>'pendingRequests')::bigint <> 1
     OR (v->'paymentDocumentation'->>'approvedRequests')::bigint <> 2
     OR (v->'paymentDocumentation'->>'rejectedRequests')::bigint <> 1
     OR (v->'paymentDocumentation'->>'approvedAmountAllTime')::numeric <> 100
     OR (v->'paymentDocumentation'->>'requestsLast7Days')::bigint <> 4 THEN
    RAISE EXCEPTION 'PAYMENT_DOCUMENTATION_METRICS_MISMATCH: %', v->'paymentDocumentation';
  END IF;

  IF (v->'search'->>'searchesAllTime')::bigint <> 3
     OR (v->'search'->>'searchesLast7Days')::bigint <> 3
     OR (v->'search'->>'noResultSearchesLast30Days')::bigint <> 1
     OR (v->'search'->>'generatorResultHitsLast30Days')::bigint <> 1
     OR (v->'search'->>'subscriberResultHitsLast30Days')::bigint <> 2
     OR (v->'search'->>'ownerResultHitsLast30Days')::bigint <> 1
     OR (v->'search'->>'noResultRatePercentLast30Days')::numeric <> 33.33 THEN
    RAISE EXCEPTION 'SEARCH_METRICS_MISMATCH: %', v->'search';
  END IF;

END
