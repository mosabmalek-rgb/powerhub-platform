  begin
    perform * from public.powerhub_inventory_record_stock_movement(
      v_tenant_id,v_site_id,v_user_id,v_warehouse_id,v_item_id,'issue',
      0.25,null,null,'LOCKED-STOCK-OP','must be rejected while the period is locked',
