    if sqlerrm='SUPPLIER_RETURN_AUDIT_FAILURE_DID_NOT_ABORT_RETURN' then raise; end if;
    if sqlerrm<>'FORCED_SUPPLIER_RETURN_AUDIT_FAILURE' then raise; end if;
