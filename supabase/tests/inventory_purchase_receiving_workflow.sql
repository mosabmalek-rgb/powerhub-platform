  exception when others then
    if sqlerrm='SUPPLIER_RETURN_IDEMPOTENCY_KEY_ACCEPTED_DIFFERENT_PAYLOAD' then raise; end if;
    if sqlerrm not like '%IDEMPOTENCY_KEY_REUSED%' then raise; end if;
  end;

