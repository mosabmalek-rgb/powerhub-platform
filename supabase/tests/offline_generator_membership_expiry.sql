DO $assert_acl$
DECLARE
  v_signature text;
  v_proc regprocedure;
BEGIN
  FOREACH v_signature IN ARRAY ARRAY[
    'public.powerhub_sync_generator_create(bigint,text,text,text,numeric,text,text)',
    'public.powerhub_sync_generator_update(bigint,bigint,text,numeric,numeric,numeric,text,timestamptz,text)'
  ] LOOP
    v_proc := to_regprocedure(v_signature);
    IF v_proc IS NULL
       OR has_function_privilege('anon',v_proc,'EXECUTE')
       OR NOT has_function_privilege('authenticated',v_proc,'EXECUTE')
       OR NOT has_function_privilege('service_role',v_proc,'EXECUTE')
       OR EXISTS (
         SELECT 1 FROM pg_proc p CROSS JOIN LATERAL aclexplode(p.proacl) acl
         WHERE p.oid=v_proc AND acl.grantee=0 AND acl.privilege_type='EXECUTE'
       ) THEN
      RAISE EXCEPTION 'OFFLINE_GENERATOR_RPC_ACL_DRIFT: %',v_signature;
    END IF;
  END LOOP;
END
$assert_acl$;

