-- Reproduce the broad ACLs observed on the Supabase pg_net extension schema.
DO $roles$
BEGIN
  BEGIN CREATE ROLE anon NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END;
  BEGIN CREATE ROLE authenticated NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END;
  BEGIN CREATE ROLE service_role NOLOGIN BYPASSRLS; EXCEPTION WHEN duplicate_object THEN NULL; END;
  BEGIN CREATE ROLE supabase_admin NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END;
END
$roles$;

CREATE SCHEMA net AUTHORIZATION supabase_admin;
GRANT ALL ON SCHEMA net TO PUBLIC, anon, authenticated, service_role;

SET ROLE supabase_admin;
CREATE TABLE net.http_request_queue (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url text NOT NULL
);
CREATE TABLE net._http_response (
  id bigint PRIMARY KEY,
  status_code integer
);
CREATE FUNCTION net.http_get(text,jsonb,jsonb,integer)
RETURNS bigint LANGUAGE sql AS 'SELECT 1::bigint';
CREATE FUNCTION net.http_post(text,jsonb,jsonb,jsonb,integer)
RETURNS bigint LANGUAGE sql AS 'SELECT 1::bigint';
CREATE FUNCTION net.http_delete(text,jsonb,jsonb,integer,jsonb)
RETURNS bigint LANGUAGE sql AS 'SELECT 1::bigint';
CREATE FUNCTION net.http_collect_response(bigint,boolean)
RETURNS boolean LANGUAGE sql AS 'SELECT true';
CREATE FUNCTION net._await_response(bigint)
RETURNS boolean LANGUAGE sql AS 'SELECT true';

-- Simulate extension-install ACLs which inherited access from PUBLIC.
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA net TO PUBLIC, anon, authenticated, service_role;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA net TO PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA net TO PUBLIC, anon, authenticated, service_role;

