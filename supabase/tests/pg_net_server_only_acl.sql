DO $assert_existing_acl$
DECLARE
  v_signature text;
  v_object regprocedure;
BEGIN
  IF has_schema_privilege('anon','net','USAGE')
     OR has_schema_privilege('authenticated','net','USAGE')
     OR NOT has_schema_privilege('service_role','net','USAGE')
     OR NOT has_schema_privilege('postgres','net','USAGE') THEN
    RAISE EXCEPTION 'PG_NET_SCHEMA_USAGE_BOUNDARY_INVALID';
  END IF;

  FOREACH v_signature IN ARRAY ARRAY[
    'net.http_get(text,jsonb,jsonb,integer)',
    'net.http_post(text,jsonb,jsonb,jsonb,integer)',
    'net.http_delete(text,jsonb,jsonb,integer,jsonb)',
    'net.http_collect_response(bigint,boolean)',
    'net._await_response(bigint)'
  ] LOOP
    v_object := to_regprocedure(v_signature);
    IF v_object IS NULL
       OR has_function_privilege('anon',v_object,'EXECUTE')
       OR has_function_privilege('authenticated',v_object,'EXECUTE')
       OR NOT has_function_privilege('service_role',v_object,'EXECUTE')
       OR NOT has_function_privilege('postgres',v_object,'EXECUTE') THEN
      RAISE EXCEPTION 'PG_NET_FUNCTION_ACL_INVALID: %',v_signature;
    END IF;
    IF EXISTS (
      SELECT 1 FROM pg_proc p CROSS JOIN LATERAL aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) acl
      WHERE p.oid=v_object AND acl.grantee=0 AND acl.privilege_type='EXECUTE'
    ) THEN
      RAISE EXCEPTION 'PG_NET_PUBLIC_EXECUTE_REMAINS: %',v_signature;
    END IF;
  END LOOP;

  IF has_table_privilege('anon','net.http_request_queue','SELECT')
     OR has_table_privilege('anon','net.http_request_queue','INSERT')
     OR has_table_privilege('authenticated','net.http_request_queue','SELECT')
     OR has_table_privilege('authenticated','net.http_request_queue','INSERT')
     OR has_table_privilege('anon','net._http_response','SELECT')
     OR has_table_privilege('authenticated','net._http_response','SELECT')
     OR NOT has_table_privilege('service_role','net.http_request_queue','INSERT')
     OR NOT has_table_privilege('service_role','net._http_response','SELECT')
     OR NOT has_table_privilege('postgres','net.http_request_queue','INSERT') THEN
    RAISE EXCEPTION 'PG_NET_TABLE_ACL_INVALID';
  END IF;

  IF has_sequence_privilege('anon','net.http_request_queue_id_seq','USAGE')
     OR has_sequence_privilege('authenticated','net.http_request_queue_id_seq','USAGE')
     OR NOT has_sequence_privilege('service_role','net.http_request_queue_id_seq','USAGE')
     OR NOT has_sequence_privilege('postgres','net.http_request_queue_id_seq','USAGE') THEN
    RAISE EXCEPTION 'PG_NET_SEQUENCE_ACL_INVALID';
  END IF;
END
$assert_existing_acl$;

-- Direct call attempts are expected to fail at schema/EXECUTE authorization.
SET ROLE anon;
DO $assert_anon_call_denied$
BEGIN
  BEGIN
    PERFORM net.http_post('https://example.invalid','{}'::jsonb,'{}'::jsonb,'{}'::jsonb,1000);
    RAISE EXCEPTION 'ANON_PG_NET_CALL_WAS_ALLOWED';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;
END
$assert_anon_call_denied$;

SET ROLE authenticated;
DO $assert_authenticated_call_denied$
BEGIN
  BEGIN
    PERFORM net.http_post('https://example.invalid','{}'::jsonb,'{}'::jsonb,'{}'::jsonb,1000);
    RAISE EXCEPTION 'AUTHENTICATED_PG_NET_CALL_WAS_ALLOWED';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;
END
$assert_authenticated_call_denied$;

