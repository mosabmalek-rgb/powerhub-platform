do $access$
declare v_table text;
begin
 if has_table_privilege('anon','public.powerhub_hr_delta_scope_membership','SELECT')
   or has_table_privilege('authenticated','public.powerhub_hr_delta_scope_membership','SELECT')
 then raise exception 'HR_MEMBERSHIP_TABLE_BROWSER_ACCESSIBLE'; end if;

 foreach v_table in array array[
   'employees','employee_attendance','employee_adjustments','payroll_runs','payroll_items',
   'payroll_adjustment_allocations'
 ] loop
   if not (select relrowsecurity from pg_class where oid=format('public.%I',v_table)::regclass) then
     raise exception 'HR_RLS_NOT_ENABLED: %',v_table;
   end if;
   if not exists(
     select 1 from pg_policies
     where schemaname='public' and tablename=v_table
       and cmd='SELECT' and roles=array['authenticated']::name[]
   ) then raise exception 'HR_AUTHENTICATED_TENANT_READ_POLICY_MISSING: %',v_table; end if;
   if has_table_privilege('anon',format('public.%I',v_table),'SELECT')
      or has_table_privilege('authenticated',format('public.%I',v_table),'INSERT')
      or has_table_privilege('authenticated',format('public.%I',v_table),'UPDATE')
      or has_table_privilege('authenticated',format('public.%I',v_table),'DELETE')
   then raise exception 'HR_BROWSER_TABLE_ACL_TOO_WIDE: %',v_table; end if;
   if v_table<>'payroll_adjustment_allocations'
      and not has_table_privilege('authenticated',format('public.%I',v_table),'SELECT')
   then raise exception 'HR_AUTHENTICATED_READ_MISSING: %',v_table; end if;
   if not has_table_privilege('service_role',format('public.%I',v_table),'INSERT')
      or not has_table_privilege('service_role',format('public.%I',v_table),'UPDATE')
      or not has_table_privilege('service_role',format('public.%I',v_table),'DELETE')
   then raise exception 'HR_SERVICE_ROLE_DML_MISSING: %',v_table; end if;
 end loop;

 if has_sequence_privilege('anon','public.employees_id_seq','USAGE')
    or has_sequence_privilege('authenticated','public.employees_id_seq','USAGE')
    or not has_sequence_privilege('service_role','public.employees_id_seq','USAGE')
 then raise exception 'HR_SEQUENCE_ACL_INVALID'; end if;
end $access$;
