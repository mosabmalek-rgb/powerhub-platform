-- Minimal isolated fixture for the forward-only historical payment reclassification.
create table public.payments (
  id bigint primary key,
  tenant_id bigint not null,
  site_id bigint not null,
  subscriber_id bigint not null,
  invoice_id bigint,
  payment_no text not null,
  amount numeric(14,2) not null,
  payment_purpose text not null default 'invoice_collection',
  invoice_applied_amount numeric(14,2) not null default 0,
  subscriber_credit_amount numeric(14,2) not null default 0,
  status text not null default 'completed',
  collected_by_user_id bigint
);

create table public.subscriber_balance_ledger (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null,
  site_id bigint not null,
  subscriber_id bigint not null,
  balance_type text not null,
  entry_type text not null,
  direction text not null,
  amount numeric(14,2) not null,
  payment_id bigint not null,
  idempotency_key text not null unique,
  created_by_user_id bigint,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table public.audit_logs (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null,
  site_id bigint not null,
  user_id bigint,
  entity_type text not null,
  entity_id text not null,
  action text not null,
  before_data jsonb,
  after_data jsonb,
  metadata jsonb,
  created_at timestamptz not null default now()
);

