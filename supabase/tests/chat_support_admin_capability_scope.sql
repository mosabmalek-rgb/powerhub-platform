CREATE OR REPLACE FUNCTION private.chat_current_user_id()
RETURNS bigint
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT u.id
  FROM public.users u
  WHERE u.auth_user_id = (SELECT auth.uid())
    AND u.account_status = 'active'
  LIMIT 1
$function$;

CREATE OR REPLACE FUNCTION private.powerhub_has_platform_capability(p_capability text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT EXISTS (
    SELECT 1
    FROM public.users u
    JOIN private.platform_capability_policies p
      ON p.platform_role = u.platform_role
     AND p.capability = p_capability
     AND p.is_allowed = true
    WHERE u.auth_user_id = (SELECT auth.uid())
      AND u.account_status = 'active'
  )
$function$;

