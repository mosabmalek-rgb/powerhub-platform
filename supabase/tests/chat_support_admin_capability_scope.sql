DO $acl_contract$
DECLARE
  v_signature text;
  v_oid oid;
BEGIN
  FOREACH v_signature IN ARRAY ARRAY[
    'public.chat_support_admin_save_settings(integer,integer)',
    'public.chat_support_admin_snapshot()',
    'public.chat_support_admin_upsert_category(text,text,text,integer,integer,integer,boolean)',
    'public.chat_support_admin_upsert_quick_reply(text,text,text,text,boolean)',
    'public.chat_support_admin_upsert_sla(text,numeric)',
    'public.chat_support_admin_upsert_tag(text,text,text,boolean)'
  ] LOOP
    v_oid := to_regprocedure(v_signature);
    IF v_oid IS NULL
       OR NOT (SELECT prosecdef FROM pg_proc WHERE oid = v_oid)
       OR coalesce(array_to_string((SELECT proconfig FROM pg_proc WHERE oid = v_oid), ','), '') NOT LIKE '%search_path=""%'
       OR has_function_privilege('anon', v_oid, 'EXECUTE')
       OR NOT has_function_privilege('authenticated', v_oid, 'EXECUTE')
       OR EXISTS (
         SELECT 1
         FROM aclexplode(coalesce((SELECT proacl FROM pg_proc WHERE oid = v_oid), acldefault('f',(SELECT proowner FROM pg_proc WHERE oid = v_oid)))) a
         WHERE a.grantee = 0 AND a.privilege_type = 'EXECUTE'
       ) THEN
      RAISE EXCEPTION 'CHAT_SUPPORT_ADMIN_RPC_ACL_OR_SECURITY_CONTEXT_MISMATCH: %', v_signature;
    END IF;
  END LOOP;

  IF has_function_privilege('authenticated', 'private.chat_assert_support_admin()', 'EXECUTE')
     OR has_function_privilege('anon', 'private.chat_assert_support_admin()', 'EXECUTE') THEN
    RAISE EXCEPTION 'CHAT_SUPPORT_ADMIN_ASSERT_DIRECTLY_CALLABLE';
  END IF;

  IF has_table_privilege('authenticated','public.chat_support_categories','INSERT')
     OR has_table_privilege('authenticated','public.chat_support_categories','UPDATE')
     OR has_table_privilege('authenticated','public.chat_support_categories','DELETE')
     OR has_table_privilege('authenticated','public.chat_support_quick_replies','INSERT')
     OR has_table_privilege('authenticated','public.chat_support_quick_replies','UPDATE')
     OR has_table_privilege('authenticated','public.chat_support_quick_replies','DELETE')
     OR has_table_privilege('authenticated','public.chat_support_settings','INSERT')
     OR has_table_privilege('authenticated','public.chat_support_settings','UPDATE')
     OR has_table_privilege('authenticated','public.chat_support_settings','DELETE') THEN
    RAISE EXCEPTION 'CHAT_SUPPORT_ADMIN_DIRECT_TABLE_DML_GRANT_PRESENT';
  END IF;
END
$acl_contract$;

