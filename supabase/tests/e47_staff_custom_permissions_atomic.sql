CREATE FUNCTION public.powerhub_assign_existing_staff(
 p_tenant_id bigint,p_site_id bigint,p_actor_user_id bigint,
 p_target_user_id bigint,p_role text,p_all_branches boolean)
RETURNS TABLE(profile_id bigint,target_user_id bigint)
LANGUAGE plpgsql SECURITY INVOKER SET search_path=public,pg_temp AS $f$
DECLARE v_profile_id bigint;
BEGIN
 IF p_tenant_id<>10 OR p_site_id NOT IN (101,102) THEN
   RAISE EXCEPTION 'SITE_OUT_OF_SCOPE' USING errcode='P0001';
 END IF;
 INSERT INTO public.tenant_members(tenant_id,user_id,role)
 VALUES(p_tenant_id,p_target_user_id,'member')
 ON CONFLICT(tenant_id,user_id) DO UPDATE SET is_active=true;
 INSERT INTO public.staff_profiles(tenant_id,site_id,user_id,role)
 VALUES(p_tenant_id,CASE WHEN p_all_branches THEN NULL ELSE p_site_id END,p_target_user_id,p_role)
 RETURNING id INTO v_profile_id;
 RETURN QUERY SELECT v_profile_id,p_target_user_id;
END $f$;

