-- A controlled canonical-payment stub so the manual-discount wrapper can be tested
-- atomically without invoking real payment providers or production money flows.
create or replace function public.powerhub_create_payment(
  p_tenant_id bigint,p_site_id bigint,p_user_id bigint,p_subscriber_id bigint,p_invoice_id bigint,
  p_payment_no text,p_amount numeric,p_payment_method text,p_company_account_id bigint,
  p_transfer_from_account text,p_transfer_from_type text,p_reference_no text,
  p_receipt_image_key text,p_receipt_image_hash text,p_collector_session_id bigint,p_client_operation_id uuid
)
returns table(payment_id bigint,replayed boolean)
language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_id bigint; v_inv public.invoices%rowtype;
begin
  if p_amount<=0 then raise exception 'INVALID_PAYMENT_AMOUNT' using errcode='P0001'; end if;
  if p_client_operation_id is not null then
    select id into v_id from public.payments where client_operation_id=p_client_operation_id::text;
    if found then return query select v_id,true; return; end if;
  end if;
  select * into v_inv from public.invoices where id=p_invoice_id and tenant_id=p_tenant_id and site_id=p_site_id and subscriber_id=p_subscriber_id for update;
  if not found then raise exception 'INVOICE_OUT_OF_SCOPE' using errcode='P0001'; end if;
  if p_amount>v_inv.balance_due then raise exception 'INVOICE_BALANCE_CONFLICT' using errcode='P0001'; end if;
  insert into public.payments(tenant_id,site_id,subscriber_id,invoice_id,payment_no,client_operation_id,amount,payment_method,transfer_from_account,transfer_from_type,reference_no,receipt_image_key,receipt_image_hash,collected_by_user_id,collector_session_id)
  values(p_tenant_id,p_site_id,p_subscriber_id,p_invoice_id,p_payment_no,p_client_operation_id::text,p_amount,p_payment_method,p_transfer_from_account,p_transfer_from_type,p_reference_no,p_receipt_image_key,p_receipt_image_hash,p_user_id,p_collector_session_id)
  returning id into v_id;
  update public.invoices set paid_amount=paid_amount+p_amount,
    balance_due=greatest(0,total_amount-(paid_amount+p_amount)),
    status=case when greatest(0,total_amount-(paid_amount+p_amount))=0 then 'paid' else 'partially_paid' end,
    updated_at=now() where id=p_invoice_id;
  insert into public.account_transactions(tenant_id,account_id,transaction_type,amount,description,reference_no,related_payment_id,created_by_user_id)
  values(p_tenant_id,p_company_account_id,'collection',p_amount,p_payment_no,p_reference_no,v_id,p_user_id);
  if p_client_operation_id is not null then
    insert into public.offline_sync_operations(tenant_id,site_id,user_id,client_operation_id,operation_type,entity_type,entity_id,response)
    values(p_tenant_id,p_site_id,p_user_id,p_client_operation_id::text,'payment_create','payment',v_id,jsonb_build_object('id',v_id));
  end if;
  return query select v_id,false;
end;$$;

