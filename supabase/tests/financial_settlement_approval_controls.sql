  SELECT approved_by_user_id INTO v_approver_id
  FROM public.financial_settlements WHERE id=v_settlement_id;
  IF v_approver_id IS DISTINCT FROM 2 THEN
    RAISE EXCEPTION 'INDEPENDENT_APPROVER_NOT_RECORDED';
  END IF;

