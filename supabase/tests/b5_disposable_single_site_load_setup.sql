CREATE OR REPLACE FUNCTION public.b5_execute_synthetic_movement(p_worker integer,p_iteration integer)
RETURNS text LANGUAGE plpgsql SECURITY INVOKER SET search_path='public','pg_temp'
AS $b5$
DECLARE
 v_key_index integer;
 v_operation text;
 v_key uuid;
 v_desc text;
 v_started timestamptz;
 v_first bigint;
 v_second bigint;
 v_replayed boolean;
 v_elapsed numeric;
BEGIN
 IF current_database()<>'powerhub_b5_synthetic_load_test'
   OR p_worker NOT BETWEEN 1 AND 4 OR p_iteration NOT BETWEEN 1 AND 250
 THEN RAISE EXCEPTION 'B5_INVALID_DISPOSABLE_SCOPE' USING ERRCODE='22023'; END IF;
 -- 999 first-time operations and one exact idempotent replay out of 1,000.
 v_key_index:=CASE WHEN p_worker=4 AND p_iteration=250 THEN 1 ELSE p_iteration END;
 v_operation:=CASE WHEN v_key_index%10<6 THEN 'deposit'
                   WHEN v_key_index%10<9 THEN 'withdrawal' ELSE 'transfer' END;
 v_key:=md5('B5-single-branch-synthetic:'||p_worker||':'||v_key_index)::uuid;
 v_desc:='B5 fixture worker '||p_worker||' operation '||v_key_index;
 v_started:=clock_timestamp();
 IF v_operation='transfer' THEN
   SELECT from_transaction_id,to_transaction_id,replayed
     INTO v_first,v_second,v_replayed
   FROM public.powerhub_transfer_company_accounts_idempotent(
     1,10,7,100,200,1.00,v_desc,v_key);
   IF v_second IS NULL OR v_second=v_first
   THEN RAISE EXCEPTION 'B5_TRANSFER_PAIR_INCOMPLETE'; END IF;
 ELSE
   SELECT transaction_id,replayed INTO v_first,v_replayed
   FROM public.powerhub_add_account_movement_idempotent(
     1,10,7,100,v_operation,1.00,v_desc,
     'B5-SYN-'||p_worker||'-'||v_key_index,v_key);
 END IF;
 v_elapsed:=round(extract(epoch from clock_timestamp()-v_started)::numeric*1000,3);
 IF v_first IS NULL OR v_replayed IS DISTINCT FROM (p_worker=4 AND p_iteration=250)
 THEN RAISE EXCEPTION 'B5_FIRST_POST_OR_REPLAY_MISMATCH'; END IF;
 INSERT INTO public.b5_measurements
   (worker_id,backend_pid,iteration,operation,replayed,transaction_id,elapsed_ms)
 VALUES(p_worker,pg_backend_pid(),p_iteration,v_operation,v_replayed,v_first,v_elapsed);
 RETURN 'B5_OK';
END $b5$;
REVOKE ALL ON FUNCTION public.b5_execute_synthetic_movement(integer,integer)
 FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.b5_execute_synthetic_movement(integer,integer)
 TO service_role;

