-- Password reset workflow for tenant owners and platform admins.
-- The Auth password itself is never stored in PowerHub. This migration stores only
-- the short-lived workflow/audit state needed to safely coordinate Supabase Auth
-- with tenant-scoped authorization.
create table if not exists public.password_reset_intents (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint references public.sites(id) on delete set null,
  target_user_id bigint not null references public.users(id) on delete cascade,
  target_auth_user_id uuid not null,
  actor_user_id bigint not null references public.users(id),
  actor_type text not null check (actor_type in ('tenant_owner','platform_admin')),
  status text not null default 'in_progress' check (status in ('in_progress','completed','failed')),
  failure_reason text,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists password_reset_intents_target_idx
  on public.password_reset_intents (tenant_id, target_user_id, created_at desc);
create unique index if not exists password_reset_intents_active_target_uq
  on public.password_reset_intents (tenant_id, target_user_id)
  where status = 'in_progress';

alter table public.password_reset_intents enable row level security;
revoke all on table public.password_reset_intents from public, anon, authenticated;
grant all on table public.password_reset_intents to service_role;

create or replace function public.powerhub_prepare_password_reset(
  p_actor_user_id bigint,
  p_tenant_id bigint,
  p_target_user_id bigint,
  p_site_id bigint default null
)
returns table(intent_id bigint,target_auth_user_id uuid,target_user_id bigint,tenant_id bigint,site_id bigint)
language plpgsql security definer set search_path = public, pg_temp
as $function$
declare
  v_actor_role text; v_actor_platform_role text; v_actor_tenant_role text;
  v_target_role text; v_target_platform_role text; v_target_status text; v_target_auth_user_id uuid;
  v_target_member_role text; v_target_member_active boolean; v_target_membership_status text;
  v_site_id bigint; v_existing_id bigint; v_existing_created_at timestamptz; v_actor_type text;
begin
  perform pg_advisory_xact_lock(hashtext('password-reset-tenant:' || p_tenant_id::text)::bigint);
  perform pg_advisory_xact_lock(hashtext('password-reset-target:' || p_tenant_id::text || ':' || p_target_user_id::text)::bigint);

  select u.role,u.platform_role into v_actor_role,v_actor_platform_role
  from public.users u where u.id=p_actor_user_id and u.account_status='active';
  if v_actor_role is null then raise exception 'ACTOR_NOT_FOUND_OR_INACTIVE' using errcode='42501'; end if;

  if v_actor_role='admin' and v_actor_platform_role in ('platform_owner','platform_admin') then
    v_actor_type:='platform_admin';
  elsif v_actor_role='user' then
    select tm.role into v_actor_tenant_role from public.tenant_members tm
    where tm.tenant_id=p_tenant_id and tm.user_id=p_actor_user_id and tm.role='owner'
      and tm.is_active=true and tm.membership_status='active';
    if v_actor_tenant_role is null then raise exception 'PASSWORD_RESET_OWNER_FORBIDDEN' using errcode='42501'; end if;
    v_actor_type:='tenant_owner';
  else
    raise exception 'PASSWORD_RESET_PLATFORM_ROLE_FORBIDDEN' using errcode='42501';
  end if;

  select u.role,u.platform_role,u.account_status,u.auth_user_id
    into v_target_role,v_target_platform_role,v_target_status,v_target_auth_user_id
  from public.users u where u.id=p_target_user_id for update;
  if v_target_role is null then raise exception 'PASSWORD_RESET_TARGET_NOT_FOUND' using errcode='P0002'; end if;
  if v_target_role<>'user' or v_target_platform_role is not null then raise exception 'PASSWORD_RESET_TARGET_NOT_ELIGIBLE' using errcode='42501'; end if;
  if v_target_status<>'active' then raise exception 'PASSWORD_RESET_TARGET_NOT_ACTIVE' using errcode='42501'; end if;
  if v_target_auth_user_id is null then raise exception 'PASSWORD_RESET_AUTH_ACCOUNT_MISSING' using errcode='P0002'; end if;

  select tm.role,tm.is_active,tm.membership_status
    into v_target_member_role,v_target_member_active,v_target_membership_status
  from public.tenant_members tm
  where tm.tenant_id=p_tenant_id and tm.user_id=p_target_user_id for update;
  if v_target_member_role is null or v_target_member_active is not true or v_target_membership_status<>'active'
    then raise exception 'PASSWORD_RESET_TARGET_OUT_OF_SCOPE' using errcode='42501'; end if;

  if v_actor_type='tenant_owner' then
    if v_target_member_role<>'member' then raise exception 'PASSWORD_RESET_OWNER_TARGET_ONLY' using errcode='42501'; end if;
    select sp.site_id into v_site_id from public.staff_profiles sp
    where sp.tenant_id=p_tenant_id and sp.site_id=p_site_id and sp.user_id=p_target_user_id
      and sp.role<>'owner' and sp.is_active=true limit 1;
    if v_site_id is null then raise exception 'PASSWORD_RESET_STAFF_OUT_OF_SCOPE' using errcode='42501'; end if;
  else
    if v_target_member_role not in ('owner','member') then raise exception 'PASSWORD_RESET_TARGET_OUT_OF_SCOPE' using errcode='42501'; end if;
    if p_site_id is not null then
      select sp.site_id into v_site_id from public.staff_profiles sp
      where sp.tenant_id=p_tenant_id and sp.site_id=p_site_id and sp.user_id=p_target_user_id and sp.is_active=true limit 1;
      if v_site_id is null then raise exception 'PASSWORD_RESET_TARGET_SITE_OUT_OF_SCOPE' using errcode='42501'; end if;
    else
      select sp.site_id into v_site_id from public.staff_profiles sp
      where sp.tenant_id=p_tenant_id and sp.user_id=p_target_user_id and sp.is_active=true
      order by case when sp.role='owner' then 0 else 1 end,sp.site_id nulls last limit 1;
    end if;
    if v_site_id is null then select min(s.id) into v_site_id from public.sites s where s.tenant_id=p_tenant_id; end if;
    if v_site_id is null then raise exception 'PASSWORD_RESET_SITE_NOT_FOUND' using errcode='P0002'; end if;
  end if;

  select id,created_at into v_existing_id,v_existing_created_at
  from public.password_reset_intents
  where tenant_id=p_tenant_id and target_user_id=p_target_user_id and status='in_progress'
  order by created_at desc limit 1 for update;
  if v_existing_id is not null then
    if v_existing_created_at>now()-interval '10 minutes' then raise exception 'PASSWORD_RESET_IN_PROGRESS' using errcode='55P03'; end if;
    update public.password_reset_intents set status='failed',failure_reason='stale_in_progress_intent',completed_at=now() where id=v_existing_id;
  end if;

  insert into public.password_reset_intents(
    tenant_id,site_id,target_user_id,target_auth_user_id,actor_user_id,actor_type,status,metadata
  ) values(p_tenant_id,v_site_id,p_target_user_id,v_target_auth_user_id,p_actor_user_id,v_actor_type,'in_progress',
    jsonb_build_object('targetRole',v_target_member_role))
  returning id into v_existing_id;

  insert into public.audit_logs(tenant_id,site_id,user_id,actor_platform_role,actor_tenant_role,entity_type,entity_id,action,metadata)
  values(p_tenant_id,v_site_id,p_actor_user_id,
    case when v_actor_type='platform_admin' then v_actor_platform_role else null end,
    case when v_actor_type='tenant_owner' then 'owner' else null end,
    'user_account',p_target_user_id::text,'password_reset_started',
    jsonb_build_object('intentId',v_existing_id,'targetUserId',p_target_user_id,'actorType',v_actor_type));

  return query select v_existing_id,v_target_auth_user_id,p_target_user_id,p_tenant_id,v_site_id;
end;
$function$;

create or replace function public.powerhub_complete_password_reset(
  p_intent_id bigint,p_actor_user_id bigint,p_success boolean,p_failure_reason text default null
)
returns table(success boolean,intent_status text)
language plpgsql security definer set search_path=public,pg_temp
as $function$
declare v_intent public.password_reset_intents%rowtype; v_before_must_change boolean;
  v_actor_platform_role text; v_actor_tenant_role text;
begin
  select * into v_intent from public.password_reset_intents where id=p_intent_id for update;
  if not found then raise exception 'PASSWORD_RESET_INTENT_NOT_FOUND' using errcode='P0002'; end if;
  if v_intent.actor_user_id<>p_actor_user_id then raise exception 'PASSWORD_RESET_ACTOR_MISMATCH' using errcode='42501'; end if;
  if v_intent.status='completed' then return query select true,'completed'::text; return; end if;
  if v_intent.status<>'in_progress' then raise exception 'PASSWORD_RESET_INTENT_NOT_ACTIVE' using errcode='P0001'; end if;

  if p_success is distinct from true then
    update public.password_reset_intents set status='failed',failure_reason=left(coalesce(p_failure_reason,'auth_update_failed'),1000),completed_at=now()
    where id=p_intent_id;
    insert into public.audit_logs(tenant_id,site_id,user_id,entity_type,entity_id,action,metadata)
    values(v_intent.tenant_id,v_intent.site_id,p_actor_user_id,'user_account',v_intent.target_user_id::text,'password_reset_failed',
      jsonb_build_object('intentId',v_intent.id,'reason',left(coalesce(p_failure_reason,'auth_update_failed'),500)));
    return query select false,'failed'::text; return;
  end if;

  select must_change_password into v_before_must_change
  from public.users where id=v_intent.target_user_id and auth_user_id=v_intent.target_auth_user_id for update;
  if not found then raise exception 'PASSWORD_RESET_TARGET_CHANGED' using errcode='P0002'; end if;

  update public.users set must_change_password=true,temporary_password_issued_at=now(),updated_at=now()
  where id=v_intent.target_user_id and auth_user_id=v_intent.target_auth_user_id;

  update public.password_reset_intents set status='completed',failure_reason=null,completed_at=now() where id=p_intent_id;
  select platform_role into v_actor_platform_role from public.users where id=p_actor_user_id;
  select role into v_actor_tenant_role from public.tenant_members
  where tenant_id=v_intent.tenant_id and user_id=p_actor_user_id and is_active=true and membership_status='active' limit 1;

  insert into public.audit_logs(
    tenant_id,site_id,user_id,actor_platform_role,actor_tenant_role,entity_type,entity_id,action,before_data,after_data,metadata
  ) values(
    v_intent.tenant_id,v_intent.site_id,p_actor_user_id,v_actor_platform_role,v_actor_tenant_role,
    'user_account',v_intent.target_user_id::text,'password_reset_completed',
    jsonb_build_object('mustChangePassword',v_before_must_change),
    jsonb_build_object('mustChangePassword',true),
    jsonb_build_object('intentId',v_intent.id)
  );
  return query select true,'completed'::text;
end;
$function$;

revoke all on function public.powerhub_prepare_password_reset(bigint,bigint,bigint,bigint) from public,anon,authenticated;
revoke all on function public.powerhub_complete_password_reset(bigint,bigint,boolean,text) from public,anon,authenticated;
grant execute on function public.powerhub_prepare_password_reset(bigint,bigint,bigint,bigint) to service_role;
grant execute on function public.powerhub_complete_password_reset(bigint,bigint,boolean,text) to service_role;
