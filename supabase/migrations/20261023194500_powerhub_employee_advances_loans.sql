-- Employee salary advances and employee loans with atomic disbursement and repayments.
alter table public.employee_adjustments
  add column if not exists advance_kind text,
  add column if not exists monthly_deduction numeric(12,2),
  add column if not exists disbursement_account_id bigint,
  add column if not exists disbursement_transaction_id bigint,
  add column if not exists disbursed_at timestamptz;

update public.employee_adjustments
set advance_kind = 'salary_advance'
where adjustment_type = 'advance' and advance_kind is null;

alter table public.employee_adjustments
  add constraint employee_adjustments_advance_kind_ck
  check (advance_kind is null or advance_kind in ('salary_advance','employee_loan')) not valid;
alter table public.employee_adjustments
  add constraint employee_adjustments_monthly_deduction_ck
  check (monthly_deduction is null or (monthly_deduction > 0 and monthly_deduction <= amount)) not valid;
alter table public.employee_adjustments validate constraint employee_adjustments_advance_kind_ck;
alter table public.employee_adjustments validate constraint employee_adjustments_monthly_deduction_ck;

alter table public.employee_adjustments
  add constraint employee_adjustments_disbursement_account_fk
  foreign key (disbursement_account_id) references public.company_accounts(id) on delete restrict;
alter table public.employee_adjustments
  add constraint employee_adjustments_disbursement_transaction_fk
  foreign key (disbursement_transaction_id) references public.account_transactions(id) on delete restrict;

create table if not exists public.employee_adjustment_repayments (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint not null references public.sites(id) on delete restrict,
  adjustment_id bigint not null references public.employee_adjustments(id) on delete restrict,
  repayment_method text not null check (repayment_method in ('cash','bank','wallet','payroll')),
  amount numeric(12,2) not null check (amount > 0 and amount = round(amount,2)),
  company_account_id bigint references public.company_accounts(id) on delete restrict,
  account_transaction_id bigint references public.account_transactions(id) on delete restrict,
  payroll_run_id bigint references public.payroll_runs(id) on delete restrict,
  payment_date date not null,
  reference_no text,
  notes text,
  operation_key text not null,
  operation_payload_hash text not null,
  created_by_user_id bigint not null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  unique (tenant_id, operation_key),
  check (
    (repayment_method in ('cash','bank','wallet') and company_account_id is not null and account_transaction_id is not null and payroll_run_id is null)
    or (repayment_method='payroll' and payroll_run_id is not null and company_account_id is null and account_transaction_id is null)
  )
);
create unique index if not exists employee_adjustments_disbursement_transaction_unique_idx
  on public.employee_adjustments(disbursement_transaction_id) where disbursement_transaction_id is not null;
create index if not exists employee_adjustment_repayments_adjustment_date_idx
  on public.employee_adjustment_repayments(tenant_id,adjustment_id,payment_date desc,id desc);
create index if not exists employee_adjustments_advance_scope_idx
