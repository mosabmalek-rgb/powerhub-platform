-- PowerHub subscriber portal hardening v1
-- Goal: reduce enumeration/brute-force risk without exposing subscriber data to anon clients.

create table if not exists public.subscriber_portal_attempts (
  id bigint generated by default as identity primary key,
  portal_code text not null,
  request_fingerprint text not null,
  succeeded boolean not null default false,
  attempted_at timestamptz not null default now()
);

create index if not exists subscriber_portal_attempts_fingerprint_time_idx
  on public.subscriber_portal_attempts (request_fingerprint, attempted_at desc);

create index if not exists subscriber_portal_attempts_portal_time_idx
  on public.subscriber_portal_attempts (portal_code, attempted_at desc);

alter table public.subscriber_portal_attempts enable row level security;

revoke all on public.subscriber_portal_attempts from anon, authenticated;

grant select, insert on public.subscriber_portal_attempts to service_role;

grant usage, select on sequence public.subscriber_portal_attempts_id_seq to service_role;

create or replace function public.powerhub_subscriber_portal_check_rate_limit(
  p_portal_code text,
  p_request_fingerprint text,
  p_window_seconds integer default 300,
  p_max_attempts integer default 10
)
returns boolean
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  if length(btrim(coalesce(p_portal_code, ''))) < 2
     or length(btrim(coalesce(p_request_fingerprint, ''))) < 16 then
    return false;
  end if;

  select count(*)::integer
    into v_count
  from public.subscriber_portal_attempts
  where portal_code = lower(btrim(p_portal_code))
    and request_fingerprint = p_request_fingerprint
    and attempted_at >= now() - make_interval(secs => greatest(1, least(p_window_seconds, 3600)));

  return v_count < greatest(1, least(p_max_attempts, 100));
end;
$$;

create or replace function public.powerhub_subscriber_portal_record_attempt(
  p_portal_code text,
  p_request_fingerprint text,
  p_succeeded boolean default false
)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
begin
  if length(btrim(coalesce(p_portal_code, ''))) < 2
     or length(btrim(coalesce(p_request_fingerprint, ''))) < 16 then
    return;
  end if;

  insert into public.subscriber_portal_attempts (
    portal_code, request_fingerprint, succeeded
  ) values (
    lower(btrim(p_portal_code)), p_request_fingerprint, coalesce(p_succeeded, false)
  );

  delete from public.subscriber_portal_attempts
  where attempted_at < now() - interval '24 hours';
end;
$$;

revoke all on function public.powerhub_subscriber_portal_check_rate_limit(text, text, integer, integer) from public, anon, authenticated;
grant execute on function public.powerhub_subscriber_portal_check_rate_limit(text, text, integer, integer) to service_role;

revoke all on function public.powerhub_subscriber_portal_record_attempt(text, text, boolean) from public, anon, authenticated;
grant execute on function public.powerhub_subscriber_portal_record_attempt(text, text, boolean) to service_role;

comment on table public.subscriber_portal_attempts is 'Server-side rate-limit telemetry for the public subscriber portal; never exposed to anon/authenticated clients.';
