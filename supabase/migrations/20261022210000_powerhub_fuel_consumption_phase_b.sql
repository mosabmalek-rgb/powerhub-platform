create or replace function public.powerhub_inventory_record_fuel_reading(
  p_tenant_id bigint,
  p_site_id bigint,
  p_user_id bigint,
  p_generator_id bigint,
  p_reading_type text,
  p_tank_warehouse_id bigint,
  p_reading_value numeric,
  p_recorded_at timestamptz,
  p_reference_no text,
  p_notes text,
  p_corrects_reading_id bigint,
  p_correction_reason text,
  p_operation_key text
)
returns table(reading_id bigint,reading_type text,reading_value numeric,recorded_at timestamptz,corrects_reading_id bigint,replayed boolean)
language plpgsql
security definer
set search_path=public,pg_temp
as $function$
declare
  v_generator public.generators%rowtype;
  v_tank public.inventory_warehouses%rowtype;
  v_existing public.generator_fuel_readings%rowtype;
  v_prior public.generator_fuel_readings%rowtype;
  v_next public.generator_fuel_readings%rowtype;
  v_target public.generator_fuel_readings%rowtype;
  v_previous numeric(14,3);
  v_payload_hash text;
  v_platform_role text;
  v_reason text:=nullif(trim(coalesce(p_correction_reason,'')),'');
  v_reference text:=nullif(trim(coalesce(p_reference_no,'')),'');
  v_notes text:=nullif(trim(coalesce(p_notes,'')),'');
begin
  if p_tenant_id is null or p_site_id is null or p_user_id is null or p_generator_id is null
    or p_reading_type not in ('tank_level','operating_hours') or p_reading_type is null
    or p_reading_value is null or p_reading_value < 0 or p_reading_value>1000000000
    or abs(p_reading_value*1000-round(p_reading_value*1000))>0.0000001
    or p_recorded_at is null or p_recorded_at > now()+interval '5 minutes'
    or p_operation_key is null or length(trim(p_operation_key)) not between 1 and 180 then
    raise exception 'INVALID_FUEL_READING' using errcode='P0001';
  end if;
  if v_reference is not null and length(v_reference)>120 then raise exception 'INVALID_FUEL_READING_REFERENCE' using errcode='P0001'; end if;
  if v_notes is not null and length(v_notes)>2000 then raise exception 'INVALID_FUEL_READING_NOTES' using errcode='P0001'; end if;
  if v_reason is not null and length(v_reason) not between 3 and 500 then raise exception 'INVALID_FUEL_READING_CORRECTION_REASON' using errcode='P0001'; end if;
  if p_reading_type='tank_level' and p_tank_warehouse_id is null then raise exception 'FUEL_TANK_REQUIRED' using errcode='P0001'; end if;
  if p_reading_type='operating_hours' and p_tank_warehouse_id is not null then raise exception 'OPERATING_HOURS_DO_NOT_USE_TANK' using errcode='P0001'; end if;

  perform pg_advisory_xact_lock(hashtextextended(p_tenant_id::text||':fuel-reading:'||trim(p_operation_key),0));
  v_payload_hash:=md5(jsonb_build_object(
    'siteId',p_site_id,'generatorId',p_generator_id,'readingType',p_reading_type,
    'tankWarehouseId',p_tank_warehouse_id,'readingValue',p_reading_value,'recordedAt',p_recorded_at,
    'referenceNo',v_reference,'notes',v_notes,'correctsReadingId',p_corrects_reading_id,'correctionReason',v_reason
  )::text);
  select r.* into v_existing from public.generator_fuel_readings r
    where r.tenant_id=p_tenant_id and r.operation_key=trim(p_operation_key);
  if found then
    if v_existing.operation_payload_hash is distinct from v_payload_hash then
      raise exception 'IDEMPOTENCY_KEY_REUSED' using errcode='P0001';
    end if;
    return query select v_existing.id,v_existing.reading_type,v_existing.reading_value,v_existing.recorded_at,v_existing.corrects_reading_id,true;
    return;
  end if;

  select g.* into v_generator from public.generators g
    where g.tenant_id=p_tenant_id and g.site_id=p_site_id and g.id=p_generator_id for update;
  if not found then raise exception 'FUEL_GENERATOR_OUT_OF_SCOPE' using errcode='P0001'; end if;

  if p_reading_type='tank_level' then
    select w.* into v_tank from public.inventory_warehouses w
      where w.tenant_id=p_tenant_id and w.site_id=p_site_id and w.id=p_tank_warehouse_id
        and w.is_active and w.location_type='generator_fuel_tank' and w.generator_id=p_generator_id;
    if not found then raise exception 'FUEL_TANK_OUT_OF_SCOPE' using errcode='P0001'; end if;
  end if;

  if p_corrects_reading_id is not null then
    select r.* into v_target from public.generator_fuel_readings r
      where r.tenant_id=p_tenant_id and r.site_id=p_site_id and r.generator_id=p_generator_id
        and r.reading_type=p_reading_type and r.tank_warehouse_id is not distinct from p_tank_warehouse_id
      order by r.recorded_at desc,r.id desc limit 1 for update;
    if not found or v_target.id<>p_corrects_reading_id or p_recorded_at<v_target.recorded_at or v_reason is null then
      raise exception 'FUEL_READING_CORRECTION_TARGET_INVALID' using errcode='P0001';
    end if;
  end if;

  select r.* into v_prior from public.generator_fuel_readings r
    where r.tenant_id=p_tenant_id and r.site_id=p_site_id and r.generator_id=p_generator_id
      and r.reading_type=p_reading_type and r.tank_warehouse_id is not distinct from p_tank_warehouse_id
      and r.recorded_at<=p_recorded_at
      and (p_corrects_reading_id is null or r.id<>p_corrects_reading_id)
    order by r.recorded_at desc,r.id desc limit 1 for update;
  select r.* into v_next from public.generator_fuel_readings r
    where r.tenant_id=p_tenant_id and r.site_id=p_site_id and r.generator_id=p_generator_id
      and r.reading_type=p_reading_type and r.tank_warehouse_id is not distinct from p_tank_warehouse_id
      and r.recorded_at>p_recorded_at
      and (p_corrects_reading_id is null or r.id<>p_corrects_reading_id)
    order by r.recorded_at asc,r.id asc limit 1;

  if p_reading_type='operating_hours' then
    if p_corrects_reading_id is not null then
      select r.reading_value into v_previous from public.generator_fuel_readings r
        where r.tenant_id=p_tenant_id and r.site_id=p_site_id and r.generator_id=p_generator_id
          and r.reading_type='operating_hours' and r.id<>p_corrects_reading_id
          and r.recorded_at<=v_target.recorded_at
        order by r.recorded_at desc,r.id desc limit 1;
      if v_previous is not null and p_reading_value<v_previous then
        raise exception 'OPERATING_HOURS_BELOW_PREVIOUS_READING' using errcode='P0001';
      end if;
    else
      if v_prior.id is not null and p_reading_value<v_prior.reading_value then
        raise exception 'OPERATING_HOURS_BACKWARDS' using errcode='P0001';
      end if;
      if v_prior.id is null and p_reading_value<v_generator.operating_hours and v_reason is null then
        raise exception 'OPERATING_HOURS_BELOW_GENERATOR_BASELINE' using errcode='P0001';
      end if;
      if v_next.id is not null and p_reading_value>v_next.reading_value then
        raise exception 'OPERATING_HOURS_ABOVE_NEXT_READING' using errcode='P0001';
      end if;
    end if;
  elsif p_corrects_reading_id is not null and v_reason is null then
    raise exception 'FUEL_READING_CORRECTION_REASON_REQUIRED' using errcode='P0001';
  end if;
  if v_reason is not null and p_corrects_reading_id is null
    and not (p_reading_type='operating_hours' and v_prior.id is null and p_reading_value<v_generator.operating_hours) then
    raise exception 'FUEL_READING_CORRECTION_TARGET_REQUIRED' using errcode='P0001';
  end if;

  insert into public.generator_fuel_readings(
    tenant_id,site_id,generator_id,reading_type,tank_warehouse_id,reading_value,recorded_at,
    reference_no,notes,corrects_reading_id,correction_reason,operation_key,operation_payload_hash,created_by_user_id
  ) values (
    p_tenant_id,p_site_id,p_generator_id,p_reading_type,p_tank_warehouse_id,p_reading_value,p_recorded_at,
    v_reference,v_notes,p_corrects_reading_id,v_reason,trim(p_operation_key),v_payload_hash,p_user_id
  ) returning * into v_existing;

  if p_reading_type='tank_level' and (v_next.id is null) then
    update public.generators g set fuel_level_liters=p_reading_value,updated_at=now()
      where g.tenant_id=p_tenant_id and g.site_id=p_site_id and g.id=p_generator_id;
  elsif p_reading_type='operating_hours' and (v_next.id is null) then
    update public.generators g set operating_hours=p_reading_value,updated_at=now()
      where g.tenant_id=p_tenant_id and g.site_id=p_site_id and g.id=p_generator_id;
  end if;

  select u.platform_role into v_platform_role from public.users u where u.id=p_user_id;
  if v_platform_role not in ('platform_owner','platform_admin','finance_admin') then v_platform_role:=null; end if;
  insert into public.audit_logs(tenant_id,site_id,user_id,actor_platform_role,entity_type,entity_id,action,after_data,metadata)
  values (
    p_tenant_id,p_site_id,p_user_id,v_platform_role,'generator_fuel_reading',v_existing.id::text,
    case when p_corrects_reading_id is null then 'create' else 'correct' end,
    jsonb_build_object('generatorId',p_generator_id,'readingType',p_reading_type,'tankWarehouseId',p_tank_warehouse_id,
      'readingValue',p_reading_value,'recordedAt',p_recorded_at,'correctsReadingId',p_corrects_reading_id,
      'correctionReason',v_reason),
    jsonb_build_object('operationKey',trim(p_operation_key),'referenceNo',v_reference)
  );

  return query select v_existing.id,v_existing.reading_type,v_existing.reading_value,v_existing.recorded_at,v_existing.corrects_reading_id,false;
end;
$function$;

create or replace function public.powerhub_inventory_record_fuel_fill(
  p_tenant_id bigint,
  p_site_id bigint,
  p_user_id bigint,
  p_generator_id bigint,
  p_fuel_item_id bigint,
  p_source_warehouse_id bigint,
  p_destination_warehouse_id bigint,
  p_litres numeric,
  p_occurred_at timestamptz,
  p_level_before_liters numeric,
  p_level_after_liters numeric,
  p_operating_hours numeric,
  p_reference_no text,
  p_notes text,
  p_operation_key text
)
returns table(fuel_event_id bigint,stock_transfer_id bigint,litres numeric,total_cost_amount numeric,replayed boolean)
language plpgsql
security definer
set search_path=public,pg_temp
as $function$
declare
  v_generator public.generators%rowtype;
  v_source public.inventory_warehouses%rowtype;
  v_destination public.inventory_warehouses%rowtype;
  v_item public.inventory_items%rowtype;
  v_existing public.generator_fuel_events%rowtype;
  v_transfer record;
  v_payload_hash text;
  v_unit_cost numeric(14,4);
  v_total_cost numeric(14,2);
  v_platform_role text;
  v_reference text:=nullif(trim(coalesce(p_reference_no,'')),'');
  v_notes text:=nullif(trim(coalesce(p_notes,'')),'');
begin
  if p_tenant_id is null or p_site_id is null or p_user_id is null or p_generator_id is null
    or p_fuel_item_id is null or p_source_warehouse_id is null or p_destination_warehouse_id is null
    or p_source_warehouse_id=p_destination_warehouse_id or p_litres is null or p_litres<=0 or p_litres>1000000000
    or abs(p_litres*1000-round(p_litres*1000))>0.0000001
    or p_occurred_at is null or p_occurred_at>now()+interval '5 minutes'
    or (p_level_before_liters is null)<>(p_level_after_liters is null)
    or (p_level_before_liters is not null and (p_level_before_liters<0 or p_level_before_liters>1000000000 or p_level_after_liters<p_level_before_liters or p_level_after_liters>1000000000))
    or (p_operating_hours is not null and (p_operating_hours<0 or abs(p_operating_hours*1000-round(p_operating_hours*1000))>0.0000001))
    or p_operation_key is null or length(trim(p_operation_key)) not between 1 and 150 then
    raise exception 'INVALID_FUEL_FILL' using errcode='P0001';
  end if;
  if v_reference is not null and length(v_reference)>120 then raise exception 'INVALID_FUEL_FILL_REFERENCE' using errcode='P0001'; end if;
  if v_notes is not null and length(v_notes)>2000 then raise exception 'INVALID_FUEL_FILL_NOTES' using errcode='P0001'; end if;

  perform pg_advisory_xact_lock(hashtextextended(p_tenant_id::text||':fuel-fill:'||trim(p_operation_key),0));
  v_payload_hash:=md5(jsonb_build_object(
    'siteId',p_site_id,'generatorId',p_generator_id,'fuelItemId',p_fuel_item_id,
    'sourceWarehouseId',p_source_warehouse_id,'destinationWarehouseId',p_destination_warehouse_id,
    'litres',p_litres,'occurredAt',p_occurred_at,'levelBeforeLiters',p_level_before_liters,
    'levelAfterLiters',p_level_after_liters,'operatingHours',p_operating_hours,
    'referenceNo',v_reference,'notes',v_notes
  )::text);
  select e.* into v_existing from public.generator_fuel_events e
    where e.tenant_id=p_tenant_id and e.operation_key=trim(p_operation_key);
  if found then
    if v_existing.operation_payload_hash is distinct from v_payload_hash then
      raise exception 'IDEMPOTENCY_KEY_REUSED' using errcode='P0001';
    end if;
    return query select v_existing.id,v_existing.stock_transfer_id,v_existing.litres,v_existing.total_cost_amount,true;
    return;
  end if;

  select g.* into v_generator from public.generators g
    where g.tenant_id=p_tenant_id and g.site_id=p_site_id and g.id=p_generator_id for update;
  if not found then raise exception 'FUEL_GENERATOR_OUT_OF_SCOPE' using errcode='P0001'; end if;
  select w.* into v_source from public.inventory_warehouses w
    where w.tenant_id=p_tenant_id and w.site_id=p_site_id and w.id=p_source_warehouse_id and w.is_active;
  if not found or v_source.location_type not in ('central_warehouse','branch_warehouse','fixed_fuel_tank') then
    raise exception 'FUEL_SOURCE_LOCATION_INVALID' using errcode='P0001';
  end if;
  select w.* into v_destination from public.inventory_warehouses w
    where w.tenant_id=p_tenant_id and w.site_id=p_site_id and w.id=p_destination_warehouse_id and w.is_active;
  if not found or v_destination.location_type<>'generator_fuel_tank' or v_destination.generator_id<>p_generator_id then
    raise exception 'FUEL_DESTINATION_TANK_INVALID' using errcode='P0001';
  end if;
  select i.* into v_item from public.inventory_items i
    where i.tenant_id=p_tenant_id and i.id=p_fuel_item_id and i.is_active;
  if not found or v_item.category<>'fuel' or lower(v_item.base_unit) not in ('liter','litre') then
    raise exception 'FUEL_ITEM_MUST_BE_LITRES' using errcode='P0001';
  end if;

  select * into v_transfer from public.powerhub_inventory_transfer_stock(
    p_tenant_id,p_site_id,p_user_id,p_fuel_item_id,p_source_warehouse_id,p_destination_warehouse_id,p_litres,
    'fuel-fill:'||trim(p_operation_key)||':transfer',v_reference,
    coalesce(v_notes,'تعبئة وقود للمولد '||v_generator.name)
  );
  v_total_cost:=v_transfer.total_cost_amount;
  v_unit_cost:=case when p_litres>0 then round(v_total_cost/p_litres,4) else 0 end;

  insert into public.generator_fuel_events(
    tenant_id,site_id,generator_id,fuel_item_id,source_warehouse_id,destination_warehouse_id,
    stock_transfer_id,source_movement_id,destination_movement_id,litres,unit_cost,total_cost_amount,
    occurred_at,level_before_liters,level_after_liters,operating_hours,reference_no,notes,
    operation_key,operation_payload_hash,created_by_user_id
  ) values (
    p_tenant_id,p_site_id,p_generator_id,p_fuel_item_id,p_source_warehouse_id,p_destination_warehouse_id,
    v_transfer.transfer_id,v_transfer.source_movement_id,v_transfer.destination_movement_id,p_litres,
    v_unit_cost,v_total_cost,p_occurred_at,p_level_before_liters,p_level_after_liters,p_operating_hours,
    v_reference,v_notes,trim(p_operation_key),v_payload_hash,p_user_id
  ) returning * into v_existing;

  if p_level_before_liters is not null then
    perform * from public.powerhub_inventory_record_fuel_reading(
      p_tenant_id,p_site_id,p_user_id,p_generator_id,'tank_level',p_destination_warehouse_id,
      p_level_before_liters,p_occurred_at,v_reference,'مستوى الخزان قبل التعبئة: '||coalesce(v_notes,''),
      null,null,trim(p_operation_key)||':level-before'
    );
    perform * from public.powerhub_inventory_record_fuel_reading(
      p_tenant_id,p_site_id,p_user_id,p_generator_id,'tank_level',p_destination_warehouse_id,
      p_level_after_liters,p_occurred_at,v_reference,'مستوى الخزان بعد التعبئة: '||coalesce(v_notes,''),
      null,null,trim(p_operation_key)||':level-after'
    );
  end if;
  if p_operating_hours is not null then
    perform * from public.powerhub_inventory_record_fuel_reading(
      p_tenant_id,p_site_id,p_user_id,p_generator_id,'operating_hours',null,
      p_operating_hours,p_occurred_at,v_reference,'قراءة ساعات التشغيل عند التعبئة: '||coalesce(v_notes,''),
      null,null,trim(p_operation_key)||':operating-hours'
    );
  end if;

  select u.platform_role into v_platform_role from public.users u where u.id=p_user_id;
  if v_platform_role not in ('platform_owner','platform_admin','finance_admin') then v_platform_role:=null; end if;
  insert into public.audit_logs(tenant_id,site_id,user_id,actor_platform_role,entity_type,entity_id,action,after_data,metadata)
  values (
    p_tenant_id,p_site_id,p_user_id,v_platform_role,'generator_fuel_event',v_existing.id::text,'create',
    jsonb_build_object('generatorId',p_generator_id,'fuelItemId',p_fuel_item_id,'sourceWarehouseId',p_source_warehouse_id,
      'destinationWarehouseId',p_destination_warehouse_id,'litres',p_litres,'unitCost',v_unit_cost,
      'totalCostAmount',v_total_cost,'occurredAt',p_occurred_at,'levelBeforeLiters',p_level_before_liters,
      'levelAfterLiters',p_level_after_liters,'operatingHours',p_operating_hours,'stockTransferId',v_transfer.transfer_id),
    jsonb_build_object('operationKey',trim(p_operation_key),'referenceNo',v_reference)
  );

  return query select v_existing.id,v_existing.stock_transfer_id,v_existing.litres,v_existing.total_cost_amount,false;
end;
$function$;

create or replace function public.powerhub_inventory_list_fuel_events(
  p_tenant_id bigint,p_site_id bigint,p_from_date date default null,p_to_date date default null,
  p_generator_id bigint default null,p_limit integer default 100
