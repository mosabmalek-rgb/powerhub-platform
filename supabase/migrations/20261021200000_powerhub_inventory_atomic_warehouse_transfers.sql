-- Atomic, idempotent warehouse-to-warehouse stock transfers.
-- Transfer movements remain append-only and use the existing stock movement valuation contract.
create table if not exists public.inventory_stock_transfers (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint not null,
  item_id bigint not null,
  source_warehouse_id bigint not null,
  destination_warehouse_id bigint not null,
  quantity numeric(14,3) not null check (quantity > 0),
  total_cost_amount numeric(14,2) not null check (total_cost_amount >= 0),
  operation_key text not null check (length(trim(operation_key)) between 1 and 180),
  operation_payload_hash text not null,
  reference_no text,
  notes text,
  source_movement_id bigint,
  destination_movement_id bigint,
  created_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (tenant_id,id),
  unique (tenant_id,operation_key),
  constraint inventory_stock_transfers_site_fk foreign key (tenant_id,site_id)
    references public.sites(tenant_id,id) on delete restrict,
  constraint inventory_stock_transfers_item_fk foreign key (tenant_id,item_id)
    references public.inventory_items(tenant_id,id) on delete restrict,
  constraint inventory_stock_transfers_source_warehouse_fk foreign key (tenant_id,source_warehouse_id)
    references public.inventory_warehouses(tenant_id,id) on delete restrict,
  constraint inventory_stock_transfers_destination_warehouse_fk foreign key (tenant_id,destination_warehouse_id)
    references public.inventory_warehouses(tenant_id,id) on delete restrict,
  constraint inventory_stock_transfers_distinct_warehouses_ck check (source_warehouse_id <> destination_warehouse_id),
  constraint inventory_stock_transfers_source_movement_fk foreign key (tenant_id,source_movement_id)
    references public.inventory_stock_movements(tenant_id,id) on delete restrict,
  constraint inventory_stock_transfers_destination_movement_fk foreign key (tenant_id,destination_movement_id)
    references public.inventory_stock_movements(tenant_id,id) on delete restrict
);

create index if not exists inventory_stock_transfers_tenant_site_created_idx
  on public.inventory_stock_transfers(tenant_id,site_id,created_at desc,id desc);
create index if not exists inventory_stock_transfers_item_created_idx
  on public.inventory_stock_transfers(tenant_id,item_id,created_at desc,id desc);

alter table public.inventory_stock_transfers enable row level security;
revoke all on public.inventory_stock_transfers from public, anon, authenticated;
grant select, insert, update on public.inventory_stock_transfers to service_role;
grant usage, select on sequence public.inventory_stock_transfers_id_seq to service_role;

create or replace function public.powerhub_inventory_transfer_stock(
  p_tenant_id bigint,
  p_site_id bigint,
  p_user_id bigint,
  p_item_id bigint,
  p_source_warehouse_id bigint,
  p_destination_warehouse_id bigint,
  p_quantity numeric,
  p_operation_key text,
  p_reference_no text default null,
  p_notes text default null
)
returns table(
  transfer_id bigint,
  source_movement_id bigint,
  destination_movement_id bigint,
  quantity numeric,
  total_cost_amount numeric,
  replayed boolean
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_transfer public.inventory_stock_transfers%rowtype;
  v_source public.inventory_warehouses%rowtype;
  v_destination public.inventory_warehouses%rowtype;
  v_item public.inventory_items%rowtype;
  v_source_qty numeric(14,3);
  v_source_value numeric(14,2);
  v_destination_qty numeric(14,3);
  v_destination_value numeric(14,2);
  v_unit_cost numeric(14,4);
  v_total_cost numeric(14,2);
  v_payload_hash text;
  v_platform_role text;
  v_out public.inventory_stock_movements%rowtype;
  v_in public.inventory_stock_movements%rowtype;
begin
  if p_tenant_id is null or p_site_id is null or p_user_id is null or p_item_id is null
     or p_source_warehouse_id is null or p_destination_warehouse_id is null
     or p_source_warehouse_id = p_destination_warehouse_id then
    raise exception 'INVALID_STOCK_TRANSFER' using errcode='P0001';
  end if;
  if p_quantity is null or p_quantity <= 0 or p_quantity > 1000000000
     or abs(p_quantity * 1000 - round(p_quantity * 1000)) > 0.0000001 then
    raise exception 'INVALID_STOCK_TRANSFER_QUANTITY' using errcode='P0001';
  end if;
  if p_operation_key is null or length(trim(p_operation_key)) not between 1 and 180 then
    raise exception 'INVALID_OPERATION_KEY' using errcode='P0001';
  end if;

  v_payload_hash := md5(jsonb_build_object(
    'siteId',p_site_id,'itemId',p_item_id,'sourceWarehouseId',p_source_warehouse_id,
    'destinationWarehouseId',p_destination_warehouse_id,'quantity',p_quantity,
    'referenceNo',nullif(trim(p_reference_no),''),'notes',nullif(trim(p_notes),'')
  )::text);

  perform pg_advisory_xact_lock(hashtextextended(
    p_tenant_id::text||':inventory-transfer-key:'||trim(p_operation_key),0
  ));
  select t.* into v_transfer from public.inventory_stock_transfers t
  where t.tenant_id=p_tenant_id and t.operation_key=trim(p_operation_key);
  if found then
    if v_transfer.operation_payload_hash <> v_payload_hash then
      raise exception 'IDEMPOTENCY_KEY_REUSED' using errcode='P0001';
    end if;
    return query select v_transfer.id,v_transfer.source_movement_id,v_transfer.destination_movement_id,
      v_transfer.quantity,v_transfer.total_cost_amount,true;
    return;
  end if;

  select w.* into v_source from public.inventory_warehouses w
  where w.tenant_id=p_tenant_id and w.site_id=p_site_id and w.id=p_source_warehouse_id and w.is_active;
  if not found then raise exception 'STOCK_WAREHOUSE_OUT_OF_SCOPE' using errcode='P0001'; end if;
  select w.* into v_destination from public.inventory_warehouses w
  where w.tenant_id=p_tenant_id and w.site_id=p_site_id and w.id=p_destination_warehouse_id and w.is_active;
  if not found then raise exception 'STOCK_DESTINATION_WAREHOUSE_OUT_OF_SCOPE' using errcode='P0001'; end if;
  select i.* into v_item from public.inventory_items i
  where i.tenant_id=p_tenant_id and i.id=p_item_id and i.is_active;
  if not found then raise exception 'STOCK_ITEM_OUT_OF_SCOPE' using errcode='P0001'; end if;
  select u.platform_role into v_platform_role from public.users u where u.id=p_user_id;
  if not found then raise exception 'ACTOR_NOT_FOUND' using errcode='P0001'; end if;

  if exists (
    select 1 from public.financial_settlements fs
    where fs.tenant_id=p_tenant_id and fs.site_id=p_site_id and fs.status='locked'
      and fs.period_start<=now() and fs.period_end>=now()
  ) then raise exception 'FINANCIAL_PERIOD_LOCKED' using errcode='P0001'; end if;

  -- Lock both item/warehouse balances in a stable order to avoid transfer deadlocks.
  perform pg_advisory_xact_lock(hashtextextended(
    p_tenant_id::text||':inventory-stock:'||least(p_source_warehouse_id,p_destination_warehouse_id)::text||':'||p_item_id::text,0
  ));
  perform pg_advisory_xact_lock(hashtextextended(
    p_tenant_id::text||':inventory-stock:'||greatest(p_source_warehouse_id,p_destination_warehouse_id)::text||':'||p_item_id::text,0
  ));

  select coalesce(sum(case when m.movement_type in ('opening_balance','purchase_receipt','adjustment_in','return_from_issue')
      then m.quantity else -m.quantity end),0)::numeric(14,3),
    coalesce(sum(case when m.movement_type in ('opening_balance','purchase_receipt','adjustment_in','return_from_issue')
      then m.total_cost_amount else -m.total_cost_amount end),0)::numeric(14,2)
  into v_source_qty,v_source_value from public.inventory_stock_movements m
  where m.tenant_id=p_tenant_id and m.site_id=p_site_id and m.warehouse_id=p_source_warehouse_id and m.item_id=p_item_id;

  if v_source_qty < p_quantity then raise exception 'INSUFFICIENT_STOCK' using errcode='P0001'; end if;
  if v_source_qty <= 0 or v_source_value < 0 then raise exception 'INVENTORY_BALANCE_INVALID' using errcode='P0001'; end if;

  if p_quantity = v_source_qty then
    v_total_cost := v_source_value;
  else
    v_total_cost := round(p_quantity * round(v_source_value / v_source_qty,4),2);
  end if;
  v_unit_cost := case when p_quantity > 0 then round(v_total_cost / p_quantity,4) else 0 end;

  select coalesce(sum(case when m.movement_type in ('opening_balance','purchase_receipt','adjustment_in','return_from_issue')
      then m.quantity else -m.quantity end),0)::numeric(14,3),
    coalesce(sum(case when m.movement_type in ('opening_balance','purchase_receipt','adjustment_in','return_from_issue')
      then m.total_cost_amount else -m.total_cost_amount end),0)::numeric(14,2)
  into v_destination_qty,v_destination_value from public.inventory_stock_movements m
  where m.tenant_id=p_tenant_id and m.site_id=p_site_id and m.warehouse_id=p_destination_warehouse_id and m.item_id=p_item_id;
  if v_destination_qty < 0 or v_destination_value < 0 then raise exception 'INVENTORY_BALANCE_INVALID' using errcode='P0001'; end if;

  insert into public.inventory_stock_transfers(
    tenant_id,site_id,item_id,source_warehouse_id,destination_warehouse_id,quantity,total_cost_amount,
    operation_key,operation_payload_hash,reference_no,notes,created_by_user_id
  ) values (
    p_tenant_id,p_site_id,p_item_id,p_source_warehouse_id,p_destination_warehouse_id,p_quantity,v_total_cost,
    trim(p_operation_key),v_payload_hash,nullif(trim(p_reference_no),''),nullif(trim(p_notes),''),p_user_id
  ) returning * into v_transfer;

  insert into public.inventory_stock_movements(
    tenant_id,site_id,warehouse_id,item_id,movement_type,quantity,unit_cost,total_cost_amount,
    reference_no,notes,operation_key,operation_payload_hash,occurred_at,created_by_user_id
  ) values (
    p_tenant_id,p_site_id,p_source_warehouse_id,p_item_id,'issue',p_quantity,v_unit_cost,v_total_cost,
    coalesce(nullif(trim(p_reference_no),''),'TRF-'||v_transfer.id::text),
    'تحويل مخزني صادر #'||v_transfer.id||case when nullif(trim(p_notes),'') is not null then ': '||trim(p_notes) else '' end,
    'transfer:'||trim(p_operation_key)||':out',v_payload_hash,now(),p_user_id
  ) returning * into v_out;

  insert into public.inventory_stock_movements(
    tenant_id,site_id,warehouse_id,item_id,movement_type,quantity,unit_cost,total_cost_amount,
    reference_no,notes,operation_key,operation_payload_hash,occurred_at,created_by_user_id
  ) values (
    p_tenant_id,p_site_id,p_destination_warehouse_id,p_item_id,'adjustment_in',p_quantity,v_unit_cost,v_total_cost,
    coalesce(nullif(trim(p_reference_no),''),'TRF-'||v_transfer.id::text),
    'تحويل مخزني وارد #'||v_transfer.id||case when nullif(trim(p_notes),'') is not null then ': '||trim(p_notes) else '' end,
    'transfer:'||trim(p_operation_key)||':in',v_payload_hash,now(),p_user_id
  ) returning * into v_in;

  update public.inventory_stock_transfers set source_movement_id=v_out.id,destination_movement_id=v_in.id
  where tenant_id=p_tenant_id and id=v_transfer.id;

  insert into public.audit_logs(
    tenant_id,site_id,user_id,actor_platform_role,entity_type,entity_id,action,before_data,after_data,metadata
  ) values (
    p_tenant_id,p_site_id,p_user_id,v_platform_role,'inventory_stock_transfer',v_transfer.id::text,'transfer_stock',
    jsonb_build_object('sourceWarehouseId',p_source_warehouse_id,'destinationWarehouseId',p_destination_warehouse_id,
      'sourceQuantity',v_source_qty,'sourceValue',v_source_value,'destinationQuantity',v_destination_qty,'destinationValue',v_destination_value),
    jsonb_build_object('itemId',p_item_id,'quantity',p_quantity,'totalCostAmount',v_total_cost,
      'sourceMovementId',v_out.id,'destinationMovementId',v_in.id),
    jsonb_build_object('operationKey',trim(p_operation_key),'payloadHash',v_payload_hash)
  );

  return query select v_transfer.id,v_out.id,v_in.id,p_quantity,v_total_cost,false;
end;
$$;

revoke all on function public.powerhub_inventory_transfer_stock(bigint,bigint,bigint,bigint,bigint,bigint,numeric,text,text,text)
  from public,anon,authenticated;
grant execute on function public.powerhub_inventory_transfer_stock(bigint,bigint,bigint,bigint,bigint,bigint,numeric,text,text,text)
  to service_role;
