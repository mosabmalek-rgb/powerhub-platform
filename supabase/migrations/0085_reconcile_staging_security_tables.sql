-- Staging reconciliation: the canonical PowerHub schema defines these tables,
-- but the connected Staging project is missing them. Keep the operation
-- additive and idempotent so Production is unaffected when the tables already exist.

create table if not exists public.platform_security_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('suspicious_login', 'backup', 'security_change')),
  severity text not null default 'info' check (severity in ('info', 'warning', 'critical')),
  status text not null default 'open' check (status in ('open', 'resolved', 'success', 'failed')),
  title text not null,
  details text,
  metadata jsonb,
  related_user_id bigint references public.users(id) on delete set null,
  created_by_user_id bigint references public.users(id) on delete set null,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists platform_security_event_type_date_idx
  on public.platform_security_events(event_type, created_at);
create index if not exists platform_security_event_status_idx
  on public.platform_security_events(status, severity);

create table if not exists public.platform_security_settings (
  id bigint generated by default as identity primary key,
  setting_key text not null unique,
  is_enabled boolean not null default false,
  value jsonb,
  updated_by_user_id bigint references public.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

alter table public.platform_security_events enable row level security;
alter table public.platform_security_settings enable row level security;
