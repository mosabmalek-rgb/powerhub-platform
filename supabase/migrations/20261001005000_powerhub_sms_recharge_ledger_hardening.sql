-- PowerHub SMS recharge ledger hardening
--
-- One-off SMS recharges are ledgered separately from renewable SMS add-ons.
-- Provider confirmation (API or manual) is required before any credit is granted.

create table if not exists public.tenant_sms_recharge_ledger (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null
    references public.tenants(id) on delete cascade,
  request_id bigint
    references public.sms_package_requests(id) on delete set null,
  provider_mode text not null default 'manual'
    check (provider_mode in ('provider_api','manual')),
  status text not null default 'pending'
    check (status in ('pending','processing','provider_confirmed','manual_confirmed','failed','cancelled')),
  requested_messages integer not null
    check (requested_messages > 0 and requested_messages <= 100000000),
  credited_messages integer not null default 0
    check (credited_messages >= 0 and credited_messages <= requested_messages),
  provider_reference text,
  provider_balance numeric,
  idempotency_key uuid not null unique,
  requested_by_user_id bigint not null
    references public.users(id) on delete restrict,
  processed_by_user_id bigint
    references public.users(id) on delete set null,
  confirmed_at timestamptz,
  failure_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(request_id)
);

create index if not exists tenant_sms_recharge_ledger_tenant_status_idx
  on public.tenant_sms_recharge_ledger(tenant_id,status,created_at desc);

alter table public.tenant_sms_recharge_ledger enable row level security;

revoke all on table public.tenant_sms_recharge_ledger
  from public,anon,authenticated;

revoke all on sequence public.tenant_sms_recharge_ledger_id_seq
  from public,anon,authenticated;

-- Provider/manual confirmation is the only operation that turns a recharge
-- request into credited SMS. The operation is role-gated and idempotent.
create or replace function public.powerhub_admin_confirm_sms_recharge(
  p_actor_user_id bigint,
  p_ledger_id bigint,
  p_status text,
  p_credited_messages integer,
  p_provider_reference text default null,
  p_provider_balance numeric default null,
  p_failure_reason text default null
)
returns table(
  success boolean,
  status text,
  credited_messages integer,
  replayed boolean
)
language plpgsql
security definer
set search_path='public','pg_temp'
as $function$
declare
  v_role text;
  v_row public.tenant_sms_recharge_ledger%rowtype;
  v_site_id bigint;
begin
  select u.platform_role
    into v_role
  from public.users u
  where u.id=p_actor_user_id
    and u.role='admin'
    and u.account_status='active'
    and u.platform_role in ('platform_owner','platform_admin','finance_admin');

  if v_role is null then
    raise exception 'FORBIDDEN_PLATFORM_ROLE' using errcode='42501';
  end if;

  if p_status not in ('provider_confirmed','manual_confirmed','failed','cancelled') then
    raise exception 'INVALID_SMS_RECHARGE_STATUS' using errcode='22023';
  end if;

  if p_credited_messages < 0 then
    raise exception 'INVALID_SMS_RECHARGE_CREDIT' using errcode='22023';
  end if;

  select *
    into v_row
  from public.tenant_sms_recharge_ledger l
  where l.id=p_ledger_id
  for update;

  if not found then
    raise exception 'SMS_RECHARGE_NOT_FOUND' using errcode='P0002';
  end if;

  if v_row.status in ('provider_confirmed','manual_confirmed','failed','cancelled') then
    if v_row.status=p_status
       and v_row.credited_messages=p_credited_messages then
      return query
      select true,v_row.status,v_row.credited_messages,true;
      return;
    end if;

    raise exception 'SMS_RECHARGE_ALREADY_FINALIZED' using errcode='55000';
  end if;

  if p_status in ('provider_confirmed','manual_confirmed')
     and p_credited_messages < 1 then
    raise exception 'SMS_RECHARGE_CREDIT_REQUIRED' using errcode='22023';
  end if;

  update public.tenant_sms_recharge_ledger l
  set status=p_status,
      credited_messages=case
        when p_status in ('provider_confirmed','manual_confirmed')
          then p_credited_messages
        else 0
      end,
      provider_reference=nullif(trim(coalesce(p_provider_reference,'')),''),
      provider_balance=p_provider_balance,
      processed_by_user_id=p_actor_user_id,
      confirmed_at=case
        when p_status in ('provider_confirmed','manual_confirmed')
          then now()
        else null
      end,
      failure_reason=nullif(trim(coalesce(p_failure_reason,'')),''),
      updated_at=now()
  where l.id=p_ledger_id
  returning l.* into v_row;

  update public.sms_package_requests r
  set status=case
        when p_status in ('provider_confirmed','manual_confirmed') then 'approved'
        when p_status='cancelled' then 'cancelled'
        else 'rejected'
      end,
      approved_messages=case
        when p_status in ('provider_confirmed','manual_confirmed')
          then p_credited_messages
        else 0
      end,
      reviewed_by_user_id=p_actor_user_id,
      reviewed_at=now(),
      updated_at=now()
  where r.id=v_row.request_id;

  select s.id
    into v_site_id
  from public.sites s
  where s.tenant_id=v_row.tenant_id
    and s.status<>'archived'
  order by s.id
  limit 1;

  insert into public.audit_logs(
    tenant_id,
    site_id,
    user_id,
    actor_platform_role,
    entity_type,
    entity_id,
    action,
    after_data,
    metadata
  )
  values(
    v_row.tenant_id,
    v_site_id,
    p_actor_user_id,
    v_role,
    'tenant_sms_recharge_ledger',
    v_row.id::text,
    case
      when p_status in ('provider_confirmed','manual_confirmed')
        then 'sms_recharge_confirmed'
      else 'sms_recharge_finalized'
    end,
    jsonb_build_object(
      'status',v_row.status,
      'creditedMessages',v_row.credited_messages,
      'providerMode',v_row.provider_mode,
      'providerReference',v_row.provider_reference,
      'providerBalance',v_row.provider_balance
    ),
    jsonb_build_object(
      'requestId',v_row.request_id,
      'failureReason',v_row.failure_reason
    )
  );

  return query
  select true,v_row.status,v_row.credited_messages,false;
end;
$function$;

revoke all on function public.powerhub_admin_confirm_sms_recharge(
  bigint,bigint,text,integer,text,numeric,text
) from public,anon,authenticated;

grant execute on function public.powerhub_admin_confirm_sms_recharge(
  bigint,bigint,text,integer,text,numeric,text
) to service_role;
