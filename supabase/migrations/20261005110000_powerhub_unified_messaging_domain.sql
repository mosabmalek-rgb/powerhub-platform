create or replace function public.powerhub_unified_messaging_templates(
  p_tenant_id bigint,
  p_channel text default null,
  p_event_type text default null
)
returns table(
  id bigint,
  tenant_id bigint,
  name text,
  description text,
  channel text,
  event_type text,
  body text,
  variables jsonb,
  is_active boolean,
  version integer,
  created_by bigint,
  updated_by bigint,
  created_at timestamptz,
  updated_at timestamptz
)
language sql
security definer
set search_path = public, pg_temp
as $function$
  select t.id, t.tenant_id, t.name, t.description, t.channel, t.event_type,
         t.body, t.variables, t.is_active, t.version, t.created_by,
         t.updated_by, t.created_at, t.updated_at
  from public.powerhub_message_templates t
  where t.tenant_id = p_tenant_id
    and (p_channel is null or t.channel = p_channel)
    and (p_event_type is null or t.event_type = p_event_type)
  order by t.is_active desc, t.updated_at desc, t.id desc;
$function$;

create or replace function public.powerhub_unified_messaging_upsert_template(
  p_tenant_id bigint,
  p_name text,
  p_description text,
  p_channel text,
  p_event_type text,
  p_body text,
  p_variables jsonb,
  p_is_active boolean,
  p_actor_user_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  v_id bigint;
begin
  if p_tenant_id is null or p_tenant_id < 1 then raise exception 'INVALID_TENANT_ID' using errcode='22023'; end if;
  if p_channel not in ('sms','whatsapp') then raise exception 'INVALID_CHANNEL' using errcode='22023'; end if;
  if char_length(trim(coalesce(p_name,''))) not between 2 and 120 then raise exception 'INVALID_TEMPLATE_NAME' using errcode='22023'; end if;
  if char_length(trim(coalesce(p_body,''))) not between 1 and 4096 then raise exception 'INVALID_TEMPLATE_BODY' using errcode='22023'; end if;

  insert into public.powerhub_message_templates(
    tenant_id,name,description,channel,event_type,body,variables,is_active,version,created_by,updated_by
  ) values (
    p_tenant_id,trim(p_name),nullif(trim(p_description),''),p_channel,nullif(trim(p_event_type),''),
    p_body,coalesce(p_variables,'[]'::jsonb),coalesce(p_is_active,true),1,p_actor_user_id,p_actor_user_id
  )
  on conflict (tenant_id, lower(name), channel, coalesce(event_type,'')) do update
    set description=excluded.description,
        body=excluded.body,
        variables=excluded.variables,
        is_active=excluded.is_active,
        version=public.powerhub_message_templates.version + 1,
        updated_by=p_actor_user_id,
        updated_at=now()
  returning id into v_id;

  return v_id;
end;
$function$;

create or replace function public.powerhub_unified_messaging_automations(
  p_tenant_id bigint,
  p_site_id bigint default null
)
returns table(
  id bigint,
  tenant_id bigint,
  site_id bigint,
  template_id bigint,
  template_name text,
  name text,
  event_type text,
  send_type text,
  schedule_type text,
  schedule_anchor_at timestamptz,
  timezone text,
  audience jsonb,
  trigger_config jsonb,
  enabled boolean,
  created_at timestamptz,
  updated_at timestamptz
)
language sql
security definer
set search_path = public, pg_temp
as $function$
  select a.id,a.tenant_id,a.site_id,a.template_id,t.name,a.name,a.event_type,
         a.send_type,a.schedule_type,a.schedule_anchor_at,a.timezone,a.audience,
         a.trigger_config,a.enabled,a.created_at,a.updated_at
  from public.powerhub_message_automations a
  join public.powerhub_message_templates t on t.id=a.template_id
  where a.tenant_id=p_tenant_id
    and (p_site_id is null or a.site_id=p_site_id)
  order by a.enabled desc,a.updated_at desc,a.id desc;
$function$;

create or replace function public.powerhub_unified_messaging_upsert_automation(
  p_tenant_id bigint,
  p_site_id bigint,
  p_template_id bigint,
  p_name text,
  p_event_type text,
  p_send_type text,
  p_schedule_type text,
  p_schedule_anchor_at timestamptz,
  p_timezone text,
  p_audience jsonb,
  p_trigger_config jsonb,
  p_enabled boolean,
  p_actor_user_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  v_id bigint;
begin
  if p_send_type not in ('automatic','scheduled') then raise exception 'INVALID_SEND_TYPE' using errcode='22023'; end if;
  if p_send_type='automatic' and (p_schedule_type <> 'none' or p_schedule_anchor_at is not null) then raise exception 'AUTOMATIC_CANNOT_HAVE_SCHEDULE' using errcode='22023'; end if;
  if p_send_type='scheduled' and (p_schedule_type='none' or p_schedule_anchor_at is null) then raise exception 'SCHEDULE_REQUIRED' using errcode='22023'; end if;

  if not exists (
    select 1 from public.powerhub_message_templates t
    where t.id=p_template_id and t.tenant_id=p_tenant_id and t.is_active
  ) then
    raise exception 'TEMPLATE_OUT_OF_SCOPE' using errcode='P0001';
  end if;

  insert into public.powerhub_message_automations(
    tenant_id,site_id,template_id,name,event_type,send_type,schedule_type,
    schedule_anchor_at,timezone,audience,enabled,created_by,updated_by
  ) values (
    p_tenant_id,p_site_id,p_template_id,trim(p_name),nullif(trim(p_event_type),''),
    p_send_type,p_schedule_type,p_schedule_anchor_at,coalesce(nullif(trim(p_timezone),''),'Asia/Gaza'),
    coalesce(p_audience,'{}'::jsonb),coalesce(p_enabled,true),p_actor_user_id,p_actor_user_id
  )
  on conflict (tenant_id, lower(name)) do update
    set site_id=excluded.site_id,template_id=excluded.template_id,event_type=excluded.event_type,
        send_type=excluded.send_type,schedule_type=excluded.schedule_type,
        schedule_anchor_at=excluded.schedule_anchor_at,timezone=excluded.timezone,
        audience=excluded.audience,trigger_config=excluded.trigger_config,enabled=excluded.enabled,updated_by=p_actor_user_id,updated_at=now()
  returning id into v_id;

  return v_id;
end;
$function$;

