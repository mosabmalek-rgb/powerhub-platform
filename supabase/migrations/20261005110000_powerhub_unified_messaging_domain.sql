-- PowerHub: unified messaging domain.
-- This migration is additive. Existing invoice/payment SMS flows remain intact.
-- Direct client execution is intentionally disabled; server procedures use service_role
-- only after PowerHub capability + site/tenant scope checks.

-- Canonical business events. The catalog is intentionally data-free so tenant
-- automation rows remain backward compatible while the UI can present stable names.
-- invoice_issued: an approved reading creates an invoice; each invoice gets queued.
-- subscriber_created: a new subscriber gets the reference/welcome message immediately.
-- invoice_overdue: a subscriber who misses the due date can receive a reminder.
-- payment_received: existing payment receipt flow remains available.
-- service_alert: reserved for future operational alerts.

alter table public.tenant_messaging_configurations
  add column if not exists invoice_message_style text not null default 'details',
  add column if not exists payment_reminder_enabled boolean not null default true,
  add column if not exists payment_reminder_after_days integer not null default 1;

alter table public.tenant_messaging_configurations
  drop constraint if exists tenant_messaging_configurations_invoice_message_style_check,
  drop constraint if exists tenant_messaging_configurations_payment_reminder_after_days_check;

alter table public.tenant_messaging_configurations
  add constraint tenant_messaging_configurations_invoice_message_style_check
    check (invoice_message_style in ('details','portal_link')),
  add constraint tenant_messaging_configurations_payment_reminder_after_days_check
    check (payment_reminder_after_days between 0 and 90);


-- Unified domain allows free-form/manual campaigns while preserving existing business events.
alter table public.notification_messages
  drop constraint if exists notification_messages_event_type_check;
alter table public.notification_messages
  add constraint notification_messages_event_type_check
  check (event_type in ('invoice_issued','payment_reminder','payment_received','service_alert','subscriber_reference','manual'));

alter table public.notification_messages
  add column if not exists send_type text,
  add column if not exists schedule_type text,
  add column if not exists template_id bigint,
  add column if not exists automation_id bigint;

alter table public.notification_messages
  drop constraint if exists notification_messages_send_type_check;
alter table public.notification_messages
  add constraint notification_messages_send_type_check
  check (send_type is null or send_type in ('manual','automatic','scheduled'));

alter table public.notification_messages
  drop constraint if exists notification_messages_schedule_type_check;
alter table public.notification_messages
  add constraint notification_messages_schedule_type_check
  check (schedule_type is null or schedule_type in ('none','one_time','weekly','every_10_days','every_15_days','monthly','custom'));

create table if not exists public.powerhub_message_templates (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  name text not null,
  description text,
  channel text not null check (channel in ('sms','whatsapp')),
  event_type text,
  body text not null,
  variables jsonb not null default '[]'::jsonb,
  is_active boolean not null default true,
  version integer not null default 1 check (version > 0),
  created_by bigint references public.users(id) on delete set null,
  updated_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint powerhub_message_templates_name_check check (char_length(trim(name)) between 2 and 120),
  constraint powerhub_message_templates_body_check check (char_length(trim(body)) between 1 and 4096)
);


alter table public.powerhub_message_templates
  drop constraint if exists powerhub_message_templates_event_type_check;
alter table public.powerhub_message_templates
  add constraint powerhub_message_templates_event_type_check check (
    event_type is null or event_type in ('invoice_issued','subscriber_created','invoice_overdue','payment_received','service_alert')
  );

create unique index if not exists powerhub_message_templates_unique
  on public.powerhub_message_templates(tenant_id, lower(name), channel, coalesce(event_type, ''));

create index if not exists powerhub_message_templates_lookup_idx
  on public.powerhub_message_templates(tenant_id, channel, event_type, is_active);

create table if not exists public.powerhub_message_automations (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint references public.sites(id) on delete cascade,
  template_id bigint not null references public.powerhub_message_templates(id) on delete restrict,
  name text not null,
  event_type text,
  send_type text not null check (send_type in ('automatic','scheduled')),
  schedule_type text not null default 'none'
    check (schedule_type in ('none','one_time','weekly','every_10_days','every_15_days','monthly','custom')),
  schedule_anchor_at timestamptz,
  timezone text not null default 'Asia/Gaza',
  audience jsonb not null default '{}'::jsonb,

  trigger_config jsonb not null default '{}'::jsonb,
  enabled boolean not null default true,
  created_by bigint references public.users(id) on delete set null,
  updated_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint powerhub_message_automations_name_check check (char_length(trim(name)) between 2 and 120),
  constraint powerhub_message_automations_schedule_check check (
    (send_type = 'automatic' and schedule_type = 'none' and schedule_anchor_at is null)
    or
    (send_type = 'scheduled' and schedule_type <> 'none' and schedule_anchor_at is not null)
  )
);

create unique index if not exists powerhub_message_automations_unique
  on public.powerhub_message_automations(tenant_id, lower(name));

create index if not exists powerhub_message_automations_scope_idx
  on public.powerhub_message_automations(tenant_id, site_id, enabled, send_type, schedule_type);

alter table public.notification_messages
  add constraint notification_messages_template_fk
  foreign key (template_id) references public.powerhub_message_templates(id) on delete set null;

alter table public.notification_messages
  add constraint notification_messages_automation_fk
  foreign key (automation_id) references public.powerhub_message_automations(id) on delete set null;

-- Backfill the classification of existing rows without changing delivery behavior.
update public.notification_messages
set send_type = case
  when coalesce(payload->>'queuedBy','') in ('invoice_issue','invoice_issue_automatic') then 'automatic'
  when coalesce(payload->>'queuedBy','') like '%schedule%' then 'scheduled'
  else 'manual'
end
where send_type is null;

update public.notification_messages
set schedule_type = case coalesce(payload->>'scheduleMode','')
  when 'weekly' then 'weekly'
  when 'every_10_days' then 'every_10_days'
  when 'every_15_days' then 'every_15_days'
  when 'monthly' then 'monthly'
  else 'none'
end
where schedule_type is null;

-- Keep timestamps coherent for future direct updates.
create or replace function public.powerhub_touch_unified_messaging_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $function$
begin
  new.updated_at := now();
  return new;
end;
$function$;

