-- Owner membership overrides complement staff-profile overrides so every owner identity
-- can receive an individual exception even when it has no staff_profiles row.
create table if not exists public.tenant_member_capability_overrides (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null,
  user_id bigint not null,
  capability text not null,
  is_allowed boolean not null,
  updated_by_user_id bigint references public.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  constraint tenant_member_capability_override_unique unique (tenant_id,user_id,capability),
  constraint tenant_member_capability_overrides_member_fk
    foreign key (tenant_id,user_id)
    references public.tenant_members(tenant_id,user_id) on delete cascade,
  constraint tenant_member_capability_overrides_capability_check
    check (capability = any (array[
      'manageSubscribers','manageGenerators','recordReadings','accessFieldApp',
      'approveReadings','manageTariffs','issueInvoices','collectPayments',
      'approvePaymentDocumentation','manageExpenses','managePayroll','manageTeam',
      'manageMessaging','viewAudit','viewInventory','viewSuppliers','viewPurchases',
      'manageInventoryItems','manageSuppliers','createPurchases','approvePurchases',
      'receiveInventory','manageSupplierPayments','viewSupplierLedger','issueInventory',
      'adjustInventory','manageFuelAndConsumption','manageMaintenance','viewInventoryReports',
      'viewStocktakes','manageStocktakes','approveStocktakes',
      'createInventoryItems','editInventoryItems','deactivateInventoryItems',
      'createSuppliers','editSuppliers','deactivateSuppliers',
      'createWarehouses','editWarehouses','deactivateWarehouses','reverseSupplierPayments'
    ]::text[]))
);

create index if not exists tenant_member_capability_overrides_tenant_user_idx
  on public.tenant_member_capability_overrides(tenant_id,user_id);

