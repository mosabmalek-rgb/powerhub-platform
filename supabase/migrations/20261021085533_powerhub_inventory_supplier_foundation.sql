-- PowerHub inventory, purchasing, supplier payable, and payment data foundation.
-- This migration only adds new module tables and a nullable link from account transactions.
-- It does not backfill, mutate, or reinterpret existing expenses or account balances.

-- Composite keys allow new module rows to enforce tenant consistency at the database level.
create unique index if not exists sites_tenant_id_id_unique_idx
  on public.sites (tenant_id, id);
create unique index if not exists company_accounts_tenant_id_id_unique_idx
  on public.company_accounts (tenant_id, id);
create unique index if not exists generators_tenant_id_id_unique_idx
  on public.generators (tenant_id, id);

create table public.inventory_items (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  sku text,
  name text not null check (length(trim(name)) between 1 and 180),
  category text not null default 'other'
    check (category in ('fuel', 'oil', 'filter', 'spare_part', 'maintenance_supply', 'other')),
  base_unit text not null
    check (base_unit in ('liter', 'milliliter', 'piece', 'container', 'kg', 'gram', 'meter', 'set', 'gallon', 'other')),
  reorder_point numeric(14,3) not null default 0 check (reorder_point >= 0),
  specification text,
  notes text,
  is_active boolean not null default true,
  created_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, id)
);

create unique index inventory_items_tenant_sku_unique_idx
  on public.inventory_items (tenant_id, lower(trim(sku)))
  where sku is not null and length(trim(sku)) > 0;
create index inventory_items_tenant_active_name_idx
  on public.inventory_items (tenant_id, is_active, lower(name));

create table public.inventory_warehouses (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint not null,
  code text not null check (length(trim(code)) between 1 and 40),
  name text not null check (length(trim(name)) between 1 and 120),
  notes text,
  is_active boolean not null default true,
  created_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, id),
  unique (tenant_id, site_id, code),
  constraint inventory_warehouses_site_tenant_fk
    foreign key (tenant_id, site_id) references public.sites (tenant_id, id) on delete restrict
);

create index inventory_warehouses_tenant_site_active_idx
  on public.inventory_warehouses (tenant_id, site_id, is_active);

create table public.suppliers (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  supplier_code text,
  name text not null check (length(trim(name)) between 1 and 180),
  contact_name text,
  phone text,
  email text,
  address text,
  tax_number text,
  default_payment_terms_days integer not null default 0
    check (default_payment_terms_days between 0 and 3650),
  notes text,
  is_active boolean not null default true,
  created_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, id)
);

create unique index suppliers_tenant_code_unique_idx
  on public.suppliers (tenant_id, lower(trim(supplier_code)))
  where supplier_code is not null and length(trim(supplier_code)) > 0;
create index suppliers_tenant_active_name_idx
  on public.suppliers (tenant_id, is_active, lower(name));

create table public.supplier_purchases (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint not null,
  supplier_id bigint not null,
  warehouse_id bigint not null,
  purchase_number text not null,
  supplier_invoice_no text,
  invoice_date date not null default current_date,
  due_date date,
  status text not null default 'draft'
    check (status in ('draft', 'confirmed', 'partially_received', 'received', 'cancelled')),
  subtotal_amount numeric(14,2) not null default 0 check (subtotal_amount >= 0),
  discount_amount numeric(14,2) not null default 0 check (discount_amount >= 0),
  tax_amount numeric(14,2) not null default 0 check (tax_amount >= 0),
  other_charges_amount numeric(14,2) not null default 0 check (other_charges_amount >= 0),
  total_amount numeric(14,2) generated always as
    (subtotal_amount - discount_amount + tax_amount + other_charges_amount) stored,
  payment_terms_days integer not null default 0 check (payment_terms_days between 0 and 3650),
  reference_no text,
  notes text,
  operation_key text not null check (length(trim(operation_key)) between 1 and 180),
  received_at timestamptz,
  received_by_user_id bigint references public.users(id) on delete set null,
  confirmed_at timestamptz,
  confirmed_by_user_id bigint references public.users(id) on delete set null,
  cancelled_at timestamptz,
  cancelled_by_user_id bigint references public.users(id) on delete set null,
  created_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, id),
  unique (tenant_id, purchase_number),
  unique (tenant_id, operation_key),
  constraint supplier_purchases_discount_not_above_subtotal_ck
    check (discount_amount <= subtotal_amount),
  constraint supplier_purchases_total_not_negative_ck
    check (subtotal_amount - discount_amount + tax_amount + other_charges_amount >= 0),
  constraint supplier_purchases_site_tenant_fk
    foreign key (tenant_id, site_id) references public.sites (tenant_id, id) on delete restrict,
  constraint supplier_purchases_supplier_tenant_fk
    foreign key (tenant_id, supplier_id) references public.suppliers (tenant_id, id) on delete restrict,
  constraint supplier_purchases_warehouse_tenant_fk
    foreign key (tenant_id, warehouse_id) references public.inventory_warehouses (tenant_id, id) on delete restrict,
  constraint supplier_purchases_received_state_ck
    check (
      status not in ('partially_received', 'received')
      or (received_at is not null and received_by_user_id is not null)
    ),
  constraint supplier_purchases_confirmed_state_ck
    check (
      status not in ('confirmed', 'partially_received', 'received')
      or (confirmed_at is not null and confirmed_by_user_id is not null)
    )
);

create unique index supplier_purchases_supplier_invoice_unique_idx
  on public.supplier_purchases (tenant_id, supplier_id, lower(trim(supplier_invoice_no)))
  where supplier_invoice_no is not null and length(trim(supplier_invoice_no)) > 0 and status <> 'cancelled';
create index supplier_purchases_tenant_site_date_idx
  on public.supplier_purchases (tenant_id, site_id, invoice_date desc, id desc);
create index supplier_purchases_supplier_status_due_idx
  on public.supplier_purchases (tenant_id, supplier_id, status, due_date, id);

create table public.supplier_purchase_lines (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  purchase_id bigint not null,
  item_id bigint not null,
  quantity numeric(14,3) not null check (quantity > 0),
  unit text not null check (length(trim(unit)) between 1 and 40),
  units_to_base_factor numeric(14,6) not null default 1 check (units_to_base_factor > 0),
  unit_price numeric(14,4) not null check (unit_price >= 0),
  discount_amount numeric(14,2) not null default 0 check (discount_amount >= 0),
  tax_amount numeric(14,2) not null default 0 check (tax_amount >= 0),
  line_subtotal numeric(14,2) generated always as (round(quantity * unit_price, 2)) stored,
  line_total numeric(14,2) generated always as
    (round(quantity * unit_price, 2) - discount_amount + tax_amount) stored,
  received_quantity numeric(14,3) not null default 0
    check (received_quantity >= 0 and received_quantity <= quantity),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, id),
  constraint supplier_purchase_lines_discount_ck
    check (discount_amount <= round(quantity * unit_price, 2)),
  constraint supplier_purchase_lines_total_ck
    check (round(quantity * unit_price, 2) - discount_amount + tax_amount >= 0),
  constraint supplier_purchase_lines_purchase_tenant_fk
    foreign key (tenant_id, purchase_id) references public.supplier_purchases (tenant_id, id) on delete restrict,
  constraint supplier_purchase_lines_item_tenant_fk
    foreign key (tenant_id, item_id) references public.inventory_items (tenant_id, id) on delete restrict
);

create index supplier_purchase_lines_purchase_idx
  on public.supplier_purchase_lines (tenant_id, purchase_id, id);
create index supplier_purchase_lines_item_idx
  on public.supplier_purchase_lines (tenant_id, item_id, purchase_id);

