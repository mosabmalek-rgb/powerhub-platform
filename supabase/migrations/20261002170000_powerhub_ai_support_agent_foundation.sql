create or replace function public.chat_ai_admin_upsert_article(
  p_id bigint default null,
  p_title text default null,
  p_primary_question text default null,
  p_alternative_questions jsonb default '[]'::jsonb,
  p_answer text default null,
  p_category text default 'other',
  p_linked_route text default null,
  p_related_operation text default null,
  p_status text default 'draft',
  p_search_aliases text default '',
  p_audience text default 'generator_owner'
)
returns public.chat_knowledge_articles
language plpgsql
security invoker
set search_path=''
volatile
as $$
declare
  v_user bigint;
  v_row public.chat_knowledge_articles;
begin
  select id into v_user from public.users where auth_user_id=(select auth.uid());
  if v_user is null then raise exception 'UNAUTHORIZED'; end if;
  if not private.powerhub_has_platform_capability('manageSupportChat') then raise exception 'FORBIDDEN'; end if;
  if nullif(btrim(p_title),'') is null or nullif(btrim(p_primary_question),'') is null then raise exception 'INVALID_KNOWLEDGE'; end if;
  if nullif(btrim(p_answer),'') is null then raise exception 'INVALID_KNOWLEDGE'; end if;
  if p_status not in ('draft','published','archived') then raise exception 'INVALID_STATUS'; end if;

  if p_id is null then
    insert into public.chat_knowledge_articles(
      title,primary_question,alternative_questions,answer,category,linked_route,related_operation,status,
      search_aliases,audience,source,version,published_at,created_by_user_id,updated_by_user_id
    )
    values(
      btrim(p_title),btrim(p_primary_question),coalesce(p_alternative_questions,'[]'::jsonb),btrim(p_answer),
      coalesce(nullif(btrim(p_category),''),'other'),nullif(btrim(p_linked_route),''),
      nullif(btrim(p_related_operation),''),p_status,nullif(btrim(p_search_aliases),''),
      coalesce(nullif(btrim(p_audience),''),'generator_owner'),'powerhub',1,
      case when p_status='published' then now() else null end,v_user,v_user
    )
    returning * into v_row;
  else
    update public.chat_knowledge_articles
    set title=btrim(p_title),
        primary_question=btrim(p_primary_question),
        alternative_questions=coalesce(p_alternative_questions,'[]'::jsonb),
        answer=btrim(p_answer),
        category=coalesce(nullif(btrim(p_category),''),'other'),
        linked_route=nullif(btrim(p_linked_route),''),
        related_operation=nullif(btrim(p_related_operation),''),
        status=p_status,
        search_aliases=nullif(btrim(p_search_aliases),''),
        audience=coalesce(nullif(btrim(p_audience),''),'generator_owner'),
        version=version+1,
        published_at=case when p_status='published' then coalesce(published_at,now()) else published_at end,
        updated_by_user_id=v_user,
        updated_at=now()
    where id=p_id
    returning * into v_row;

    if not found then raise exception 'NOT_FOUND'; end if;
  end if;

  return v_row;
end;
$$;

