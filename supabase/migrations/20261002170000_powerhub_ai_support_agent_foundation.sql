-- PowerHub AI Support Agent foundation.
-- Knowledge retrieval, per-user context, assistant-message idempotency, safe handoff,
-- admin knowledge management, AI observability, and feedback.
-- The model gateway is intentionally application-side; database functions never call an LLM.

create table if not exists private.chat_ai_settings (
  id boolean primary key default true check (id = true),
  enabled boolean not null default false,
  model text not null default 'openai/gpt-5.5',
  min_retrieval_score numeric(8,5) not null default 0.05000 check (min_retrieval_score >= 0 and min_retrieval_score <= 1),
  max_articles smallint not null default 5 check (max_articles between 1 and 12),
  max_history_messages smallint not null default 12 check (max_history_messages between 2 and 30),
  handoff_on_unknown boolean not null default true,
  updated_by_user_id bigint references public.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists private.chat_ai_runs (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.chat_conversations(id) on delete cascade,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  question text not null,
  decision text not null check (decision in ('answer','clarify','handoff','error')),
  model text,
  top_retrieval_score numeric(8,5),
  retrieved_article_ids bigint[] not null default '{}',
  handoff_id bigint references public.chat_bot_handoffs(id) on delete set null,
  latency_ms integer,
  error_code text,
  created_at timestamptz not null default now()
);

create index if not exists chat_ai_runs_tenant_created_idx
  on private.chat_ai_runs(tenant_id, created_at desc);

create index if not exists chat_ai_runs_conversation_created_idx
  on private.chat_ai_runs(conversation_id, created_at desc);

alter table public.chat_knowledge_articles
  add column if not exists search_aliases text not null default '',
  add column if not exists audience text not null default 'generator_owner',
  add column if not exists source text not null default 'powerhub';

create index if not exists chat_knowledge_articles_search_fts_idx
on public.chat_knowledge_articles
using gin (
  to_tsvector(
    'simple',
    coalesce(title,'') || ' ' ||
    coalesce(primary_question,'') || ' ' ||
    coalesce(alternative_questions::text,'') || ' ' ||
    coalesce(search_aliases,'') || ' ' ||
    coalesce(answer,'')
  )
);

insert into private.chat_ai_settings(id)
values (true)
on conflict (id) do nothing;

-- Search is read-only and limited to published, PowerHub-authored knowledge.
create or replace function public.chat_ai_search_knowledge(
  p_query text,
  p_category text default null,
  p_limit integer default 5
)
returns table(
  article_id bigint,
  title text,
  primary_question text,
  alternative_questions jsonb,
  answer text,
  category text,
  linked_route text,
  related_operation text,
  score real
)
language plpgsql
security definer
set search_path=''
stable
as $$
declare
  v_uid uuid := (select auth.uid());
  v_limit integer := greatest(1, least(coalesce(p_limit,5),12));
  v_query text := nullif(btrim(coalesce(p_query,'')),'');
begin
  if v_uid is null then raise exception 'UNAUTHORIZED'; end if;

  if not exists (
    select 1
    from public.users u
    where u.auth_user_id=v_uid
      and exists (
        select 1
        from public.tenant_members tm
        where tm.user_id=u.id
          and tm.is_active=true
          and tm.membership_status='active'
          and (tm.expires_at is null or tm.expires_at>now())
      )
  ) then
    raise exception 'FORBIDDEN';
  end if;

  if v_query is null then return; end if;

  return query
  select
    a.id,
    a.title,
    a.primary_question,
    a.alternative_questions,
    a.answer,
    a.category,
    a.linked_route,
    a.related_operation,
    ts_rank_cd(
      to_tsvector(
        'simple',
        coalesce(a.title,'') || ' ' ||
        coalesce(a.primary_question,'') || ' ' ||
        coalesce(a.alternative_questions::text,'') || ' ' ||
        coalesce(a.search_aliases,'') || ' ' ||
        coalesce(a.answer,'')
      ),
      plainto_tsquery('simple', v_query)
    )::real
  from public.chat_knowledge_articles a
  where a.status='published'
    and (p_category is null or a.category=p_category)
    and to_tsvector(
      'simple',
      coalesce(a.title,'') || ' ' ||
      coalesce(a.primary_question,'') || ' ' ||
      coalesce(a.alternative_questions::text,'') || ' ' ||
      coalesce(a.search_aliases,'') || ' ' ||
      coalesce(a.answer,'')
    ) @@ plainto_tsquery('simple', v_query)
  order by 10 desc, a.updated_at desc, a.id desc
  limit v_limit;
end;
$$;

revoke all on function public.chat_ai_search_knowledge(text,text,integer) from public, anon;
grant execute on function public.chat_ai_search_knowledge(text,text,integer) to authenticated;

create or replace function public.chat_ai_get_account_context(p_tenant_id bigint)
returns jsonb
language plpgsql
security definer
set search_path=''
stable
as $$
declare
  v_user bigint;
  v_subscription jsonb;
  v_tenant jsonb;
begin
  select u.id into v_user
  from public.users u
  where u.auth_user_id=(select auth.uid());

  if v_user is null then raise exception 'UNAUTHORIZED'; end if;

  if not exists (
    select 1
    from public.tenant_members tm
    where tm.tenant_id=p_tenant_id
      and tm.user_id=v_user
      and tm.is_active=true
      and tm.membership_status='active'
      and (tm.expires_at is null or tm.expires_at>now())
  ) then
    raise exception 'FORBIDDEN';
  end if;

  select jsonb_build_object(
    'status', s.status,
    'package_code', s.package_code,
    'billing_cycle', s.billing_cycle,
    'started_at', s.started_at,
    'ends_at', s.ends_at,
    'auto_renew', s.auto_renew,
    'trial_duration_days', s.trial_duration_days
  )
  into v_subscription
  from public.tenant_subscriptions s
  where s.tenant_id=p_tenant_id
  order by s.created_at desc
  limit 1;

  select jsonb_build_object(
    'tenant_id', t.id,
    'tenant_name', t.name,
    'tenant_status', t.status
  )
  into v_tenant
  from public.tenants t
  where t.id=p_tenant_id;

  return jsonb_build_object(
    'tenant', coalesce(v_tenant,'{}'::jsonb),
    'subscription', coalesce(v_subscription,'{}'::jsonb)
  );
end;
$$;

