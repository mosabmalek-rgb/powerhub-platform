-- PowerHub AI Support Agent foundation.
-- Knowledge retrieval, per-user context, assistant-message idempotency, safe handoff,
-- admin knowledge management, AI observability, and feedback.
-- The model gateway is intentionally application-side; database functions never call an LLM.

create table if not exists private.chat_ai_settings (
  id boolean primary key default true check (id = true),
  enabled boolean not null default false,
  model text not null default 'openai/gpt-5.5',
  min_retrieval_score numeric(8,5) not null default 0.05000 check (min_retrieval_score >= 0 and min_retrieval_score <= 1),
  max_articles smallint not null default 5 check (max_articles between 1 and 12),
  max_history_messages smallint not null default 12 check (max_history_messages between 2 and 30),
  handoff_on_unknown boolean not null default true,
  updated_by_user_id bigint references public.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists private.chat_ai_runs (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.chat_conversations(id) on delete cascade,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  question text not null,
  decision text not null check (decision in ('answer','clarify','handoff','error')),
  model text,
  top_retrieval_score numeric(8,5),
  retrieved_article_ids bigint[] not null default '{}',
  handoff_id bigint references public.chat_bot_handoffs(id) on delete set null,
  latency_ms integer,
  error_code text,
  created_at timestamptz not null default now()
);

create index if not exists chat_ai_runs_tenant_created_idx
  on private.chat_ai_runs(tenant_id, created_at desc);

create index if not exists chat_ai_runs_conversation_created_idx
  on private.chat_ai_runs(conversation_id, created_at desc);

alter table public.chat_knowledge_articles
  add column if not exists search_aliases text not null default '',
  add column if not exists audience text not null default 'generator_owner',
  add column if not exists source text not null default 'powerhub';

create index if not exists chat_knowledge_articles_search_fts_idx
on public.chat_knowledge_articles
using gin (
  to_tsvector(
    'simple',
    coalesce(title,'') || ' ' ||
    coalesce(primary_question,'') || ' ' ||
    coalesce(alternative_questions::text,'') || ' ' ||
    coalesce(search_aliases,'') || ' ' ||
    coalesce(answer,'')
  )
);

insert into private.chat_ai_settings(id)
values (true)
on conflict (id) do nothing;

-- Search is read-only and limited to published, PowerHub-authored knowledge.
create or replace function public.chat_ai_search_knowledge(
  p_query text,
  p_category text default null,
  p_limit integer default 5
)
returns table(
  article_id bigint,
  title text,
  primary_question text,
  alternative_questions jsonb,
  answer text,
  category text,
  linked_route text,
  related_operation text,
  score real
)
language plpgsql
security definer
set search_path=''
stable
as $$
declare
  v_uid uuid := (select auth.uid());
  v_limit integer := greatest(1, least(coalesce(p_limit,5),12));
  v_query text := nullif(btrim(coalesce(p_query,'')),'');
begin
  if v_uid is null then raise exception 'UNAUTHORIZED'; end if;

  if not exists (
    select 1
    from public.users u
    where u.auth_user_id=v_uid
      and exists (
        select 1
        from public.tenant_members tm
        where tm.user_id=u.id
          and tm.is_active=true
          and tm.membership_status='active'
          and (tm.expires_at is null or tm.expires_at>now())
      )
  ) then
    raise exception 'FORBIDDEN';
  end if;

  if v_query is null then return; end if;

  return query
  select
    a.id,
    a.title,
    a.primary_question,
    a.alternative_questions,
    a.answer,
    a.category,
    a.linked_route,
    a.related_operation,
    ts_rank_cd(
      to_tsvector(
        'simple',
        coalesce(a.title,'') || ' ' ||
        coalesce(a.primary_question,'') || ' ' ||
        coalesce(a.alternative_questions::text,'') || ' ' ||
        coalesce(a.search_aliases,'') || ' ' ||
        coalesce(a.answer,'')
      ),
      plainto_tsquery('simple', v_query)
    )::real
  from public.chat_knowledge_articles a
  where a.status='published'
    and (p_category is null or a.category=p_category)
    and to_tsvector(
      'simple',
      coalesce(a.title,'') || ' ' ||
      coalesce(a.primary_question,'') || ' ' ||
      coalesce(a.alternative_questions::text,'') || ' ' ||
      coalesce(a.search_aliases,'') || ' ' ||
      coalesce(a.answer,'')
    ) @@ plainto_tsquery('simple', v_query)
  order by 10 desc, a.updated_at desc, a.id desc
  limit v_limit;
end;
$$;

revoke all on function public.chat_ai_search_knowledge(text,text,integer) from public, anon;
grant execute on function public.chat_ai_search_knowledge(text,text,integer) to authenticated;

create or replace function public.chat_ai_get_account_context(p_tenant_id bigint)
returns jsonb
language plpgsql
security definer
set search_path=''
stable
as $$
declare
  v_user bigint;
  v_subscription jsonb;
  v_tenant jsonb;
begin
  select u.id into v_user
  from public.users u
  where u.auth_user_id=(select auth.uid());

  if v_user is null then raise exception 'UNAUTHORIZED'; end if;

  if not exists (
    select 1
    from public.tenant_members tm
    where tm.tenant_id=p_tenant_id
      and tm.user_id=v_user
      and tm.is_active=true
      and tm.membership_status='active'
      and (tm.expires_at is null or tm.expires_at>now())
  ) then
    raise exception 'FORBIDDEN';
  end if;

  select jsonb_build_object(
    'status', s.status,
    'package_code', s.package_code,
    'billing_cycle', s.billing_cycle,
    'started_at', s.started_at,
    'ends_at', s.ends_at,
    'auto_renew', s.auto_renew,
    'trial_duration_days', s.trial_duration_days
  )
  into v_subscription
  from public.tenant_subscriptions s
  where s.tenant_id=p_tenant_id
  order by s.created_at desc
  limit 1;

  select jsonb_build_object(
    'tenant_id', t.id,
    'tenant_name', t.name,
    'tenant_status', t.status
  )
  into v_tenant
  from public.tenants t
  where t.id=p_tenant_id;

  return jsonb_build_object(
    'tenant', coalesce(v_tenant,'{}'::jsonb),
    'subscription', coalesce(v_subscription,'{}'::jsonb)
  );
end;
$$;

revoke all on function public.chat_ai_get_account_context(bigint) from public, anon;
grant execute on function public.chat_ai_get_account_context(bigint) to authenticated;

create or replace function public.chat_ai_append_assistant_message(
  p_conversation_id bigint,
  p_body text,
  p_client_message_id uuid,
  p_metadata jsonb default '{}'::jsonb
)
returns public.chat_messages
language plpgsql
security definer
set search_path=''
volatile
as $$
declare
  v_user bigint;
  v_conversation public.chat_conversations;
  v_existing public.chat_messages;
  v_message public.chat_messages;
begin
  select id into v_user
  from public.users
  where auth_user_id=(select auth.uid());

  if v_user is null then raise exception 'UNAUTHORIZED'; end if;
  if nullif(btrim(p_body),'') is null then raise exception 'INVALID_BODY'; end if;
  if length(p_body)>12000 then raise exception 'BODY_TOO_LONG'; end if;
  if p_client_message_id is null then raise exception 'CLIENT_MESSAGE_ID_REQUIRED'; end if;

  select * into v_conversation
  from public.chat_conversations
  where id=p_conversation_id
    and conversation_type='assistant';

  if not found then raise exception 'NOT_FOUND'; end if;
  if not private.chat_can_access_conversation(p_conversation_id) then raise exception 'FORBIDDEN'; end if;

  select * into v_existing
  from public.chat_messages
  where conversation_id=p_conversation_id
    and client_message_id=p_client_message_id;

  if found then
    if v_existing.sender_type <> 'assistant' then raise exception 'IDEMPOTENCY_CONFLICT'; end if;
    return v_existing;
  end if;

  insert into public.chat_messages(
    conversation_id,
    tenant_id,
    sender_user_id,
    sender_type,
    message_type,
    visibility,
    body,
    client_message_id,
    metadata
  ) values (
    v_conversation.id,
    v_conversation.tenant_id,
    null,
    'assistant',
    'text',
    'public',
    btrim(p_body),
    p_client_message_id,
    coalesce(p_metadata,'{}'::jsonb)
  )
  returning * into v_message;

  update public.chat_conversations
  set last_message_at=v_message.created_at,
      updated_at=now()
  where id=v_conversation.id;

  return v_message;
end;
$$;

revoke all on function public.chat_ai_append_assistant_message(bigint,text,uuid,jsonb) from public, anon;
grant execute on function public.chat_ai_append_assistant_message(bigint,text,uuid,jsonb) to authenticated;

create or replace function public.chat_ai_handoff(
  p_conversation_id bigint,
  p_user_message_id bigint,
  p_ai_message_id bigint,
  p_trigger text,
  p_reason text,
  p_summary text,
  p_category text default 'other',
  p_priority text default 'normal',
  p_current_page text default null
)
returns public.chat_bot_handoffs
language plpgsql
security definer
set search_path=''
volatile
as $$
declare
  v_user bigint;
  v_conversation public.chat_conversations;
  v_handoff public.chat_bot_handoffs;
  v_ticket text;
  v_support_user bigint;
begin
  select id into v_user
  from public.users
  where auth_user_id=(select auth.uid());

  if v_user is null then raise exception 'UNAUTHORIZED'; end if;

  select * into v_conversation
  from public.chat_conversations
  where id=p_conversation_id
    and conversation_type='assistant';

  if not found then raise exception 'NOT_FOUND'; end if;
  if not private.chat_can_access_conversation(p_conversation_id) then raise exception 'FORBIDDEN'; end if;

  if p_trigger not in ('unknown','insufficient_knowledge','sensitive','user_requested','repeated_failure') then
    raise exception 'INVALID_HANDOFF_TRIGGER';
  end if;

  if p_priority not in ('low','normal','high','urgent') then
    raise exception 'INVALID_PRIORITY';
  end if;

  v_ticket := private.chat_support_ticket_number();

  insert into public.chat_bot_handoffs(
    conversation_id,
    tenant_id,
    trigger,
    reason,
    user_message_id,
    ai_message_id,
    summary,
    category,
    priority,
    current_page,
    context_snapshot
  )
  values(
    v_conversation.id,
    v_conversation.tenant_id,
    p_trigger,
    coalesce(nullif(btrim(p_reason),''),'لم يتم العثور على إجابة موثوقة.'),
    p_user_message_id,
    p_ai_message_id,
    nullif(btrim(p_summary),''),
    coalesce(nullif(btrim(p_category),''),'other'),
    p_priority,
    nullif(btrim(p_current_page),''),
    jsonb_build_object('ticket_number',v_ticket,'source','powerhub_ai')
  )
  returning * into v_handoff;

  update public.chat_conversations
  set conversation_type='support',
      status='SUPPORT_PENDING',
      ticket_number=coalesce(ticket_number,v_ticket),
      category_code=coalesce(category_code,coalesce(nullif(btrim(p_category),''),'other')),
      source='assistant',
      last_customer_message_at=coalesce(last_customer_message_at,last_message_at,created_at),
      priority=p_priority,
      updated_at=now()
  where id=p_conversation_id;

  insert into public.chat_ticket_events(
    conversation_id,
    tenant_id,
    actor_user_id,
    event_type,
    from_status,
    to_status,
    from_priority,
    to_priority,
    metadata
  )
  values(
    p_conversation_id,
    v_conversation.tenant_id,
    v_user,
    'status_changed',
    v_conversation.status,
    'SUPPORT_PENDING',
    v_conversation.priority,
    p_priority,
    jsonb_build_object('trigger',p_trigger,'reason',p_reason,'handoff_id',v_handoff.id)
  );

  for v_support_user in select id from private.chat_support_user_ids() loop
    insert into public.chat_inbox_notifications(
      user_id,
      tenant_id,
      conversation_id,
      message_id,
      notification_type,
      title,
      body
    )
    values(
      v_support_user,
      v_conversation.tenant_id,
      p_conversation_id,
      p_ai_message_id,
      'support_update',
      'طلب دعم جديد من مساعد PowerHub',
      coalesce(v_ticket,'تذكرة دعم') || ' — ' || left(coalesce(p_reason,'تحويل تلقائي للدعم'),180)
    )
    on conflict do nothing;
  end loop;

  return v_handoff;
end;
$$;

revoke all on function public.chat_ai_handoff(bigint,bigint,bigint,text,text,text,text,text,text) from public, anon;
grant execute on function public.chat_ai_handoff(bigint,bigint,bigint,text,text,text,text,text,text) to authenticated;

create or replace function public.chat_ai_rate_message(
  p_message_id bigint,
  p_rating text,
  p_feedback_text text default null
)
returns public.chat_bot_feedback
language plpgsql
security definer
set search_path=''
volatile
as $$
declare
  v_user bigint;
  v_message public.chat_messages;
  v_row public.chat_bot_feedback;
begin
  select id into v_user
  from public.users
  where auth_user_id=(select auth.uid());

  if v_user is null then raise exception 'UNAUTHORIZED'; end if;
  if p_rating not in ('positive','negative') then raise exception 'INVALID_RATING'; end if;

  select * into v_message
  from public.chat_messages
  where id=p_message_id
    and sender_type='assistant';

  if not found then raise exception 'NOT_FOUND'; end if;
  if not private.chat_can_access_conversation(v_message.conversation_id) then raise exception 'FORBIDDEN'; end if;

  insert into public.chat_bot_feedback(conversation_id,message_id,user_id,rating,feedback_text)
  values(v_message.conversation_id,p_message_id,v_user,nullif(btrim(p_rating),''),nullif(btrim(p_feedback_text),''))
  on conflict(message_id,user_id) do update
    set rating=excluded.rating,
        feedback_text=excluded.feedback_text,
        created_at=now()
  returning * into v_row;

  return v_row;
end;
$$;

revoke all on function public.chat_ai_rate_message(bigint,text,text) from public, anon;
grant execute on function public.chat_ai_rate_message(bigint,text,text) to authenticated;

create or replace function public.chat_ai_admin_upsert_article(
  p_id bigint default null,
  p_title text default null,
  p_primary_question text default null,
  p_alternative_questions jsonb default '[]'::jsonb,
  p_answer text default null,
  p_category text default 'other',
  p_linked_route text default null,
  p_related_operation text default null,
  p_status text default 'draft',
  p_search_aliases text default '',
  p_audience text default 'generator_owner'
)
returns public.chat_knowledge_articles
language plpgsql
security invoker
set search_path=''
volatile
as $$
declare
  v_user bigint;
  v_row public.chat_knowledge_articles;
begin
  select id into v_user from public.users where auth_user_id=(select auth.uid());
  if v_user is null then raise exception 'UNAUTHORIZED'; end if;
  if not private.powerhub_has_platform_capability('manageSupportChat') then raise exception 'FORBIDDEN'; end if;
  if nullif(btrim(p_title),'') is null or nullif(btrim(p_primary_question),'') is null then raise exception 'INVALID_KNOWLEDGE'; end if;
  if nullif(btrim(p_answer),'') is null then raise exception 'INVALID_KNOWLEDGE'; end if;
  if p_status not in ('draft','published','archived') then raise exception 'INVALID_STATUS'; end if;

  if p_id is null then
    insert into public.chat_knowledge_articles(
      title,primary_question,alternative_questions,answer,category,linked_route,related_operation,status,
      search_aliases,audience,source,version,published_at,created_by_user_id,updated_by_user_id
    )
    values(
      btrim(p_title),btrim(p_primary_question),coalesce(p_alternative_questions,'[]'::jsonb),btrim(p_answer),
      coalesce(nullif(btrim(p_category),''),'other'),nullif(btrim(p_linked_route),''),
      nullif(btrim(p_related_operation),''),p_status,nullif(btrim(p_search_aliases),''),
      coalesce(nullif(btrim(p_audience),''),'generator_owner'),'powerhub',1,
      case when p_status='published' then now() else null end,v_user,v_user
    )
    returning * into v_row;
  else
    update public.chat_knowledge_articles
    set title=btrim(p_title),
        primary_question=btrim(p_primary_question),
        alternative_questions=coalesce(p_alternative_questions,'[]'::jsonb),
        answer=btrim(p_answer),
        category=coalesce(nullif(btrim(p_category),''),'other'),
        linked_route=nullif(btrim(p_linked_route),''),
        related_operation=nullif(btrim(p_related_operation),''),
        status=p_status,
        search_aliases=nullif(btrim(p_search_aliases),''),
        audience=coalesce(nullif(btrim(p_audience),''),'generator_owner'),
        version=version+1,
        published_at=case when p_status='published' then coalesce(published_at,now()) else published_at end,
        updated_by_user_id=v_user,
        updated_at=now()
    where id=p_id
    returning * into v_row;

    if not found then raise exception 'NOT_FOUND'; end if;
  end if;

  return v_row;
end;
$$;

revoke execute on function public.chat_ai_admin_upsert_article(bigint,text,text,jsonb,text,text,text,text,text,text,text) from public, anon;
grant execute on function public.chat_ai_admin_upsert_article(bigint,text,text,jsonb,text,text,text,text,text,text,text) to authenticated;

create or replace function public.chat_ai_admin_snapshot()
returns jsonb
language plpgsql
security invoker
set search_path=''
stable
as $$
declare v_user bigint;
begin
  select id into v_user from public.users where auth_user_id=(select auth.uid());
  if v_user is null then raise exception 'UNAUTHORIZED'; end if;
  if not private.powerhub_has_platform_capability('manageSupportChat') then raise exception 'FORBIDDEN'; end if;

  return jsonb_build_object(
    'settings', coalesce((select to_jsonb(s) from private.chat_ai_settings s where id=true),'{}'::jsonb),
    'knowledge', jsonb_build_object(
      'total', (select count(*) from public.chat_knowledge_articles),
      'published', (select count(*) from public.chat_knowledge_articles where status='published'),
      'draft', (select count(*) from public.chat_knowledge_articles where status='draft'),
      'archived', (select count(*) from public.chat_knowledge_articles where status='archived')
    ),
    'recentFailures', coalesce((
      select jsonb_agg(to_jsonb(r) order by r.created_at desc)
      from (
        select decision,error_code,question,created_at
        from private.chat_ai_runs
        where decision in ('handoff','error')
        order by created_at desc
        limit 20
      ) r
    ),'[]'::jsonb)
  );
end;
$$;

revoke all on function public.chat_ai_admin_snapshot() from public, anon;
grant execute on function public.chat_ai_admin_snapshot() to authenticated;


