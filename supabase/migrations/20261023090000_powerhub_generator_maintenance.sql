create or replace function public.powerhub_maintenance_create_work_order(
  p_tenant_id bigint,p_site_id bigint,p_user_id bigint,p_generator_id bigint,p_preventive_plan_id bigint,
  p_order_type text,p_priority text,p_title text,p_description text,
  p_reported_at timestamptz,p_scheduled_for timestamptz,p_assigned_to_user_id bigint,
  p_operation_key text
)
returns table(work_order_id bigint,work_order_number text,status text,replayed boolean)
language plpgsql security invoker set search_path=public,pg_temp
as $$
declare
  v_existing public.generator_maintenance_work_orders%rowtype;
  v_order public.generator_maintenance_work_orders%rowtype;
  v_generator public.generators%rowtype;
  v_hash text;
  v_number text;
  v_reported_at timestamptz;
begin
  if p_tenant_id is null or p_site_id is null or p_user_id is null or p_generator_id is null then
    raise exception 'MAINTENANCE_SCOPE_REQUIRED' using errcode='P0001';
  end if;
  if p_operation_key is null or length(btrim(p_operation_key)) not between 1 and 180 then
    raise exception 'INVALID_OPERATION_KEY' using errcode='P0001';
  end if;
  if p_order_type is null or p_priority is null
     or p_order_type not in ('breakdown','preventive','inspection','repair','other')
     or p_priority not in ('low','normal','high','urgent')
     or p_title is null or length(btrim(p_title)) not between 3 and 180
     or length(coalesce(p_description,''))>5000 then
    raise exception 'INVALID_MAINTENANCE_WORK_ORDER' using errcode='P0001';
  end if;
  -- Hash raw caller input so a retry with an omitted timestamp has an identical payload.
  v_hash:=md5(jsonb_build_object('tenant_id',p_tenant_id,'site_id',p_site_id,'generator_id',p_generator_id,
    'preventive_plan_id',p_preventive_plan_id,'order_type',p_order_type,'priority',p_priority,
    'title',btrim(p_title),'description',nullif(btrim(p_description),''),
    'reported_at',p_reported_at,'scheduled_for',p_scheduled_for,'assigned_to_user_id',p_assigned_to_user_id)::text);
  perform pg_advisory_xact_lock(hashtextextended(p_tenant_id::text||':maintenance-create:'||btrim(p_operation_key),0));
  select * into v_existing from public.generator_maintenance_work_orders
    where tenant_id=p_tenant_id and operation_key=btrim(p_operation_key) for update;
  if found then
    if v_existing.operation_payload_hash is distinct from v_hash then
      raise exception 'MAINTENANCE_IDEMPOTENCY_KEY_REUSED' using errcode='P0001';
    end if;
    return query select v_existing.id,v_existing.work_order_number,v_existing.status,true;
    return;
  end if;
  select * into v_generator from public.generators g
    where g.tenant_id=p_tenant_id and g.site_id=p_site_id and g.id=p_generator_id for share;
  if not found then raise exception 'MAINTENANCE_GENERATOR_OUT_OF_SCOPE' using errcode='P0001'; end if;
  if p_order_type='preventive' and p_preventive_plan_id is null then
    raise exception 'MAINTENANCE_PREVENTIVE_PLAN_REQUIRED' using errcode='P0001';
  end if;
  if p_preventive_plan_id is not null and (p_order_type<>'preventive' or not exists(
    select 1 from public.generator_maintenance_preventive_plans pl
    where pl.tenant_id=p_tenant_id and pl.site_id=p_site_id and pl.id=p_preventive_plan_id
      and pl.generator_id=p_generator_id and pl.is_active
  )) then raise exception 'MAINTENANCE_PLAN_OUT_OF_SCOPE' using errcode='P0001'; end if;
  if not exists(select 1 from public.users u where u.id=p_user_id) then
    raise exception 'MAINTENANCE_ACTOR_NOT_FOUND' using errcode='P0001';
  end if;
  if p_assigned_to_user_id is not null and not exists(
    select 1 from public.staff_profiles sp where sp.tenant_id=p_tenant_id and sp.user_id=p_assigned_to_user_id
      and sp.is_active=true and (sp.site_id=p_site_id or sp.site_id is null)
  ) then raise exception 'MAINTENANCE_ASSIGNEE_OUT_OF_SCOPE' using errcode='P0001'; end if;
  v_reported_at:=coalesce(p_reported_at,now());
  v_number:='MW-'||to_char(v_reported_at at time zone 'UTC','YYYYMMDD')||'-'||
    lpad(nextval('public.generator_maintenance_work_order_number_seq')::text,7,'0');
  insert into public.generator_maintenance_work_orders(
    tenant_id,site_id,generator_id,preventive_plan_id,work_order_number,order_type,priority,status,title,description,
    reported_at,scheduled_for,assigned_to_user_id,operating_hours_at_open,operation_key,
    operation_payload_hash,created_by_user_id,updated_by_user_id
  ) values(
    p_tenant_id,p_site_id,p_generator_id,p_preventive_plan_id,v_number,p_order_type,p_priority,
    case when p_scheduled_for is not null and p_scheduled_for>v_reported_at then 'scheduled' else 'new' end,
    btrim(p_title),nullif(btrim(p_description),''),v_reported_at,p_scheduled_for,
    p_assigned_to_user_id,v_generator.operating_hours,btrim(p_operation_key),v_hash,p_user_id,p_user_id
  ) returning * into v_order;
  insert into public.generator_maintenance_audit_events(tenant_id,site_id,actor_user_id,entity_type,entity_id,action,after_data,operation_key)
  values(p_tenant_id,p_site_id,p_user_id,'work_order',v_order.id,'create',
    jsonb_build_object('number',v_order.work_order_number,'status',v_order.status,'generator_id',v_order.generator_id,
      'order_type',v_order.order_type,'priority',v_order.priority),btrim(p_operation_key));
  return query select v_order.id,v_order.work_order_number,v_order.status,false;
end;
$$;

create or replace function public.powerhub_maintenance_assign_supplier(
  p_tenant_id bigint,p_site_id bigint,p_user_id bigint,p_work_order_id bigint,p_supplier_id bigint,p_operation_key text
)
returns table(work_order_id bigint,assigned_supplier_id bigint,replayed boolean)
language plpgsql security invoker set search_path=public,pg_temp
as $maintenance_assign$
declare
  v_order public.generator_maintenance_work_orders%rowtype;
  v_supplier public.suppliers%rowtype;
  v_existing record;
  v_hash text;
  v_previous_supplier_id bigint;
begin
  if p_tenant_id is null or p_site_id is null or p_user_id is null or p_work_order_id is null then
    raise exception 'MAINTENANCE_SCOPE_REQUIRED' using errcode='P0001';
  end if;
  if p_operation_key is null or length(btrim(p_operation_key)) not between 1 and 180 then
    raise exception 'INVALID_OPERATION_KEY' using errcode='P0001';
  end if;
  if not exists(select 1 from public.users where id=p_user_id) then
    raise exception 'MAINTENANCE_ACTOR_NOT_FOUND' using errcode='P0001';
  end if;

  v_hash:=md5(jsonb_build_object('tenant_id',p_tenant_id,'site_id',p_site_id,
    'work_order_id',p_work_order_id,'supplier_id',p_supplier_id)::text);
  perform pg_advisory_xact_lock(hashtextextended(p_tenant_id::text||':maintenance-supplier:'||btrim(p_operation_key),0));

  select a.entity_id,a.after_data into v_existing
    from public.generator_maintenance_audit_events a
    where a.tenant_id=p_tenant_id and a.entity_type='work_order'
      and a.action='assign_supplier' and a.operation_key=btrim(p_operation_key)
    limit 1;
  if found then
    if v_existing.entity_id<>p_work_order_id
       or v_existing.after_data->>'operation_payload_hash' is distinct from v_hash then
      raise exception 'MAINTENANCE_IDEMPOTENCY_KEY_REUSED' using errcode='P0001';
    end if;
    return query select p_work_order_id,(v_existing.after_data->>'assigned_supplier_id')::bigint,true;
    return;
  end if;

  select * into v_order from public.generator_maintenance_work_orders w
    where w.tenant_id=p_tenant_id and w.site_id=p_site_id and w.id=p_work_order_id for update;
  if not found then raise exception 'MAINTENANCE_WORK_ORDER_NOT_FOUND' using errcode='P0001'; end if;
  if v_order.status not in ('scheduled','new','in_progress','waiting_for_parts') then
    raise exception 'MAINTENANCE_WORK_ORDER_NOT_OPEN' using errcode='P0001';
  end if;
  if p_supplier_id is not null then
    select * into v_supplier from public.suppliers s
      where s.tenant_id=p_tenant_id and s.id=p_supplier_id and s.is_active=true for share;
    if not found then raise exception 'MAINTENANCE_SUPPLIER_OUT_OF_SCOPE' using errcode='P0001'; end if;
  end if;

  v_previous_supplier_id:=v_order.assigned_supplier_id;
  update public.generator_maintenance_work_orders set assigned_supplier_id=p_supplier_id,
    updated_by_user_id=p_user_id,updated_at=now()
    where tenant_id=p_tenant_id and site_id=p_site_id and id=p_work_order_id
    returning * into v_order;
  insert into public.generator_maintenance_audit_events(
    tenant_id,site_id,actor_user_id,entity_type,entity_id,action,before_data,after_data,operation_key
  ) values(
    p_tenant_id,p_site_id,p_user_id,'work_order',p_work_order_id,'assign_supplier',
    jsonb_build_object('assigned_supplier_id',v_previous_supplier_id),
    jsonb_build_object('assigned_supplier_id',v_order.assigned_supplier_id,
      'supplier_name',case when p_supplier_id is null then null else v_supplier.name end,
      'operation_payload_hash',v_hash),
    btrim(p_operation_key)
  );
  return query select v_order.id,v_order.assigned_supplier_id,false;
end;
$maintenance_assign$;

create or replace function public.powerhub_maintenance_add_part(
  p_tenant_id bigint,p_site_id bigint,p_user_id bigint,p_work_order_id bigint,
  p_item_id bigint,p_warehouse_id bigint,p_quantity numeric,p_notes text,p_operation_key text
)
returns table(part_id bigint,stock_movement_id bigint,quantity numeric,unit_cost numeric,total_cost_amount numeric,replayed boolean)
language plpgsql security invoker set search_path=public,pg_temp
as $$
declare
  v_order public.generator_maintenance_work_orders%rowtype;
  v_item public.inventory_items%rowtype;
  v_existing public.generator_maintenance_work_order_parts%rowtype;
  v_part public.generator_maintenance_work_order_parts%rowtype;
  v_move record;
  v_hash text;
  v_stock_key text;
begin
  if p_tenant_id is null or p_site_id is null or p_user_id is null or p_work_order_id is null then
    raise exception 'MAINTENANCE_SCOPE_REQUIRED' using errcode='P0001';
  end if;
  if p_operation_key is null or length(btrim(p_operation_key)) not between 1 and 150 then
    raise exception 'INVALID_OPERATION_KEY' using errcode='P0001';
  end if;
  if p_quantity is null or p_quantity<=0 or p_quantity>1000000 or p_quantity*1000<>trunc(p_quantity*1000) then
    raise exception 'INVALID_MAINTENANCE_PART_QUANTITY' using errcode='P0001';
  end if;
  if length(coalesce(p_notes,''))>1000 then raise exception 'INVALID_MAINTENANCE_PART_NOTES' using errcode='P0001'; end if;
  v_hash:=md5(jsonb_build_object('site_id',p_site_id,'work_order_id',p_work_order_id,'item_id',p_item_id,
    'warehouse_id',p_warehouse_id,'quantity',p_quantity,'notes',nullif(btrim(p_notes),''))::text);
  perform pg_advisory_xact_lock(hashtextextended(p_tenant_id::text||':maintenance-part:'||btrim(p_operation_key),0));
  select * into v_existing from public.generator_maintenance_work_order_parts
    where tenant_id=p_tenant_id and operation_key=btrim(p_operation_key) for update;
  if found then
    if v_existing.operation_payload_hash is distinct from v_hash then
      raise exception 'MAINTENANCE_IDEMPOTENCY_KEY_REUSED' using errcode='P0001';
    end if;
    return query select v_existing.id,v_existing.stock_movement_id,v_existing.quantity,v_existing.unit_cost,v_existing.total_cost_amount,true;
    return;
  end if;
  select * into v_order from public.generator_maintenance_work_orders
    where tenant_id=p_tenant_id and site_id=p_site_id and id=p_work_order_id for update;
  if not found then raise exception 'MAINTENANCE_WORK_ORDER_NOT_FOUND' using errcode='P0001'; end if;
  if v_order.status not in ('new','scheduled','in_progress','waiting_for_parts') then
    raise exception 'MAINTENANCE_WORK_ORDER_NOT_OPEN' using errcode='P0001';
  end if;
  select * into v_item from public.inventory_items i
    where i.tenant_id=p_tenant_id and i.id=p_item_id and i.is_active=true for share;
  if not found then raise exception 'MAINTENANCE_PART_ITEM_OUT_OF_SCOPE' using errcode='P0001'; end if;
  if v_item.category not in ('spare_part','oil','filter','maintenance_supply','other') then
    raise exception 'MAINTENANCE_PART_CATEGORY_INVALID' using errcode='P0001';
  end if;
  v_stock_key:='maint-part:'||p_tenant_id::text||':'||md5(btrim(p_operation_key));
  select * into v_move from public.powerhub_inventory_record_stock_movement(
    p_tenant_id,p_site_id,p_user_id,p_warehouse_id,p_item_id,'issue',p_quantity,null,
    v_order.generator_id,v_order.work_order_number,
    concat('صرف قطعة غيار لأمر الصيانة ',v_order.work_order_number,case when nullif(btrim(p_notes),'') is null then '' else ' — '||btrim(p_notes) end),
    v_stock_key
  );
  insert into public.generator_maintenance_work_order_parts(
    tenant_id,site_id,work_order_id,generator_id,item_id,warehouse_id,quantity,unit_cost,total_cost_amount,
    stock_movement_id,operation_key,operation_payload_hash,notes,issued_by_user_id
  ) values(
    p_tenant_id,p_site_id,v_order.id,v_order.generator_id,p_item_id,p_warehouse_id,p_quantity,
    v_move.unit_cost,v_move.total_cost_amount,v_move.movement_id,btrim(p_operation_key),v_hash,
    nullif(btrim(p_notes),''),p_user_id
  ) returning * into v_part;
  update public.generator_maintenance_work_orders w set
    parts_cost=coalesce((select sum(p.total_cost_amount) from public.generator_maintenance_work_order_parts p
      where p.tenant_id=p_tenant_id and p.work_order_id=v_order.id),0),
    total_cost_amount=coalesce((select sum(p.total_cost_amount) from public.generator_maintenance_work_order_parts p
      where p.tenant_id=p_tenant_id and p.work_order_id=v_order.id),0)+w.labor_cost+w.external_service_cost,
    updated_by_user_id=p_user_id,updated_at=now()
  where w.tenant_id=p_tenant_id and w.id=v_order.id;
  insert into public.generator_maintenance_audit_events(tenant_id,site_id,actor_user_id,entity_type,entity_id,action,after_data,operation_key)
  values(p_tenant_id,p_site_id,p_user_id,'work_order_part',v_part.id,'issue',
    jsonb_build_object('work_order_id',v_order.id,'item_id',p_item_id,'warehouse_id',p_warehouse_id,
      'quantity',v_part.quantity,'unit_cost',v_part.unit_cost,'total_cost_amount',v_part.total_cost_amount,
      'stock_movement_id',v_part.stock_movement_id),btrim(p_operation_key));
  return query select v_part.id,v_part.stock_movement_id,v_part.quantity,v_part.unit_cost,v_part.total_cost_amount,false;
end;
$$;

create or replace function public.powerhub_maintenance_transition_work_order(
  p_tenant_id bigint,p_site_id bigint,p_user_id bigint,p_work_order_id bigint,p_action text,
  p_work_summary text default null,p_meter_hours_close numeric default null,p_downtime_minutes integer default null,
  p_labor_cost numeric default 0,p_external_service_cost numeric default 0,p_reason text default null,p_operation_key text default null
)
returns table(work_order_id bigint,work_order_number text,status text,total_cost_amount numeric,replayed boolean)
language plpgsql security invoker set search_path=public,pg_temp
as $$
declare
  v_order public.generator_maintenance_work_orders%rowtype;
  v_generator public.generators%rowtype;
  v_hash text;
  v_replay_hash text;
  v_replay_entity_id bigint;
  v_previous jsonb;
  v_next_status text;
  v_parts_cost numeric(14,2);
  v_latest_hours numeric(14,2);
  v_now timestamptz:=clock_timestamp();
begin
  if p_tenant_id is null or p_site_id is null or p_user_id is null or p_work_order_id is null then
    raise exception 'MAINTENANCE_SCOPE_REQUIRED' using errcode='P0001';
  end if;
  if p_operation_key is null or length(btrim(p_operation_key)) not between 1 and 180 then
    raise exception 'INVALID_OPERATION_KEY' using errcode='P0001';
  end if;
  if p_action not in ('start','wait_for_parts','complete','cancel','correct_completion') then raise exception 'INVALID_MAINTENANCE_ACTION' using errcode='P0001'; end if;
  if coalesce(p_labor_cost,0)<0 or coalesce(p_external_service_cost,0)<0
     or coalesce(p_labor_cost,0)>1000000000 or coalesce(p_external_service_cost,0)>1000000000
     or coalesce(p_labor_cost,0)*100<>trunc(coalesce(p_labor_cost,0)*100)
     or coalesce(p_external_service_cost,0)*100<>trunc(coalesce(p_external_service_cost,0)*100) then
    raise exception 'INVALID_MAINTENANCE_COST' using errcode='P0001';
  end if;
  if p_downtime_minutes is not null and p_downtime_minutes<0 then raise exception 'INVALID_MAINTENANCE_DOWNTIME' using errcode='P0001'; end if;
  if p_action='complete' and (nullif(btrim(p_work_summary),'') is null or length(btrim(p_work_summary))>5000) then
    raise exception 'MAINTENANCE_CLOSEOUT_SUMMARY_REQUIRED' using errcode='P0001';
  end if;
  if p_action='cancel' and (nullif(btrim(p_reason),'') is null or length(btrim(p_reason)) not between 3 and 500) then
    raise exception 'MAINTENANCE_CANCEL_REASON_REQUIRED' using errcode='P0001';
  end if;
  if p_action='correct_completion' and (nullif(btrim(p_reason),'') is null or length(btrim(p_reason)) not between 3 and 500) then
    raise exception 'MAINTENANCE_COMPLETION_CORRECTION_REASON_REQUIRED' using errcode='P0001';
  end if;
  if p_action='correct_completion' and (nullif(btrim(p_work_summary),'') is null or length(btrim(p_work_summary))>5000) then
    raise exception 'MAINTENANCE_COMPLETION_CORRECTION_SUMMARY_REQUIRED' using errcode='P0001';
  end if;
  if p_action='correct_completion' and p_meter_hours_close is not null then
    raise exception 'MAINTENANCE_COMPLETION_CORRECTION_CANNOT_CHANGE_METER' using errcode='P0001';
  end if;
  v_hash:=md5(jsonb_build_object('site_id',p_site_id,'work_order_id',p_work_order_id,'action',p_action,
    'work_summary',nullif(btrim(p_work_summary),''),'meter_hours_close',p_meter_hours_close,
    'downtime_minutes',p_downtime_minutes,
    'labor_cost',case when p_action='correct_completion' then p_labor_cost else coalesce(p_labor_cost,0) end,
    'external_service_cost',case when p_action='correct_completion' then p_external_service_cost else coalesce(p_external_service_cost,0) end,
    'reason',nullif(btrim(p_reason),''))::text);
  perform pg_advisory_xact_lock(hashtextextended(p_tenant_id::text||':maintenance-transition:'||btrim(p_operation_key),0));
  select a.entity_id, a.after_data->>'payload_hash'
    into v_replay_entity_id, v_replay_hash
    from public.generator_maintenance_audit_events a
    where a.tenant_id=p_tenant_id and a.operation_key=btrim(p_operation_key)
      and a.action='transition_operation'
    for update;
  if found then
    if v_replay_hash is distinct from v_hash or v_replay_entity_id is distinct from p_work_order_id then
      raise exception 'MAINTENANCE_IDEMPOTENCY_KEY_REUSED' using errcode='P0001';
    end if;
    select * into v_order from public.generator_maintenance_work_orders
      where tenant_id=p_tenant_id and site_id=p_site_id and id=v_replay_entity_id;
    if not found then raise exception 'MAINTENANCE_WORK_ORDER_NOT_FOUND' using errcode='P0001'; end if;
    return query select v_order.id,v_order.work_order_number,v_order.status,v_order.total_cost_amount,true;
    return;
  end if;
  select * into v_order from public.generator_maintenance_work_orders
    where tenant_id=p_tenant_id and site_id=p_site_id and id=p_work_order_id for update;
  if not found then raise exception 'MAINTENANCE_WORK_ORDER_NOT_FOUND' using errcode='P0001'; end if;
  v_previous:=jsonb_build_object(
    'status',v_order.status,'work_summary',v_order.work_summary,
    'completed_at',v_order.completed_at,'completed_by_user_id',v_order.completed_by_user_id,
    'operating_hours_at_close',v_order.operating_hours_at_close,'downtime_minutes',v_order.downtime_minutes,
    'parts_cost',v_order.parts_cost,'labor_cost',v_order.labor_cost,
    'external_service_cost',v_order.external_service_cost,'total_cost_amount',v_order.total_cost_amount,
    'cancel_reason',v_order.cancel_reason
  );
  if p_action='start' then
    if v_order.status not in ('new','scheduled','waiting_for_parts') then raise exception 'MAINTENANCE_INVALID_STATE_TRANSITION' using errcode='P0001'; end if;
    v_next_status:='in_progress';
    update public.generator_maintenance_work_orders set status=v_next_status,started_at=coalesce(started_at,v_now),
      updated_by_user_id=p_user_id,updated_at=v_now where id=v_order.id and tenant_id=p_tenant_id returning * into v_order;
  elsif p_action='wait_for_parts' then
    if v_order.status<>'in_progress' then raise exception 'MAINTENANCE_INVALID_STATE_TRANSITION' using errcode='P0001'; end if;
    v_next_status:='waiting_for_parts';
    update public.generator_maintenance_work_orders set status=v_next_status,updated_by_user_id=p_user_id,updated_at=v_now
      where id=v_order.id and tenant_id=p_tenant_id returning * into v_order;
  elsif p_action='cancel' then
    if v_order.status not in ('scheduled','new','in_progress','waiting_for_parts') then raise exception 'MAINTENANCE_INVALID_STATE_TRANSITION' using errcode='P0001'; end if;
    v_next_status:='cancelled';
    update public.generator_maintenance_work_orders set status=v_next_status,cancelled_at=v_now,cancel_reason=btrim(p_reason),
      updated_by_user_id=p_user_id,updated_at=v_now where id=v_order.id and tenant_id=p_tenant_id returning * into v_order;
  elsif p_action='correct_completion' then
    if v_order.status<>'completed' then
      raise exception 'MAINTENANCE_COMPLETION_CORRECTION_REQUIRES_COMPLETED_ORDER' using errcode='P0001';
    end if;
    if not exists(select 1 from public.users where id=p_user_id) then
      raise exception 'MAINTENANCE_ACTOR_NOT_FOUND' using errcode='P0001';
    end if;
    v_next_status:='completed';
    update public.generator_maintenance_work_orders set
      work_summary=btrim(p_work_summary),
      downtime_minutes=coalesce(p_downtime_minutes,downtime_minutes),
      labor_cost=coalesce(p_labor_cost,labor_cost),
      external_service_cost=coalesce(p_external_service_cost,external_service_cost),
      total_cost_amount=parts_cost+coalesce(p_labor_cost,labor_cost)+coalesce(p_external_service_cost,external_service_cost),
      updated_by_user_id=p_user_id,updated_at=v_now
    where tenant_id=p_tenant_id and site_id=p_site_id and id=p_work_order_id
    returning * into v_order;
    -- A correction changes the recorded close-out only. It never issues/returns stock,
    -- creates a new meter reading, advances a preventive plan, or posts a second expense.
  else
    if v_order.status not in ('in_progress','waiting_for_parts') then raise exception 'MAINTENANCE_INVALID_STATE_TRANSITION' using errcode='P0001'; end if;
    if not exists(select 1 from public.users where id=p_user_id) then raise exception 'MAINTENANCE_ACTOR_NOT_FOUND' using errcode='P0001'; end if;
    select g.* into v_generator from public.generators g
      where g.tenant_id=p_tenant_id and g.site_id=p_site_id and g.id=v_order.generator_id for update;
    if not found then raise exception 'MAINTENANCE_GENERATOR_OUT_OF_SCOPE' using errcode='P0001'; end if;
    select greatest(coalesce(v_generator.operating_hours,0),coalesce(max(r.reading_value),0)) into v_latest_hours
      from public.generator_fuel_readings r
      where r.tenant_id=p_tenant_id and r.site_id=p_site_id and r.generator_id=v_order.generator_id
        and r.reading_type='operating_hours'
        -- A documented correction supersedes its target; include the correction value, not the stale row.
        and not exists (
          select 1 from public.generator_fuel_readings correction
          where correction.tenant_id=r.tenant_id and correction.corrects_reading_id=r.id
        );
    if p_meter_hours_close is not null and (p_meter_hours_close<coalesce(v_latest_hours,0)
       or p_meter_hours_close>1000000000 or p_meter_hours_close*100<>trunc(p_meter_hours_close*100)) then
      raise exception 'MAINTENANCE_HOURS_BACKWARDS' using errcode='P0001';
    end if;
    if exists(select 1 from public.generator_maintenance_preventive_plans pl
      where pl.tenant_id=p_tenant_id and pl.site_id=p_site_id and pl.generator_id=v_order.generator_id
        and pl.id=v_order.preventive_plan_id and pl.is_active and pl.interval_operating_hours is not null)
      and p_meter_hours_close is null then
      raise exception 'MAINTENANCE_CLOSEOUT_HOURS_REQUIRED' using errcode='P0001';
    end if;
    v_next_status:='completed';
    select coalesce(sum(p.total_cost_amount),0)::numeric(14,2) into v_parts_cost
      from public.generator_maintenance_work_order_parts p where p.tenant_id=p_tenant_id and p.work_order_id=v_order.id;
    update public.generator_maintenance_work_orders set status=v_next_status,work_summary=btrim(p_work_summary),
      operating_hours_at_close=p_meter_hours_close,completed_at=v_now,completed_by_user_id=p_user_id,
      downtime_minutes=coalesce(p_downtime_minutes,downtime_minutes),labor_cost=coalesce(p_labor_cost,0),
      external_service_cost=coalesce(p_external_service_cost,0),parts_cost=v_parts_cost,
      total_cost_amount=v_parts_cost+coalesce(p_labor_cost,0)+coalesce(p_external_service_cost,0),
      updated_by_user_id=p_user_id,updated_at=v_now
      where id=v_order.id and tenant_id=p_tenant_id returning * into v_order;
    -- Persist close-out meter hours in the canonical append-only reading ledger.
    -- This runs in the same transaction: if the reading is invalid, close-out rolls back too.
    if p_meter_hours_close is not null then
      perform * from public.powerhub_inventory_record_fuel_reading(
        p_tenant_id,p_site_id,p_user_id,v_order.generator_id,'operating_hours',null,p_meter_hours_close,v_now,
        'MW closeout '||v_order.work_order_number,
        'قراءة ساعات التشغيل عند إغلاق أمر الصيانة '||v_order.work_order_number,
        null,null,'maintenance-closeout-hours:'||v_order.id::text
      );
    end if;
    update public.generators set last_maintenance_at=v_now,
      operating_hours=coalesce(p_meter_hours_close,operating_hours),updated_at=v_now
      where tenant_id=p_tenant_id and site_id=p_site_id and id=v_order.generator_id;
    update public.generator_maintenance_preventive_plans pl set
      last_completed_at=v_now,
      last_completed_operating_hours=coalesce(p_meter_hours_close,pl.last_completed_operating_hours),
      next_due_at=case when pl.interval_days is null then null else v_now+make_interval(days=>pl.interval_days) end,
      next_due_operating_hours=case when pl.interval_operating_hours is null then null else coalesce(p_meter_hours_close,pl.next_due_operating_hours)+pl.interval_operating_hours end,
      updated_by_user_id=p_user_id,updated_at=v_now
      where pl.tenant_id=p_tenant_id and pl.site_id=p_site_id and pl.generator_id=v_order.generator_id
        and pl.id=v_order.preventive_plan_id and pl.is_active;
    update public.generator_maintenance_alert_events set alert_type='resolved',resolved_at=v_now,updated_at=v_now
      where tenant_id=p_tenant_id and site_id=p_site_id and generator_id=v_order.generator_id
        and v_order.preventive_plan_id is not null and plan_id=v_order.preventive_plan_id
        and alert_type in ('due_soon','overdue');
  end if;
  insert into public.generator_maintenance_audit_events(tenant_id,site_id,actor_user_id,entity_type,entity_id,action,before_data,after_data,operation_key)
  values(p_tenant_id,p_site_id,p_user_id,'work_order',v_order.id,p_action,v_previous,
    jsonb_build_object('status',v_order.status,'work_summary',v_order.work_summary,'operating_hours_at_close',v_order.operating_hours_at_close,
      'completed_at',v_order.completed_at,'completed_by_user_id',v_order.completed_by_user_id,
      'downtime_minutes',v_order.downtime_minutes,'labor_cost',v_order.labor_cost,'external_service_cost',v_order.external_service_cost,
      'parts_cost',v_order.parts_cost,'total_cost_amount',v_order.total_cost_amount,'reason',nullif(btrim(p_reason),''),
      'correction_policy',case when p_action='correct_completion' then 'record-only-no-ledger-side-effects' else null end),
    btrim(p_operation_key));
  if not exists(select 1 from public.generator_maintenance_audit_events
    where tenant_id=p_tenant_id and operation_key=btrim(p_operation_key) and action='transition_operation') then
    insert into public.generator_maintenance_audit_events(tenant_id,site_id,actor_user_id,entity_type,entity_id,action,after_data,operation_key)
    values(p_tenant_id,p_site_id,p_user_id,'work_order',v_order.id,'transition_operation',
      jsonb_build_object('payload_hash',v_hash),btrim(p_operation_key));
  end if;
  return query select v_order.id,v_order.work_order_number,v_order.status,v_order.total_cost_amount,false;
end;
$$;

create or replace function public.powerhub_maintenance_create_preventive_plan(
  p_tenant_id bigint,p_site_id bigint,p_user_id bigint,p_generator_id bigint,p_plan_code text,p_title text,
  p_description text,p_interval_days integer,p_interval_operating_hours numeric,p_next_due_at timestamptz,
  p_next_due_operating_hours numeric,p_due_soon_days integer,p_due_soon_hours numeric,p_operation_key text
)
returns table(plan_id bigint,plan_code text,is_active boolean,replayed boolean)
language plpgsql security invoker set search_path=public,pg_temp
as $$
declare
  v_existing public.generator_maintenance_preventive_plans%rowtype;
  v_plan public.generator_maintenance_preventive_plans%rowtype;
  v_generator public.generators%rowtype;
  v_hash text;
begin
  if p_tenant_id is null or p_site_id is null or p_user_id is null or p_generator_id is null then raise exception 'MAINTENANCE_SCOPE_REQUIRED' using errcode='P0001'; end if;
  if p_operation_key is null or length(btrim(p_operation_key)) not between 1 and 180 then raise exception 'INVALID_OPERATION_KEY' using errcode='P0001'; end if;
  if p_plan_code is null or length(btrim(p_plan_code)) not between 2 and 40 or p_title is null or length(btrim(p_title)) not between 3 and 180 then raise exception 'INVALID_MAINTENANCE_PLAN' using errcode='P0001'; end if;
  if p_interval_days is null and p_interval_operating_hours is null then raise exception 'MAINTENANCE_PLAN_INTERVAL_REQUIRED' using errcode='P0001'; end if;
  if p_interval_days is not null and p_interval_days not between 1 and 3650 then raise exception 'INVALID_MAINTENANCE_PLAN_INTERVAL' using errcode='P0001'; end if;
  if p_interval_operating_hours is not null and (p_interval_operating_hours<=0 or p_interval_operating_hours>1000000 or p_interval_operating_hours*100<>trunc(p_interval_operating_hours*100)) then raise exception 'INVALID_MAINTENANCE_PLAN_INTERVAL' using errcode='P0001'; end if;
  if p_interval_operating_hours is not null and (p_next_due_operating_hours is null or p_next_due_operating_hours<0) then raise exception 'MAINTENANCE_PLAN_HOURS_DUE_REQUIRED' using errcode='P0001'; end if;
  if p_interval_days is not null and p_next_due_at is null then raise exception 'MAINTENANCE_PLAN_DATE_DUE_REQUIRED' using errcode='P0001'; end if;
  if coalesce(p_due_soon_days,7) not between 0 and 365 or coalesce(p_due_soon_hours,10)<0 then raise exception 'INVALID_MAINTENANCE_PLAN_ALERT_WINDOW' using errcode='P0001'; end if;
  v_hash:=md5(jsonb_build_object('site_id',p_site_id,'generator_id',p_generator_id,'plan_code',upper(btrim(p_plan_code)),
    'title',btrim(p_title),'description',nullif(btrim(p_description),''),'interval_days',p_interval_days,
    'interval_operating_hours',p_interval_operating_hours,'next_due_at',p_next_due_at,
    'next_due_operating_hours',p_next_due_operating_hours,'due_soon_days',coalesce(p_due_soon_days,7),
    'due_soon_hours',coalesce(p_due_soon_hours,10))::text);
  perform pg_advisory_xact_lock(hashtextextended(p_tenant_id::text||':maintenance-plan:'||btrim(p_operation_key),0));
  select * into v_existing from public.generator_maintenance_preventive_plans where tenant_id=p_tenant_id and operation_key=btrim(p_operation_key) for update;
  if found then
    if v_existing.operation_payload_hash is distinct from v_hash then raise exception 'MAINTENANCE_IDEMPOTENCY_KEY_REUSED' using errcode='P0001'; end if;
    return query select v_existing.id,v_existing.plan_code,v_existing.is_active,true; return;
  end if;
  select * into v_generator from public.generators g where g.tenant_id=p_tenant_id and g.site_id=p_site_id and g.id=p_generator_id for share;
  if not found then raise exception 'MAINTENANCE_GENERATOR_OUT_OF_SCOPE' using errcode='P0001'; end if;
  if not exists(select 1 from public.users where id=p_user_id) then raise exception 'MAINTENANCE_ACTOR_NOT_FOUND' using errcode='P0001'; end if;
  insert into public.generator_maintenance_preventive_plans(
    tenant_id,site_id,generator_id,plan_code,title,description,interval_days,interval_operating_hours,
    next_due_at,next_due_operating_hours,due_soon_days,due_soon_hours,operation_key,operation_payload_hash,
    created_by_user_id,updated_by_user_id
  ) values(p_tenant_id,p_site_id,p_generator_id,upper(btrim(p_plan_code)),btrim(p_title),nullif(btrim(p_description),''),
    p_interval_days,p_interval_operating_hours,p_next_due_at,p_next_due_operating_hours,coalesce(p_due_soon_days,7),
    coalesce(p_due_soon_hours,10),btrim(p_operation_key),v_hash,p_user_id,p_user_id) returning * into v_plan;
  insert into public.generator_maintenance_audit_events(tenant_id,site_id,actor_user_id,entity_type,entity_id,action,after_data,operation_key)
  values(p_tenant_id,p_site_id,p_user_id,'preventive_plan',v_plan.id,'create',
