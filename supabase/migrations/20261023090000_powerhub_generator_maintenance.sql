create or replace function public.powerhub_maintenance_list_preventive_plans(
  p_tenant_id bigint,p_site_id bigint,p_generator_id bigint default null
)
returns table(plan_id bigint,plan_code text,generator_id bigint,generator_name text,title text,description text,
 interval_days integer,interval_operating_hours numeric,next_due_at timestamptz,next_due_operating_hours numeric,
 due_soon_days integer,due_soon_hours numeric,is_active boolean,last_completed_at timestamptz,
 last_completed_operating_hours numeric,alert_type text,observed_operating_hours numeric)
language sql stable security invoker set search_path=public,pg_temp
as $$
 select p.id,p.plan_code,p.generator_id,g.name,p.title,p.description,p.interval_days,p.interval_operating_hours,
  p.next_due_at,p.next_due_operating_hours,p.due_soon_days,p.due_soon_hours,p.is_active,p.last_completed_at,
  p.last_completed_operating_hours,a.alert_type,g.operating_hours
 from public.generator_maintenance_preventive_plans p
 join public.generators g on g.tenant_id=p.tenant_id and g.site_id=p.site_id and g.id=p.generator_id
 left join public.generator_maintenance_alert_events a on a.tenant_id=p.tenant_id and a.site_id=p.site_id
  and a.plan_id=p.id and a.alert_type in ('due_soon','overdue')
 where p.tenant_id=p_tenant_id and p.site_id=p_site_id and (p_generator_id is null or p.generator_id=p_generator_id)
 order by case when a.alert_type='overdue' then 0 when a.alert_type='due_soon' then 1 else 2 end,
  coalesce(p.next_due_at,'infinity'::timestamptz),p.id;
$$;

