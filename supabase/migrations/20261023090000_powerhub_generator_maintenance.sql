create or replace function public.powerhub_maintenance_evaluate_due_plans(
  p_tenant_id bigint default null,p_site_id bigint default null
)
returns table(alert_event_id bigint,plan_id bigint,generator_id bigint,alert_type text,due_at timestamptz,due_operating_hours numeric,observed_operating_hours numeric,replayed boolean,notification_created boolean)
language plpgsql security invoker set search_path=public,pg_temp
as $maintenance_eval$
declare
  v_plan public.generator_maintenance_preventive_plans%rowtype;
  v_hours numeric(14,2);
  v_type text;
  v_key text;
  v_alert public.generator_maintenance_alert_events%rowtype;
  v_owner_id bigint;
  v_notification_id bigint;
begin
  if (p_tenant_id is null) <> (p_site_id is null) then
    raise exception 'MAINTENANCE_SCOPE_REQUIRED' using errcode='P0001';
  end if;

  for v_plan in
    select pl.* from public.generator_maintenance_preventive_plans pl
    where pl.is_active and (p_tenant_id is null or pl.tenant_id=p_tenant_id)
      and (p_site_id is null or pl.site_id=p_site_id)
    order by pl.tenant_id,pl.site_id,pl.id
    for update
  loop
    select greatest(coalesce(g.operating_hours,0),coalesce((
      select max(r.reading_value) from public.generator_fuel_readings r
      where r.tenant_id=v_plan.tenant_id and r.site_id=v_plan.site_id and r.generator_id=v_plan.generator_id
        and r.reading_type='operating_hours'
        and not exists (
          select 1 from public.generator_fuel_readings correction
          where correction.tenant_id=r.tenant_id and correction.corrects_reading_id=r.id
        )
    ),0)) into v_hours from public.generators g
    where g.tenant_id=v_plan.tenant_id and g.site_id=v_plan.site_id and g.id=v_plan.generator_id;
    if not found then continue; end if;
    if (v_plan.next_due_at is not null and now()>=v_plan.next_due_at)
       or (v_plan.next_due_operating_hours is not null and v_hours>=v_plan.next_due_operating_hours) then
      v_type:='overdue';
    elsif (v_plan.next_due_at is not null and now()>=v_plan.next_due_at-make_interval(days=>v_plan.due_soon_days))
       or (v_plan.next_due_operating_hours is not null and v_hours>=v_plan.next_due_operating_hours-v_plan.due_soon_hours) then
      v_type:='due_soon';
    else
      continue;
    end if;
    v_key:='plan:'||v_plan.id::text||':cycle:'||md5(coalesce(v_plan.next_due_at::text,'-')||':'||coalesce(v_plan.next_due_operating_hours::text,'-'));
    insert into public.generator_maintenance_alert_events(
      tenant_id,site_id,generator_id,plan_id,alert_type,alert_key,due_at,due_operating_hours,observed_operating_hours
    ) values(v_plan.tenant_id,v_plan.site_id,v_plan.generator_id,v_plan.id,v_type,v_key,
      v_plan.next_due_at,v_plan.next_due_operating_hours,v_hours)
    on conflict (tenant_id,alert_key) do update set alert_type=excluded.alert_type,
      observed_operating_hours=excluded.observed_operating_hours,resolved_at=null,updated_at=now()
    returning * into v_alert;

    -- The protected scheduler and page evaluator can both run; the stable recipient/event key
    -- guarantees at most one in-app alert per due cycle and alert type. No SMS is sent here.
    v_owner_id:=null;
    v_notification_id:=null;
    select o.owner_user_id into v_owner_id
      from public.tenant_owner_profiles o
      join public.users u on u.id=o.owner_user_id
      where o.tenant_id=v_plan.tenant_id and o.owner_user_id is not null
        and u.account_status='active'
      limit 1;
    if v_owner_id is not null then
      insert into public.powerhub_user_notifications(
        user_id,tenant_id,notification_type,title,body,target_path,entity_type,entity_id,dedupe_key,metadata
      ) values(
        v_owner_id,v_plan.tenant_id,'system_alert',
        case when v_type='overdue' then 'صيانة وقائية متأخرة' else 'اقترب موعد الصيانة الوقائية' end,
        'الخطة «'||v_plan.title||'» للمولد رقم '||v_plan.generator_id::text||
          case when v_type='overdue' then ' تجاوزت موعد الاستحقاق.' else ' اقترب موعد استحقاقها.' end,
        '/inventory','maintenance_alert',v_alert.id::text,
        'maintenance-alert:'||v_key||':'||v_type,
        jsonb_build_object('site_id',v_plan.site_id,'generator_id',v_plan.generator_id,
          'plan_id',v_plan.id,'alert_type',v_type,'due_at',v_plan.next_due_at,
          'due_operating_hours',v_plan.next_due_operating_hours,'observed_operating_hours',v_hours)
      ) on conflict(user_id,dedupe_key) do nothing returning id into v_notification_id;
    end if;
    return query select v_alert.id,v_alert.plan_id,v_alert.generator_id,v_alert.alert_type,
      v_alert.due_at,v_alert.due_operating_hours,v_alert.observed_operating_hours,false,
      (v_notification_id is not null);
  end loop;
end;
$maintenance_eval$;

create or replace function public.powerhub_maintenance_report_by_generator(
  p_tenant_id bigint,p_site_id bigint,p_from_date date,p_to_date date,p_generator_id bigint default null
)
returns table(
  generator_id bigint,generator_name text,fault_title text,work_order_count bigint,
  breakdown_count bigint,preventive_count bigint,completed_count bigint,open_count bigint,
  downtime_minutes bigint,parts_cost numeric,labor_cost numeric,external_service_cost numeric,
  total_cost_amount numeric,first_reported_at timestamptz,last_reported_at timestamptz
)
language plpgsql stable security invoker set search_path=public,pg_temp
as $maintenance_report$
declare
  v_timezone text;
begin
  if p_tenant_id is null or p_site_id is null or p_from_date is null or p_to_date is null
     or p_from_date>p_to_date or (p_to_date-p_from_date)>365 then
    raise exception 'INVALID_MAINTENANCE_REPORT_RANGE' using errcode='P0001';
  end if;

  select coalesce(nullif(btrim(c.timezone),''),'Asia/Gaza') into v_timezone
    from public.tenant_reading_cycle_configurations c
    where c.tenant_id=p_tenant_id and c.site_id=p_site_id;
  v_timezone:=coalesce(v_timezone,'Asia/Gaza');

  return query
  select w.generator_id,g.name,min(btrim(w.title)),
    count(*)::bigint,
    count(*) filter(where w.order_type='breakdown')::bigint,
    count(*) filter(where w.order_type='preventive')::bigint,
    count(*) filter(where w.status='completed')::bigint,
    count(*) filter(where w.status in ('scheduled','new','in_progress','waiting_for_parts'))::bigint,
    coalesce(sum(w.downtime_minutes),0)::bigint,
    coalesce(sum(w.parts_cost),0)::numeric,
    coalesce(sum(w.labor_cost),0)::numeric,
    coalesce(sum(w.external_service_cost),0)::numeric,
    coalesce(sum(w.total_cost_amount),0)::numeric,
    min(coalesce(w.reported_at,w.created_at)),
    max(coalesce(w.reported_at,w.created_at))
  from public.generator_maintenance_work_orders w
  join public.generators g
    on g.tenant_id=w.tenant_id and g.site_id=w.site_id and g.id=w.generator_id
  where w.tenant_id=p_tenant_id and w.site_id=p_site_id
    and (p_generator_id is null or w.generator_id=p_generator_id)
    and coalesce(w.reported_at,w.created_at) >= (p_from_date::timestamp at time zone v_timezone)
    and coalesce(w.reported_at,w.created_at) < ((p_to_date+1)::timestamp at time zone v_timezone)
  group by w.generator_id,g.name,lower(regexp_replace(btrim(w.title),'[[:space:]]+',' ','g'))
  order by g.name,count(*) desc,min(coalesce(w.reported_at,w.created_at)) desc;
end;
$maintenance_report$;

