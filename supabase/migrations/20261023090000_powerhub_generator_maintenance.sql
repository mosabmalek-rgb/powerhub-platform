create table public.generator_maintenance_work_orders (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint not null,
  generator_id bigint not null,
  work_order_number text not null,
  order_type text not null check (order_type in ('breakdown','preventive','inspection','repair','other')),
  priority text not null default 'normal' check (priority in ('low','normal','high','urgent')),
  status text not null default 'new' check (status in ('scheduled','new','in_progress','waiting_for_parts','completed','cancelled')),
  title text not null check (length(btrim(title)) between 3 and 180),
  description text,
  work_summary text,
  reported_at timestamptz not null default now(),
  scheduled_for timestamptz,
  started_at timestamptz,
  completed_at timestamptz,
  cancelled_at timestamptz,
  assigned_to_user_id bigint references public.users(id) on delete set null,
  assigned_supplier_id bigint,
  preventive_plan_id bigint,
  operating_hours_at_open numeric(14,2),
  operating_hours_at_close numeric(14,2),
  downtime_minutes integer not null default 0 check (downtime_minutes >= 0),
  labor_cost numeric(14,2) not null default 0 check (labor_cost >= 0),
  external_service_cost numeric(14,2) not null default 0 check (external_service_cost >= 0),
  parts_cost numeric(14,2) not null default 0 check (parts_cost >= 0),
  total_cost_amount numeric(14,2) not null default 0 check (total_cost_amount >= 0),
  operation_key text not null,
  operation_payload_hash text not null,
  cancel_reason text,
  created_by_user_id bigint references public.users(id) on delete set null,
  updated_by_user_id bigint references public.users(id) on delete set null,
  completed_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint generator_maintenance_work_orders_generator_fk
    foreign key (tenant_id,site_id,generator_id)
    references public.generators(tenant_id,site_id,id),
  constraint generator_maintenance_work_orders_tenant_site_id_unique
    unique (tenant_id,site_id,id),
  constraint generator_maintenance_work_orders_tenant_site_id_generator_unique
    unique (tenant_id,site_id,id,generator_id),
  constraint generator_maintenance_work_orders_scope_number_unique
    unique (tenant_id,site_id,work_order_number),
  constraint generator_maintenance_work_orders_operation_unique
    unique (tenant_id,operation_key),
  constraint generator_maintenance_work_orders_close_fields_check
    check (status<>'completed' or (completed_at is not null and completed_by_user_id is not null and work_summary is not null)),
  constraint generator_maintenance_work_orders_preventive_plan_check check (
    (order_type='preventive' and preventive_plan_id is not null)
