create table public.tenant_owner_alerts (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint not null references public.sites(id) on delete cascade,
  title text not null,
  message text not null,
  severity text not null default 'warning' check (severity in ('info','warning','critical')),
  created_by_user_id bigint references public.users(id) on delete set null,
  read_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index tenant_owner_alerts_tenant_site_created_idx
  on public.tenant_owner_alerts (tenant_id, site_id, created_at desc);

create index tenant_owner_alerts_unread_idx
  on public.tenant_owner_alerts (tenant_id, site_id, read_at)
  where read_at is null;

alter table public.tenant_owner_alerts enable row level security;

revoke all on table public.tenant_owner_alerts from public, anon, authenticated;
grant all on table public.tenant_owner_alerts to service_role;

revoke all on sequence public.tenant_owner_alerts_id_seq from public, anon, authenticated;
grant all on sequence public.tenant_owner_alerts_id_seq to service_role;