create or replace function public.powerhub_unified_messaging_upsert_automation_v2(
  p_id bigint,
  p_tenant_id bigint,
  p_site_id bigint,
  p_template_id bigint,
  p_name text,
  p_event_type text,
  p_send_type text,
  p_schedule_type text,
  p_schedule_anchor_at timestamptz,
  p_timezone text,
  p_audience jsonb,
  p_trigger_config jsonb,
  p_enabled boolean,
  p_actor_user_id bigint
)
returns bigint
language plpgsql
security invoker
set search_path = public, pg_temp
as $function$
declare
  v_id bigint;
  v_template_tenant bigint;
  v_template_active boolean;
  v_site_tenant bigint;
begin
  if p_send_type not in ('automatic','scheduled') then raise exception 'INVALID_SEND_TYPE' using errcode='22023'; end if;
  if p_send_type='automatic' and (p_schedule_type <> 'none' or p_schedule_anchor_at is not null) then raise exception 'AUTOMATIC_CANNOT_HAVE_SCHEDULE' using errcode='22023'; end if;
  if p_send_type='scheduled' and (p_schedule_type='none' or p_schedule_anchor_at is null) then raise exception 'SCHEDULE_REQUIRED' using errcode='22023'; end if;
  if nullif(trim(coalesce(p_event_type,'')),'') is null then raise exception 'EVENT_TYPE_REQUIRED' using errcode='22023'; end if;
  if p_event_type not in ('invoice_issued','subscriber_created','invoice_overdue','payment_received','service_alert') then
    raise exception 'INVALID_AUTOMATION_EVENT' using errcode='22023';
  end if;

  select tenant_id, is_active into v_template_tenant, v_template_active
  from public.powerhub_message_templates
  where id=p_template_id
  for share;
  if v_template_tenant is null or v_template_tenant <> p_tenant_id or v_template_active is not true then
    raise exception 'TEMPLATE_OUT_OF_SCOPE' using errcode='P0001';
  end if;
  if nullif((select event_type from public.powerhub_message_templates where id=p_template_id),'') is not null
     and (select event_type from public.powerhub_message_templates where id=p_template_id) <> p_event_type then
    raise exception 'TEMPLATE_EVENT_MISMATCH' using errcode='P0001';
  end if;

  if p_site_id is null then
    raise exception 'SITE_REQUIRED' using errcode='P0001';
  end if;
  select tenant_id into v_site_tenant from public.sites where id=p_site_id;
  if v_site_tenant is null or v_site_tenant <> p_tenant_id then
    raise exception 'SITE_OUT_OF_SCOPE' using errcode='P0001';
  end if;

  if coalesce(p_audience->'tags','[]'::jsonb) <> '[]'::jsonb and p_audience ? 'tags' then
    raise exception 'UNSUPPORTED_AUDIENCE_TAGS' using errcode='P0001';
  end if;

  if p_id is not null then
    update public.powerhub_message_automations
    set site_id=p_site_id,
        template_id=p_template_id,
        name=trim(p_name),
        event_type=trim(p_event_type),
        send_type=p_send_type,
        schedule_type=p_schedule_type,
        schedule_anchor_at=p_schedule_anchor_at,
        timezone=coalesce(nullif(trim(p_timezone),''),'Asia/Gaza'),
        audience=coalesce(p_audience,'{}'::jsonb),
        trigger_config=coalesce(p_trigger_config,'{}'::jsonb),
        enabled=coalesce(p_enabled,true),
        archived_at=null,
        updated_by=p_actor_user_id,
        updated_at=now()
    where id=p_id and tenant_id=p_tenant_id
    returning id into v_id;
    if v_id is null then raise exception 'AUTOMATION_NOT_FOUND' using errcode='P0001'; end if;
  else
    insert into public.powerhub_message_automations(
      tenant_id,site_id,template_id,name,event_type,send_type,schedule_type,schedule_anchor_at,
      timezone,audience,trigger_config,enabled,created_by,updated_by,archived_at
    ) values (
      p_tenant_id,p_site_id,p_template_id,trim(p_name),trim(p_event_type),p_send_type,p_schedule_type,p_schedule_anchor_at,
      coalesce(nullif(trim(p_timezone),''),'Asia/Gaza'),coalesce(p_audience,'{}'::jsonb),
      coalesce(p_trigger_config,'{}'::jsonb),coalesce(p_enabled,true),p_actor_user_id,p_actor_user_id,null
    )
    on conflict (tenant_id, lower(name)) do update
      set site_id=excluded.site_id,
          template_id=excluded.template_id,
          event_type=excluded.event_type,
          send_type=excluded.send_type,
          schedule_type=excluded.schedule_type,
          schedule_anchor_at=excluded.schedule_anchor_at,
          timezone=excluded.timezone,
          audience=excluded.audience,
          trigger_config=excluded.trigger_config,
          enabled=excluded.enabled,
          archived_at=null,
          updated_by=p_actor_user_id,
          updated_at=now()
    returning id into v_id;
  end if;

  return v_id;
end;
