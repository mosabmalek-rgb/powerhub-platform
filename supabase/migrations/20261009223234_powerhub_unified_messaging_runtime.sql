create or replace function public.powerhub_public_base_url()
returns text
language plpgsql
stable
security invoker
set search_path = public, pg_temp
as $function$
declare
  v_url text;
begin
  select nullif(trim(value->>'baseUrl'),'')
  into v_url
  from public.platform_settings
  where setting_key = 'powerhub_public_url'
    and is_enabled = true
  limit 1;

  if v_url is null then
    raise exception 'PUBLIC_BASE_URL_NOT_CONFIGURED' using errcode='P0001';
  end if;

  v_url := regexp_replace(v_url, '/+$', '');
  if v_url !~ '^https://[^[:space:]/]+(?:/[^[:space:]]*)?$' then
    raise exception 'PUBLIC_BASE_URL_INVALID' using errcode='P0001';
  end if;

  return v_url;
end;
$function$;

create or replace function public.powerhub_unified_messaging_upsert_template_v2(
  p_id bigint,
  p_tenant_id bigint,
  p_name text,
  p_description text,
  p_channel text,
  p_event_type text,
  p_body text,
  p_variables jsonb,
  p_is_active boolean,
  p_actor_user_id bigint,
  p_invoice_style text default null
)
returns bigint
language plpgsql
security invoker
set search_path = public, pg_temp
as $function$
declare
  v_id bigint;
  v_existing_tenant bigint;
  v_config_id bigint;
begin
  if p_tenant_id is null or p_tenant_id < 1 then raise exception 'INVALID_TENANT_ID' using errcode='22023'; end if;
  if p_channel not in ('sms','whatsapp') then raise exception 'INVALID_CHANNEL' using errcode='22023'; end if;
  if char_length(trim(coalesce(p_name,''))) not between 2 and 120 then raise exception 'INVALID_TEMPLATE_NAME' using errcode='22023'; end if;
  if char_length(trim(coalesce(p_body,''))) not between 1 and 4096 then raise exception 'INVALID_TEMPLATE_BODY' using errcode='22023'; end if;
  if p_event_type is not null and p_event_type not in ('invoice_issued','subscriber_created','invoice_overdue','payment_received','service_alert') then
    raise exception 'INVALID_TEMPLATE_EVENT' using errcode='22023';
  end if;
  if p_invoice_style is not null and p_invoice_style not in ('details','portal_link') then
    raise exception 'INVALID_INVOICE_STYLE' using errcode='22023';
  end if;

  if p_id is not null then
    select tenant_id into v_existing_tenant
    from public.powerhub_message_templates
    where id = p_id
    for update;
    if v_existing_tenant is null then raise exception 'TEMPLATE_NOT_FOUND' using errcode='P0001'; end if;
    if v_existing_tenant <> p_tenant_id then raise exception 'TEMPLATE_OUT_OF_SCOPE' using errcode='P0001'; end if;

    update public.powerhub_message_templates
    set name=trim(p_name),
        description=nullif(trim(p_description),''),
        channel=p_channel,
        event_type=nullif(trim(p_event_type),''),
        body=p_body,
        variables=coalesce(p_variables,'[]'::jsonb),
        is_active=coalesce(p_is_active,true),
        version=version+1,
        updated_by=p_actor_user_id,
        updated_at=now()
    where id=p_id
    returning id into v_id;
  else
    insert into public.powerhub_message_templates(
      tenant_id,name,description,channel,event_type,body,variables,is_active,version,created_by,updated_by
    ) values (
      p_tenant_id,trim(p_name),nullif(trim(p_description),''),p_channel,nullif(trim(p_event_type),''),
      p_body,coalesce(p_variables,'[]'::jsonb),coalesce(p_is_active,true),1,p_actor_user_id,p_actor_user_id
    )
    on conflict (tenant_id, lower(name), channel, coalesce(event_type,'')) do update
      set description=excluded.description,
          body=excluded.body,
          variables=excluded.variables,
          is_active=excluded.is_active,
          version=public.powerhub_message_templates.version+1,
          updated_by=p_actor_user_id,
          updated_at=now()
    returning id into v_id;
  end if;

  if p_channel='sms' and p_event_type='invoice_issued' and p_invoice_style is not null then
    select id into v_config_id
    from public.tenant_messaging_configurations
    where tenant_id=p_tenant_id and channel='sms'
    for update;

    if v_config_id is null then
      raise exception 'SMS_CONFIGURATION_REQUIRED_FOR_INVOICE_STYLE' using errcode='P0001';
    end if;

    update public.tenant_messaging_configurations
    set invoice_message_style=p_invoice_style, updated_at=now()
    where id=v_config_id;
  end if;

  return v_id;
end;
$function$;

