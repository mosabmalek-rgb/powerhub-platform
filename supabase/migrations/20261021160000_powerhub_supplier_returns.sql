  inventory_unit_cost numeric(14,4) not null check (inventory_unit_cost >= 0),
  stock_cost_amount numeric(14,2) generated always as (round(base_quantity*inventory_unit_cost,2)) stored,
  created_at timestamptz not null default now(),
  unique (tenant_id,id),
  unique (tenant_id,return_id,purchase_line_id),
  unique (tenant_id,stock_movement_id),
  constraint supplier_purchase_return_lines_return_tenant_fk
    foreign key (tenant_id,return_id) references public.supplier_purchase_returns(tenant_id,id) on delete restrict,
  constraint supplier_purchase_return_lines_purchase_tenant_fk
    foreign key (tenant_id,purchase_id) references public.supplier_purchases(tenant_id,id) on delete restrict,
  constraint supplier_purchase_return_lines_purchase_line_tenant_fk
    foreign key (tenant_id,purchase_line_id) references public.supplier_purchase_lines(tenant_id,id) on delete restrict,
  constraint supplier_purchase_return_lines_movement_tenant_fk
