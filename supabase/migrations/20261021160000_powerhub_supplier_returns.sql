-- Supplier returns: atomic stock reduction, gross supplier-ledger debit, and optional cash settlement.
-- The cash refund is recorded both as a linked supplier-ledger credit and a company-account deposit.
-- The resulting net supplier-ledger debit equals the amount not refunded in cash.

create sequence if not exists public.supplier_purchase_return_number_seq;

create table public.supplier_purchase_returns (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint not null,
  purchase_id bigint not null,
  supplier_id bigint not null,
  warehouse_id bigint not null,
  return_number text not null,
  return_date date not null default current_date,
  status text not null default 'posted' check (status = 'posted'),
  operation_key text not null check (length(trim(operation_key)) between 1 and 180),
  payload_hash text not null check (length(payload_hash)=32),
  reason text not null check (length(trim(reason)) between 3 and 500),
  notes text,
  total_credit_amount numeric(14,2) not null default 0 check (total_credit_amount >= 0),
  stock_cost_amount numeric(14,2) not null default 0 check (stock_cost_amount >= 0),
  refund_amount numeric(14,2) not null default 0 check (refund_amount >= 0 and refund_amount <= total_credit_amount),
  refund_company_account_id bigint,
  returned_at timestamptz not null default now(),
  returned_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (tenant_id,id),
  unique (tenant_id,return_number),
  unique (tenant_id,operation_key),
  constraint supplier_purchase_returns_refund_account_ck
    check ((refund_amount=0 and refund_company_account_id is null)
      or (refund_amount>0 and refund_company_account_id is not null)),
  constraint supplier_purchase_returns_site_tenant_fk
    foreign key (tenant_id,site_id) references public.sites(tenant_id,id) on delete restrict,
  constraint supplier_purchase_returns_purchase_tenant_fk
    foreign key (tenant_id,purchase_id) references public.supplier_purchases(tenant_id,id) on delete restrict,
  constraint supplier_purchase_returns_supplier_tenant_fk
    foreign key (tenant_id,supplier_id) references public.suppliers(tenant_id,id) on delete restrict,
  constraint supplier_purchase_returns_warehouse_tenant_fk
    foreign key (tenant_id,warehouse_id) references public.inventory_warehouses(tenant_id,id) on delete restrict,
  constraint supplier_purchase_returns_refund_account_tenant_fk
    foreign key (tenant_id,refund_company_account_id) references public.company_accounts(tenant_id,id) on delete restrict
);

create index supplier_purchase_returns_purchase_date_idx
  on public.supplier_purchase_returns(tenant_id,purchase_id,return_date desc,id desc);
create index supplier_purchase_returns_supplier_date_idx
  on public.supplier_purchase_returns(tenant_id,supplier_id,return_date desc,id desc);

create table public.supplier_purchase_return_lines (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  return_id bigint not null,
  purchase_id bigint not null,
  purchase_line_id bigint not null,
