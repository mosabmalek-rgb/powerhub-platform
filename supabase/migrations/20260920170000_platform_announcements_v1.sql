-- Platform-wide in-app announcements
create table if not exists public.platform_announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  announcement_type text not null default 'news'
    check (announcement_type in ('news','announcement','maintenance','alert')),
  status text not null default 'draft'
    check (status in ('draft','scheduled','published','archived')),
  published_at timestamp with time zone null,
  scheduled_at timestamp with time zone null,
  audience_roles text[] not null default array['all']::text[],
  created_by_user_id bigint not null references public.users(id),
  updated_by_user_id bigint null references public.users(id),
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint platform_announcements_title_len check (char_length(btrim(title)) between 2 and 180),
  constraint platform_announcements_body_len check (char_length(btrim(body)) between 2 and 10000),
  constraint platform_announcements_schedule_check check ((status = 'scheduled' and scheduled_at is not null and published_at is null) or (status = 'draft' and scheduled_at is null and published_at is null) or (status = 'published' and published_at is not null and scheduled_at is null) or status = 'archived'),
  constraint platform_announcements_audience_roles_check check (cardinality(audience_roles) between 1 and 7 and audience_roles <@ array['all','owner','manager','accountant','collector','technician','viewer','platform_owner','platform_admin','finance_admin']::text[] and (('all' = any(audience_roles) and cardinality(audience_roles) = 1) or not ('all' = any(audience_roles))))
);
create index if not exists platform_announcements_published_idx on public.platform_announcements(status, published_at desc, id desc);
create index if not exists platform_announcements_created_idx on public.platform_announcements(created_at desc, id desc);
create index if not exists platform_announcements_scheduled_idx on public.platform_announcements(status, scheduled_at asc, id asc);
create index if not exists platform_announcements_audience_gin_idx on public.platform_announcements using gin (audience_roles);
create table if not exists public.platform_announcement_reads (
  id bigint generated by default as identity primary key,
  announcement_id bigint not null references public.platform_announcements(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  read_at timestamp with time zone not null default now(),
  unique (announcement_id, user_id)
);
create index if not exists platform_announcement_reads_user_idx on public.platform_announcement_reads(user_id, read_at desc, announcement_id desc);
create index if not exists platform_announcement_reads_announcement_idx on public.platform_announcement_reads(announcement_id, user_id);
alter table public.platform_announcements enable row level security;
alter table public.platform_announcement_reads enable row level security;
revoke all on public.platform_announcements from anon, authenticated;
revoke all on public.platform_announcement_reads from anon, authenticated;
grant all on public.platform_announcements to service_role;
grant all on public.platform_announcement_reads to service_role;
create or replace function public.powerhub_touch_platform_announcement()
returns trigger language plpgsql security invoker set search_path=public,pg_temp as $$
begin new.updated_at := now(); return new; end;
$$;
drop trigger if exists platform_announcements_touch_updated_at on public.platform_announcements;
create trigger platform_announcements_touch_updated_at before update on public.platform_announcements
for each row execute function public.powerhub_touch_platform_announcement();
