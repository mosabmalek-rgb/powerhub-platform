-- Durable, per-item purchase units. The purchase line keeps the conversion snapshot;
-- a trigger makes every newly inserted/changed purchase line match the configured mapping.
create table public.inventory_item_units (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  item_id bigint not null,
  unit_label text not null check (length(btrim(unit_label)) between 1 and 40),
  factor_to_base numeric(14,6) not null check (factor_to_base > 0),
  is_active boolean not null default true,
  created_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id,id),
  constraint inventory_item_units_item_tenant_fk
    foreign key (tenant_id,item_id) references public.inventory_items(tenant_id,id) on delete restrict
);

create unique index inventory_item_units_label_unique_idx
  on public.inventory_item_units(tenant_id,item_id,lower(btrim(unit_label)));
create index inventory_item_units_active_item_idx
  on public.inventory_item_units(tenant_id,item_id,is_active,lower(btrim(unit_label)));

alter table public.inventory_item_units enable row level security;
revoke all on table public.inventory_item_units from public,anon,authenticated;
grant select,insert,update on table public.inventory_item_units to service_role;
grant usage,select on sequence public.inventory_item_units_id_seq to service_role;

create or replace function public.powerhub_inventory_create_item_unit(
  p_tenant_id bigint,
  p_site_id bigint,
  p_item_id bigint,
  p_user_id bigint,
  p_unit_label text,
  p_factor_to_base numeric
)
returns table(
  id bigint,tenant_id bigint,item_id bigint,unit_label text,factor_to_base numeric,
  is_active boolean,created_at timestamptz,updated_at timestamptz
)
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
declare
  v_item public.inventory_items%rowtype;
  v_unit public.inventory_item_units%rowtype;
  v_platform_role text;
  v_label text:=btrim(coalesce(p_unit_label,''));
begin
  if not exists(select 1 from public.sites s where s.id=p_site_id and s.tenant_id=p_tenant_id) then
    raise exception 'SITE_OUT_OF_SCOPE' using errcode='P0001';
  end if;
  select i.* into v_item from public.inventory_items i
    where i.tenant_id=p_tenant_id and i.id=p_item_id and i.is_active
    for update;
  if not found then raise exception 'INVENTORY_ITEM_NOT_FOUND' using errcode='P0001'; end if;
  if length(v_label) not between 1 and 40 or p_factor_to_base is null
    or p_factor_to_base<=0 or p_factor_to_base>1000000000
    or p_factor_to_base<>round(p_factor_to_base,6) then
    raise exception 'INVALID_ITEM_UNIT_CONVERSION' using errcode='P0001';
  end if;
  if lower(v_label)=lower(v_item.base_unit) then
    raise exception 'ITEM_UNIT_EQUALS_BASE_UNIT' using errcode='P0001';
  end if;
  select coalesce(u.platform_role,'tenant_user') into v_platform_role
    from public.users u where u.id=p_user_id;
  if not found then raise exception 'ACTOR_NOT_FOUND' using errcode='P0001'; end if;

  insert into public.inventory_item_units(
    tenant_id,item_id,unit_label,factor_to_base,created_by_user_id
  ) values (p_tenant_id,p_item_id,v_label,p_factor_to_base,p_user_id)
  returning * into v_unit;

  insert into public.audit_logs(
    tenant_id,site_id,user_id,actor_platform_role,entity_type,entity_id,action,after_data
  ) values (
    p_tenant_id,p_site_id,p_user_id,v_platform_role,'inventory_item_unit',v_unit.id::text,'create',
    jsonb_build_object('itemId',v_unit.item_id,'unitLabel',v_unit.unit_label,
      'factorToBase',v_unit.factor_to_base,'isActive',v_unit.is_active)
  );
  return query select v_unit.id,v_unit.tenant_id,v_unit.item_id,v_unit.unit_label,
    v_unit.factor_to_base,v_unit.is_active,v_unit.created_at,v_unit.updated_at;
end;
$$;

create or replace function public.powerhub_inventory_set_item_unit_active(
  p_tenant_id bigint,
  p_site_id bigint,
  p_item_id bigint,
  p_unit_id bigint,
  p_user_id bigint,
  p_is_active boolean,
  p_reason text default null
)
returns table(
  id bigint,tenant_id bigint,item_id bigint,unit_label text,factor_to_base numeric,
  is_active boolean,created_at timestamptz,updated_at timestamptz
)
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
declare
  v_unit public.inventory_item_units%rowtype;
  v_before jsonb;
  v_platform_role text;
  v_reason text:=nullif(btrim(p_reason),'');
begin
  if not exists(select 1 from public.sites s where s.id=p_site_id and s.tenant_id=p_tenant_id) then
    raise exception 'SITE_OUT_OF_SCOPE' using errcode='P0001';
  end if;
  select u.* into v_unit from public.inventory_item_units u
    where u.tenant_id=p_tenant_id and u.item_id=p_item_id and u.id=p_unit_id
    for update;
  if not found then raise exception 'INVENTORY_ITEM_UNIT_NOT_FOUND' using errcode='P0001'; end if;
  if p_is_active is null then raise exception 'INVALID_ACTIVE_STATE' using errcode='P0001'; end if;
  if not p_is_active and (v_reason is null or length(v_reason)<3) then
    raise exception 'INVENTORY_DEACTIVATION_REASON_REQUIRED' using errcode='P0001';
  end if;
  if v_unit.is_active=p_is_active then
    return query select v_unit.id,v_unit.tenant_id,v_unit.item_id,v_unit.unit_label,
      v_unit.factor_to_base,v_unit.is_active,v_unit.created_at,v_unit.updated_at;
    return;
  end if;
  if not p_is_active and exists(
    select 1 from public.supplier_purchase_lines pl
    join public.supplier_purchases p on p.tenant_id=pl.tenant_id and p.id=pl.purchase_id
    where pl.tenant_id=p_tenant_id and pl.item_id=p_item_id
      and lower(btrim(pl.unit))=lower(btrim(v_unit.unit_label))
      and pl.received_quantity<pl.quantity and p.status in ('draft','confirmed','partially_received')
  ) then
    raise exception 'INVENTORY_ITEM_UNIT_HAS_OPEN_PURCHASE' using errcode='P0001';
  end if;

  v_before:=jsonb_build_object('itemId',v_unit.item_id,'unitLabel',v_unit.unit_label,
    'factorToBase',v_unit.factor_to_base,'isActive',v_unit.is_active);
  select coalesce(u.platform_role,'tenant_user') into v_platform_role
    from public.users u where u.id=p_user_id;
  if not found then raise exception 'ACTOR_NOT_FOUND' using errcode='P0001'; end if;

  update public.inventory_item_units u set is_active=p_is_active,updated_at=now()
    where u.tenant_id=p_tenant_id and u.item_id=p_item_id and u.id=p_unit_id
    returning * into v_unit;
  insert into public.audit_logs(
    tenant_id,site_id,user_id,actor_platform_role,entity_type,entity_id,action,before_data,after_data,reason
  ) values (
    p_tenant_id,p_site_id,p_user_id,v_platform_role,'inventory_item_unit',v_unit.id::text,
    case when p_is_active then 'reactivate' else 'deactivate' end,v_before,
    jsonb_build_object('itemId',v_unit.item_id,'unitLabel',v_unit.unit_label,
      'factorToBase',v_unit.factor_to_base,'isActive',v_unit.is_active),v_reason
  );
  return query select v_unit.id,v_unit.tenant_id,v_unit.item_id,v_unit.unit_label,
    v_unit.factor_to_base,v_unit.is_active,v_unit.created_at,v_unit.updated_at;
end;
$$;

create or replace function public.powerhub_inventory_validate_purchase_line_unit()
returns trigger
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
declare
  v_base_unit text;
  v_expected_factor numeric(14,6);
begin
  select i.base_unit into v_base_unit from public.inventory_items i
    where i.tenant_id=new.tenant_id and i.id=new.item_id;
  if not found then raise exception 'INVENTORY_ITEM_NOT_FOUND' using errcode='P0001'; end if;

  if lower(btrim(new.unit))=lower(btrim(v_base_unit)) then
    v_expected_factor:=1;
  else
    select u.factor_to_base into v_expected_factor
      from public.inventory_item_units u
      where u.tenant_id=new.tenant_id and u.item_id=new.item_id
        and lower(btrim(u.unit_label))=lower(btrim(new.unit)) and u.is_active;
    if not found then raise exception 'PURCHASE_UNIT_NOT_CONFIGURED' using errcode='P0001'; end if;
  end if;
  if new.units_to_base_factor is distinct from v_expected_factor then
    raise exception 'PURCHASE_UNIT_CONVERSION_MISMATCH' using errcode='P0001';
  end if;
  return new;
end;
$$;

drop trigger if exists supplier_purchase_lines_validate_item_unit_trg on public.supplier_purchase_lines;
create trigger supplier_purchase_lines_validate_item_unit_trg
before insert or update of item_id,unit,units_to_base_factor
on public.supplier_purchase_lines
for each row execute function public.powerhub_inventory_validate_purchase_line_unit();

create or replace function public.powerhub_inventory_guard_base_unit_change()
returns trigger
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
begin
  if new.base_unit is distinct from old.base_unit and exists(
    select 1 from public.inventory_item_units u
    where u.tenant_id=old.tenant_id and u.item_id=old.id
  ) then
    raise exception 'ITEM_BASE_UNIT_HAS_PURCHASE_UNITS' using errcode='P0001';
  end if;
  return new;
end;
$$;

drop trigger if exists inventory_items_guard_base_unit_change_trg on public.inventory_items;
create trigger inventory_items_guard_base_unit_change_trg
before update of base_unit on public.inventory_items
for each row execute function public.powerhub_inventory_guard_base_unit_change();

