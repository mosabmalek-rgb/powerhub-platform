-- Bridge the current commercial catalog into normalized package policies.
-- The catalog remains editable through platform_settings; these rows are the runtime-policy bridge.
with package_rows as (
  select
    p->>'code' as package_code,
    p
  from public.platform_settings ps
  cross join lateral jsonb_array_elements(coalesce(ps.value->'packages','[]'::jsonb)) p
  where ps.setting_key='subscription_package_catalog'
    and ps.is_enabled=true
    and coalesce((p->>'active')::boolean,true)=true
),
policies as (
  select package_code,'subscriber_management' feature_key,'included' policy,
         nullif(p->'features'->'subscribers'->>'limit','')::integer default_limit,'fixed' limit_mode from package_rows
  union all select package_code,'branch_management','included',nullif(p->'features'->'branches'->>'limit','')::integer,'fixed' from package_rows
  union all select package_code,'sms','included',nullif(p->'features'->'sms'->>'limit','')::integer,'fixed' from package_rows
  union all select package_code,'field_users','included',nullif(p->>'fieldUsers','')::integer,'fixed' from package_rows
  union all select package_code,'platform_users','included',nullif(p->>'platformUsers','')::integer,'fixed' from package_rows
  union all select package_code,'subscriber_portal','included',null,'unlimited' from package_rows
  union all select package_code,'subscriber_portal_logo',
    case coalesce(p->>'logoPolicy','not_included') when 'included' then 'included' when 'addon' then 'addon' else 'not_included' end,
    case when coalesce(p->>'logoPolicy','not_included')='addon' then null else null end,'unlimited' from package_rows
  union all select package_code,'payment_documentation',
    case coalesce(p->>'paymentDocumentationPolicy','not_included') when 'included' then 'included' when 'addon' then 'addon' else 'not_included' end,
    null,'unlimited' from package_rows
  union all select package_code,'reports','included',null,'unlimited' from package_rows
  union all select package_code,'company_accounts','included',null,'unlimited' from package_rows
  union all select package_code,'human_resources','included',null,'unlimited' from package_rows
  union all select package_code,'attendance','included',null,'unlimited' from package_rows
  union all select package_code,'payroll','included',null,'unlimited' from package_rows
  union all select package_code,'financial_settlements','included',null,'unlimited' from package_rows
  union all select package_code,'mobile_sync','included',null,'unlimited' from package_rows
)
insert into public.package_feature_policies(package_code,feature_key,policy,default_limit,limit_mode,source)
select package_code,feature_key,policy,default_limit,limit_mode,'catalog'
from policies
on conflict (package_code,feature_key) do update set
  policy=excluded.policy,
  default_limit=excluded.default_limit,
  limit_mode=excluded.limit_mode,
  source='catalog',
  updated_at=now();

-- Do not materialize tenant rows yet. Absence of an override means inherit,
-- which keeps existing production behavior unchanged during rollout.

create or replace function public.powerhub_admin_feature_catalog()
returns table(
  feature_key text,
  name text,
  description text,
  category text,
  feature_type text,
  limit_type text,
  enforcement_mode text,
  is_active boolean,
  sort_order integer
)
language sql
stable
security definer
set search_path to 'public','pg_temp'
as $$
  select feature_key,name,description,category,feature_type,limit_type,enforcement_mode,is_active,sort_order
  from public.feature_catalog
  where is_active=true
  order by sort_order, feature_key;
$$;

create or replace function public.powerhub_admin_tenant_feature_controls(p_tenant_id bigint)
returns table(
  tenant_id bigint,
  feature_key text,
  status text,
  limit_mode text,
  manual_limit integer,
  override_reason text,
  updated_by_user_id bigint,
  updated_at timestamptz
)
language sql
stable
security definer
set search_path to 'public','pg_temp'
as $$
  select c.tenant_id,c.feature_key,c.status,c.limit_mode,c.manual_limit,c.override_reason,c.updated_by_user_id,c.updated_at
  from public.tenant_feature_controls c
  where c.tenant_id=p_tenant_id
  order by c.feature_key;
$$;

revoke all on function public.powerhub_admin_feature_catalog() from public, anon, authenticated;
revoke all on function public.powerhub_admin_tenant_feature_controls(bigint) from public, anon, authenticated;
grant execute on function public.powerhub_admin_feature_catalog() to service_role;
grant execute on function public.powerhub_admin_tenant_feature_controls(bigint) to service_role;

