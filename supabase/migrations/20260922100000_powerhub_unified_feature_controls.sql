-- PowerHub unified tenant feature controls.
-- Commercial package JSON remains the source of package pricing/catalog during the transition.
-- This migration introduces a normalized runtime control layer without removing legacy controls.

create table if not exists public.feature_catalog (
  feature_key text primary key,
  name text not null,
  description text not null default '',
  category text not null,
  feature_type text not null default 'capability'
    check (feature_type in ('capability','quota','addon','hybrid')),
  limit_type text not null default 'none'
    check (limit_type in ('none','count','messages','branches','users')),
  enforcement_mode text not null default 'server'
    check (enforcement_mode in ('server','rpc','provider','mixed')),
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.package_feature_policies (
  package_code text not null,
  feature_key text not null references public.feature_catalog(feature_key) on delete cascade,
  policy text not null
    check (policy in ('included','addon','not_included')),
  default_limit integer,
  limit_mode text not null default 'inherit'
    check (limit_mode in ('inherit','fixed','unlimited')),
  source text not null default 'catalog'
    check (source in ('catalog','legacy_bridge','manual')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (package_code, feature_key),
  check (default_limit is null or default_limit >= 0)
);

create table if not exists public.tenant_feature_controls (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  feature_key text not null references public.feature_catalog(feature_key) on delete cascade,
  status text not null default 'inherit'
    check (status in ('inherit','enabled','disabled')),
  limit_mode text not null default 'inherit'
    check (limit_mode in ('inherit','manual','unlimited')),
  manual_limit integer,
  override_reason text,
  updated_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, feature_key),
  check (manual_limit is null or manual_limit >= 0),
  check (
    (limit_mode = 'manual' and manual_limit is not null)
    or (limit_mode <> 'manual' and manual_limit is null)
  )
);

create table if not exists public.tenant_feature_control_audit (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  feature_key text not null references public.feature_catalog(feature_key) on delete cascade,
  actor_user_id bigint references public.users(id) on delete set null,
  action text not null
    check (action in ('create','update','reset')),
  before_data jsonb,
  after_data jsonb,
  reason text,
  created_at timestamptz not null default now()
);

create index if not exists idx_package_feature_policies_feature
  on public.package_feature_policies(feature_key);

create index if not exists idx_tenant_feature_controls_tenant
  on public.tenant_feature_controls(tenant_id);

create index if not exists idx_tenant_feature_controls_feature
  on public.tenant_feature_controls(feature_key);

create index if not exists idx_tenant_feature_control_audit_tenant
  on public.tenant_feature_control_audit(tenant_id, created_at desc);

alter table public.feature_catalog enable row level security;
alter table public.package_feature_policies enable row level security;
alter table public.tenant_feature_controls enable row level security;
alter table public.tenant_feature_control_audit enable row level security;

