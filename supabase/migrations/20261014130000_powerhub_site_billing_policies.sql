create or replace function public.powerhub_save_site_billing_policy(
  p_user_id bigint,p_tenant_id bigint,p_site_id bigint,p_minimum_mode text,p_minimum_consumption_kwh numeric,p_minimum_invoice_amount numeric,
  p_automatic_fraction_discount_enabled boolean,p_automatic_fraction_discount_min_tenth integer,p_automatic_fraction_discount_max_tenth integer,
  p_fraction_carry_enabled boolean,p_fraction_carry_min_tenth integer,p_fraction_carry_max_tenth integer
)
returns table(minimum_mode text,minimum_consumption_kwh numeric,minimum_invoice_amount numeric,
  automatic_fraction_discount_enabled boolean,automatic_fraction_discount_min_tenth integer,automatic_fraction_discount_max_tenth integer,
  fraction_carry_enabled boolean,fraction_carry_min_tenth integer,fraction_carry_max_tenth integer)
language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_allowed boolean;
begin
  if p_minimum_mode not in ('disabled','kwh','amount') then raise exception 'INVALID_MINIMUM_MODE' using errcode='P0001'; end if;
  if p_minimum_mode='kwh' and (p_minimum_consumption_kwh is null or p_minimum_consumption_kwh<=0) then raise exception 'INVALID_MINIMUM_KWH' using errcode='P0001'; end if;
  if p_minimum_mode='amount' and (p_minimum_invoice_amount is null or p_minimum_invoice_amount<=0) then raise exception 'INVALID_MINIMUM_AMOUNT' using errcode='P0001'; end if;
  if p_automatic_fraction_discount_min_tenth not between 0 and 9 or p_automatic_fraction_discount_max_tenth not between 0 and 9
     or p_fraction_carry_min_tenth not between 0 and 9 or p_fraction_carry_max_tenth not between 0 and 9
     or p_automatic_fraction_discount_min_tenth>p_automatic_fraction_discount_max_tenth
     or p_fraction_carry_min_tenth>p_fraction_carry_max_tenth then
    raise exception 'INVALID_FRACTION_RANGE' using errcode='P0001';
  end if;
  if p_automatic_fraction_discount_enabled and p_fraction_carry_enabled
     and p_automatic_fraction_discount_min_tenth<=p_fraction_carry_max_tenth
     and p_fraction_carry_min_tenth<=p_automatic_fraction_discount_max_tenth then
    raise exception 'FRACTION_RANGES_OVERLAP' using errcode='P0001';
  end if;
  select
    exists(select 1 from public.users u where u.id=p_user_id and u.account_status='active'
      and u.platform_role in ('platform_owner','platform_admin','finance_admin'))
    or exists(
      select 1 from public.tenant_members m
      where m.tenant_id=p_tenant_id and m.user_id=p_user_id
        and m.is_active and m.membership_status='active' and m.role='owner'
    )
    or exists(
      select 1 from public.tenant_members m
      join public.staff_profiles s on s.user_id=m.user_id and s.tenant_id=m.tenant_id
        and s.site_id=p_site_id and s.is_active
      where m.tenant_id=p_tenant_id and m.user_id=p_user_id and m.is_active and m.membership_status='active'
        and s.role='owner' and (s.suspension_ends_at is null or s.suspension_ends_at<=now())
    ) into v_allowed;
  if not v_allowed then raise exception 'BILLING_POLICY_PERMISSION_REQUIRED' using errcode='P0001'; end if;
  if not exists(select 1 from public.sites where id=p_site_id and tenant_id=p_tenant_id) then raise exception 'SITE_OUT_OF_SCOPE' using errcode='P0001'; end if;

  insert into public.site_billing_policies(
    tenant_id,site_id,minimum_mode,minimum_consumption_kwh,minimum_invoice_amount,
    automatic_fraction_discount_enabled,automatic_fraction_discount_min_tenth,automatic_fraction_discount_max_tenth,
    fraction_carry_enabled,fraction_carry_min_tenth,fraction_carry_max_tenth,updated_by,updated_at
  ) values (
    p_tenant_id,p_site_id,p_minimum_mode,
    case when p_minimum_mode='kwh' then p_minimum_consumption_kwh else null end,
    case when p_minimum_mode='amount' then p_minimum_invoice_amount else null end,
    p_automatic_fraction_discount_enabled,p_automatic_fraction_discount_min_tenth,p_automatic_fraction_discount_max_tenth,
    p_fraction_carry_enabled,p_fraction_carry_min_tenth,p_fraction_carry_max_tenth,p_user_id,now()
  )
  on conflict (tenant_id,site_id) do update set
    minimum_mode=excluded.minimum_mode,minimum_consumption_kwh=excluded.minimum_consumption_kwh,minimum_invoice_amount=excluded.minimum_invoice_amount,
    automatic_fraction_discount_enabled=excluded.automatic_fraction_discount_enabled,
    automatic_fraction_discount_min_tenth=excluded.automatic_fraction_discount_min_tenth,automatic_fraction_discount_max_tenth=excluded.automatic_fraction_discount_max_tenth,
    fraction_carry_enabled=excluded.fraction_carry_enabled,fraction_carry_min_tenth=excluded.fraction_carry_min_tenth,fraction_carry_max_tenth=excluded.fraction_carry_max_tenth,
    updated_by=excluded.updated_by,updated_at=now();

  insert into public.audit_logs(tenant_id,site_id,user_id,actor_tenant_role,entity_type,entity_id,action,after_data)
  values(p_tenant_id,p_site_id,p_user_id,'owner','site_billing_policy',p_site_id::text,'configure',
    jsonb_build_object('minimumMode',p_minimum_mode,'minimumConsumptionKwh',case when p_minimum_mode='kwh' then p_minimum_consumption_kwh else null end,
      'minimumInvoiceAmount',case when p_minimum_mode='amount' then p_minimum_invoice_amount else null end,
      'automaticFractionDiscountEnabled',p_automatic_fraction_discount_enabled,'automaticFractionDiscountRange',jsonb_build_array(p_automatic_fraction_discount_min_tenth,p_automatic_fraction_discount_max_tenth),
      'fractionCarryEnabled',p_fraction_carry_enabled,'fractionCarryRange',jsonb_build_array(p_fraction_carry_min_tenth,p_fraction_carry_max_tenth)));
  return query select p_minimum_mode,case when p_minimum_mode='kwh' then p_minimum_consumption_kwh else null end,
    case when p_minimum_mode='amount' then p_minimum_invoice_amount else null end,
    p_automatic_fraction_discount_enabled,p_automatic_fraction_discount_min_tenth,p_automatic_fraction_discount_max_tenth,
    p_fraction_carry_enabled,p_fraction_carry_min_tenth,p_fraction_carry_max_tenth;
end;$$;
revoke execute on function public.powerhub_save_site_billing_policy(bigint,bigint,bigint,text,numeric,numeric,boolean,integer,integer,boolean,integer,integer) from public,anon,authenticated;
grant execute on function public.powerhub_save_site_billing_policy(bigint,bigint,bigint,text,numeric,numeric,boolean,integer,integer,boolean,integer,integer) to service_role;

create or replace function public.powerhub_issue_invoice_from_reading(
  p_tenant_id bigint,
  p_site_id bigint,
  p_user_id bigint,
  p_reading_id bigint,
  p_tariff_id bigint,
  p_billing_period text,
  p_due_date timestamptz,
  p_discount_amount numeric,
  p_client_operation_id uuid
)
returns table(invoice_id bigint,invoice_no text,total_amount numeric,replayed boolean)
language plpgsql security invoker set search_path=public,pg_temp as $$
declare
  v_reading public.meter_readings%rowtype;
  v_subscriber public.subscribers%rowtype;
  v_site public.sites%rowtype;
  v_tariff public.tariffs%rowtype;
  v_existing public.invoices%rowtype;
  v_response jsonb;
  v_invoice_id bigint;
  v_invoice_no text;
  v_energy_amount numeric(14,2);
  v_actual_energy_amount numeric(14,2);
  v_minimum_kwh_adjustment numeric(14,2) := 0;
  v_minimum_amount_adjustment numeric(14,2) := 0;
  v_raw_total numeric(14,2);
  v_auto_fraction_discount numeric(14,2) := 0;
  v_fraction_to_carry numeric(14,2) := 0;
  v_fraction_digit integer := 0;
  v_previous_carry numeric(14,2) := 0;
  v_policy public.site_billing_policies%rowtype;
  v_pending record;
  v_adjustment_id bigint;
  v_display_order integer;
  v_tax_amount numeric(14,2);
  v_total_amount numeric(14,2);
  v_platform_role text;
  v_sequence bigint;
  v_invoice_year integer;
begin
  if p_billing_period !~ '^[0-9]{4}-[0-9]{2}$' then raise exception 'INVALID_BILLING_PERIOD' using errcode='P0001'; end if;
  if p_discount_amount<0 then raise exception 'INVALID_DISCOUNT' using errcode='P0001'; end if;
  if p_client_operation_id is not null then
    select response into v_response from public.offline_sync_operations
    where user_id=p_user_id and client_operation_id=p_client_operation_id::text limit 1;
    if found then
      if not exists (
        select 1 from public.offline_sync_operations
        where user_id=p_user_id and client_operation_id=p_client_operation_id::text
          and tenant_id=p_tenant_id and site_id=p_site_id and operation_type='invoice_issue'
          and entity_type='invoice'
      ) then
        raise exception 'INVOICE_OPERATION_SCOPE_CONFLICT' using errcode='P0001';
      end if;
      if coalesce(v_response->>'id','')='' or coalesce(v_response->>'invoiceNo','')='' then raise exception 'INVALID_INVOICE_OPERATION_REPLAY' using errcode='P0001'; end if;
      return query select (v_response->>'id')::bigint,v_response->>'invoiceNo',(v_response->>'totalAmount')::numeric,true;
      return;
    end if;
  end if;

  perform pg_advisory_xact_lock(p_reading_id);
  select r.* into v_reading from public.meter_readings r where r.id=p_reading_id and r.tenant_id=p_tenant_id for update;
  if not found then raise exception 'READING_OUT_OF_SCOPE' using errcode='P0001'; end if;
  select * into v_subscriber from public.subscribers where id=v_reading.subscriber_id and tenant_id=p_tenant_id and site_id=p_site_id;
  if not found then raise exception 'READING_OUT_OF_SCOPE' using errcode='P0001'; end if;
  select * into v_site from public.sites where id=p_site_id and tenant_id=p_tenant_id;
  if not found then raise exception 'SITE_OUT_OF_SCOPE' using errcode='P0001'; end if;
  if v_reading.status<>'approved' then raise exception 'READING_NOT_APPROVED' using errcode='P0001'; end if;
  select * into v_existing from public.invoices where reading_id=p_reading_id limit 1;
  if found then return query select v_existing.id,v_existing.invoice_no,v_existing.total_amount,true; return; end if;
  if exists(select 1 from public.financial_settlements where tenant_id=p_tenant_id and site_id=p_site_id and status='locked' and period_start<=p_due_date and period_end>=p_due_date) then raise exception 'FINANCIAL_PERIOD_LOCKED' using errcode='P0001'; end if;
  select * into v_tariff from public.tariffs where id=p_tariff_id and tenant_id=p_tenant_id and site_id=p_site_id and is_active=true;
  if not found then raise exception 'TARIFF_NOT_FOUND' using errcode='P0001'; end if;

  select * into v_policy
  from public.site_billing_policies
  where tenant_id=p_tenant_id and site_id=p_site_id;
  if not found then
    v_policy.minimum_mode := 'disabled';
    v_policy.minimum_consumption_kwh := null;
    v_policy.minimum_invoice_amount := null;
    v_policy.automatic_fraction_discount_enabled := false;
    v_policy.automatic_fraction_discount_min_tenth := 1;
    v_policy.automatic_fraction_discount_max_tenth := 5;
    v_policy.fraction_carry_enabled := false;
    v_policy.fraction_carry_min_tenth := 6;
    v_policy.fraction_carry_max_tenth := 9;
  end if;

  -- Lock pending carry ledger rows before summing so concurrent invoices cannot
  -- apply the same carried debt twice. The locks and state changes are in this transaction.
  for v_pending in
    select id, invoice_id, amount
    from public.billing_adjustments
    where tenant_id=p_tenant_id and site_id=p_site_id and subscriber_id=v_subscriber.id
      and adjustment_type='fraction_carried' and state='pending'
    order by id
    for update
  loop
    v_previous_carry := v_previous_carry + v_pending.amount;
  end loop;

  -- Allocate from a persistent per-year sequence. The row-level upsert serializes
  -- concurrent issuances and, unlike COUNT(invoices), never reuses a deleted number.
  v_invoice_year:=left(p_billing_period,4)::integer;
  insert into public.powerhub_invoice_sequences(invoice_year,next_sequence)
  values(v_invoice_year,2)
  on conflict (invoice_year) do update
    set next_sequence=public.powerhub_invoice_sequences.next_sequence+1
  returning next_sequence-1 into v_sequence;
  if not found or v_sequence is null or v_sequence < 1 then raise exception 'INVOICE_SEQUENCE_INVALID' using errcode='P0001'; end if;
  v_invoice_no:=format('INV-%s-%s',v_invoice_year,lpad(v_sequence::text,8,'0'));

  -- The recorded meter consumption stays factual. Minimum billable consumption
  -- is represented as an explicit adjustment line rather than changing the reading.
  v_actual_energy_amount := round(coalesce(v_reading.consumption_kwh,0)*v_tariff.price_per_kwh,2);
  v_energy_amount := v_actual_energy_amount;
  if v_policy.minimum_mode='kwh' then
    v_energy_amount := round(greatest(coalesce(v_reading.consumption_kwh,0),coalesce(v_policy.minimum_consumption_kwh,0))*v_tariff.price_per_kwh,2);
    v_minimum_kwh_adjustment := greatest(0,round(v_energy_amount-v_actual_energy_amount,2));
  end if;

  v_tax_amount := round((v_energy_amount+v_tariff.fixed_fee)*(v_tariff.tax_rate/100),2);
  v_raw_total := greatest(0,round(v_energy_amount+v_tariff.fixed_fee+v_tax_amount-p_discount_amount,2));
  if p_discount_amount > round(v_energy_amount+v_tariff.fixed_fee+v_tax_amount,2) then
    raise exception 'INVALID_DISCOUNT' using errcode='P0001';
  end if;

  -- Minimum amount is the final pre-fractional floor (tax-inclusive), after
  -- the caller's ordinary invoice discount. It is not itself a taxable item.
  if v_policy.minimum_mode='amount'
     and v_raw_total < coalesce(v_policy.minimum_invoice_amount,0) then
    v_minimum_amount_adjustment := round(coalesce(v_policy.minimum_invoice_amount,0)-v_raw_total,2);
    v_raw_total := coalesce(v_policy.minimum_invoice_amount,0);
  end if;
  v_fraction_digit := floor(mod(v_raw_total,1)*10)::integer;
  if v_raw_total > 0 then
    if coalesce(v_policy.automatic_fraction_discount_enabled,false)
       and v_fraction_digit between coalesce(v_policy.automatic_fraction_discount_min_tenth,1)
                                and coalesce(v_policy.automatic_fraction_discount_max_tenth,5) then
      v_auto_fraction_discount := round(v_raw_total-trunc(v_raw_total),2);
    elsif coalesce(v_policy.fraction_carry_enabled,false)
       and v_fraction_digit between coalesce(v_policy.fraction_carry_min_tenth,6)
                                and coalesce(v_policy.fraction_carry_max_tenth,9) then
      v_fraction_to_carry := round(v_raw_total-trunc(v_raw_total),2);
    end if;
  end if;
  v_total_amount := round(greatest(0,v_raw_total-v_auto_fraction_discount-v_fraction_to_carry)+v_previous_carry,2);
  insert into public.invoices(tenant_id,site_id,subscriber_id,reading_id,tariff_id,invoice_no,client_operation_id,billing_period,due_date,previous_reading,current_reading,consumption_kwh,price_per_kwh,fixed_fee,tax_amount,discount_amount,total_amount,balance_due,status,created_by_user_id)
  values(p_tenant_id,p_site_id,v_subscriber.id,p_reading_id,v_tariff.id,v_invoice_no,p_client_operation_id::text,p_billing_period,p_due_date,v_reading.previous_reading_value,v_reading.reading_value,coalesce(v_reading.consumption_kwh,0),v_tariff.price_per_kwh,v_tariff.fixed_fee,v_tax_amount,round(p_discount_amount+v_auto_fraction_discount,2),v_total_amount,v_total_amount,'issued',p_user_id)
  returning id into v_invoice_id;

  insert into public.invoice_lines(tenant_id,invoice_id,line_type,description,quantity,unit_price,amount,display_order)
  values(p_tenant_id,v_invoice_id,'energy','استهلاك الكهرباء',coalesce(v_reading.consumption_kwh,0),v_tariff.price_per_kwh,v_actual_energy_amount,1);
  if v_minimum_kwh_adjustment>0 then
    insert into public.invoice_lines(tenant_id,invoice_id,line_type,description,quantity,unit_price,amount,display_order)
    values(p_tenant_id,v_invoice_id,'other',format('تسوية الحد الأدنى للاستهلاك — استهلاك مفوتر لا يقل عن %s ك.و.س',to_char(v_policy.minimum_consumption_kwh,'FM999999990.000')),1,v_tariff.price_per_kwh,v_minimum_kwh_adjustment,2);
  end if;
  insert into public.invoice_lines(tenant_id,invoice_id,line_type,description,quantity,unit_price,amount,display_order)
  values(p_tenant_id,v_invoice_id,'fixed_fee','رسم ثابت',1,v_tariff.fixed_fee,v_tariff.fixed_fee,3),
        (p_tenant_id,v_invoice_id,'tax','الضريبة',1,v_tariff.tax_rate,v_tax_amount,4);
  if v_minimum_amount_adjustment>0 then
    insert into public.invoice_lines(tenant_id,invoice_id,line_type,description,quantity,unit_price,amount,display_order)
    values(p_tenant_id,v_invoice_id,'other','تسوية الحد الأدنى لمبلغ الفاتورة',1,v_minimum_amount_adjustment,v_minimum_amount_adjustment,5);
  end if;
  if p_discount_amount>0 then
    insert into public.invoice_lines(tenant_id,invoice_id,line_type,description,quantity,unit_price,amount,display_order)
    values(p_tenant_id,v_invoice_id,'discount','خصم',1,p_discount_amount,p_discount_amount,6);
  end if;
  if v_auto_fraction_discount>0 then
    insert into public.invoice_lines(tenant_id,invoice_id,line_type,description,quantity,unit_price,amount,display_order)
    values(p_tenant_id,v_invoice_id,'discount','خصم تلقائي لتسوية كسر الفاتورة',1,v_auto_fraction_discount,v_auto_fraction_discount,7);
    insert into public.billing_adjustments(tenant_id,site_id,subscriber_id,invoice_id,adjustment_type,amount,state,idempotency_key,created_by_user_id,metadata)
    values(p_tenant_id,p_site_id,v_subscriber.id,v_invoice_id,'auto_fraction_discount',v_auto_fraction_discount,'applied',format('invoice:%s:auto-fraction-discount',v_invoice_id),p_user_id,
      jsonb_build_object('fractionDigit',v_fraction_digit,'ruleMin',v_policy.automatic_fraction_discount_min_tenth,'ruleMax',v_policy.automatic_fraction_discount_max_tenth));
  end if;
  if v_fraction_to_carry>0 then
    insert into public.invoice_lines(tenant_id,invoice_id,line_type,description,quantity,unit_price,amount,display_order)
    values(p_tenant_id,v_invoice_id,'other','كسر مُرحّل إلى الفاتورة التالية',1,-v_fraction_to_carry,-v_fraction_to_carry,8);
    insert into public.billing_adjustments(tenant_id,site_id,subscriber_id,invoice_id,adjustment_type,amount,state,idempotency_key,created_by_user_id,metadata)
    values(p_tenant_id,p_site_id,v_subscriber.id,v_invoice_id,'fraction_carried',v_fraction_to_carry,'pending',format('invoice:%s:fraction-carry',v_invoice_id),p_user_id,
      jsonb_build_object('fractionDigit',v_fraction_digit,'ruleMin',v_policy.fraction_carry_min_tenth,'ruleMax',v_policy.fraction_carry_max_tenth));
  end if;

  -- Show each earlier carried amount as a distinct, auditable line on this invoice.
  v_display_order := 20;
  for v_pending in
    select id, invoice_id, amount
    from public.billing_adjustments
    where tenant_id=p_tenant_id and site_id=p_site_id and subscriber_id=v_subscriber.id
      and adjustment_type='fraction_carried' and state='pending'
    order by id
    for update
  loop
    if v_pending.invoice_id <> v_invoice_id then
      insert into public.invoice_lines(tenant_id,invoice_id,line_type,description,quantity,unit_price,amount,display_order)
      values(p_tenant_id,v_invoice_id,'other',format('رصيد كسر مرحّل من الفاتورة %s',coalesce((select invoice_no from public.invoices where id=v_pending.invoice_id),'—')),1,v_pending.amount,v_pending.amount,v_display_order);
      v_display_order := v_display_order + 1;
      update public.billing_adjustments set state='applied',applied_to_invoice_id=v_invoice_id
      where id=v_pending.id and state='pending';
      insert into public.billing_adjustments(tenant_id,site_id,subscriber_id,invoice_id,adjustment_type,amount,state,source_adjustment_id,source_invoice_id,idempotency_key,created_by_user_id,metadata)
      values(p_tenant_id,p_site_id,v_subscriber.id,v_invoice_id,'carried_debt_applied',v_pending.amount,'applied',v_pending.id,v_pending.invoice_id,
        format('invoice:%s:carried:%s',v_invoice_id,v_pending.id),p_user_id,jsonb_build_object('carriedAdjustmentId',v_pending.id));
    end if;
  end loop;

  select platform_role into v_platform_role from public.users where id=p_user_id;
  insert into public.audit_logs(tenant_id,site_id,user_id,actor_platform_role,entity_type,entity_id,action,after_data)
  values(p_tenant_id,p_site_id,p_user_id,v_platform_role,'invoice',v_invoice_id::text,'issue',
    jsonb_build_object('readingId',p_reading_id,'tariffId',p_tariff_id,'invoiceNo',v_invoice_no,'billingPeriod',p_billing_period,'totalAmount',v_total_amount,
      'actualConsumptionKwh',coalesce(v_reading.consumption_kwh,0),'minimumConsumptionAdjustment',v_minimum_kwh_adjustment,
      'minimumAmountAdjustment',v_minimum_amount_adjustment,'manualOrCallerDiscount',p_discount_amount,
      'automaticFractionDiscount',v_auto_fraction_discount,'fractionCarried',v_fraction_to_carry,'previousCarryApplied',v_previous_carry,
      'deliveryQueued',false));
  if p_client_operation_id is not null then
    insert into public.offline_sync_operations(tenant_id,site_id,user_id,client_operation_id,operation_type,entity_type,entity_id,response)
    values(p_tenant_id,p_site_id,p_user_id,p_client_operation_id::text,'invoice_issue','invoice',v_invoice_id,jsonb_build_object('id',v_invoice_id,'invoiceNo',v_invoice_no,'totalAmount',v_total_amount));
  end if;
  return query select v_invoice_id,v_invoice_no,v_total_amount,false;
