-- Site-scoped minimum billing, fractional invoice settlement, and auditable carry-forward ledger.
-- Safe defaults preserve existing invoice calculations until an owner explicitly enables a policy.
create table if not exists public.site_billing_policies (
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint not null references public.sites(id) on delete cascade,
  minimum_mode text not null default 'disabled' check (minimum_mode in ('disabled','kwh','amount')),
  minimum_consumption_kwh numeric(15,3) check (minimum_consumption_kwh is null or minimum_consumption_kwh > 0),
  minimum_invoice_amount numeric(14,2) check (minimum_invoice_amount is null or minimum_invoice_amount > 0),
  automatic_fraction_discount_enabled boolean not null default false,
  automatic_fraction_discount_min_tenth integer not null default 1 check (automatic_fraction_discount_min_tenth between 0 and 9),
  automatic_fraction_discount_max_tenth integer not null default 5 check (automatic_fraction_discount_max_tenth between 0 and 9),
  fraction_carry_enabled boolean not null default false,
  fraction_carry_min_tenth integer not null default 6 check (fraction_carry_min_tenth between 0 and 9),
  fraction_carry_max_tenth integer not null default 9 check (fraction_carry_max_tenth between 0 and 9),
  updated_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (tenant_id, site_id),
  unique (site_id),
  check (automatic_fraction_discount_min_tenth <= automatic_fraction_discount_max_tenth),
  check (fraction_carry_min_tenth <= fraction_carry_max_tenth),
  check (minimum_mode <> 'kwh' or minimum_consumption_kwh is not null),
  check (minimum_mode <> 'amount' or minimum_invoice_amount is not null),
  check (not (automatic_fraction_discount_enabled and fraction_carry_enabled)
    or automatic_fraction_discount_max_tenth < fraction_carry_min_tenth
    or fraction_carry_max_tenth < automatic_fraction_discount_min_tenth)
);
alter table public.site_billing_policies enable row level security;
revoke all on table public.site_billing_policies from public, anon, authenticated;
grant select, insert, update, delete on table public.site_billing_policies to service_role;

create table if not exists public.billing_adjustments (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint not null references public.sites(id) on delete restrict,
  subscriber_id bigint not null references public.subscribers(id) on delete restrict,
  invoice_id bigint not null references public.invoices(id) on delete cascade,
  adjustment_type text not null check (adjustment_type in ('auto_fraction_discount','fraction_carried','carried_debt_applied','manual_collection_discount')),
  amount numeric(14,2) not null check (amount > 0),
  state text not null default 'applied' check (state in ('pending','applied','void')),
  source_adjustment_id bigint references public.billing_adjustments(id) on delete restrict,
  source_invoice_id bigint references public.invoices(id) on delete restrict,
  applied_to_invoice_id bigint references public.invoices(id) on delete restrict,
  idempotency_key text not null,
  created_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  unique (site_id, idempotency_key),
  check ((adjustment_type <> 'fraction_carried') or (state in ('pending','applied','void')))
);
create index if not exists billing_adjustments_pending_carry_idx
  on public.billing_adjustments(tenant_id,site_id,subscriber_id,id)
  where adjustment_type='fraction_carried' and state='pending';
create index if not exists billing_adjustments_site_created_idx
  on public.billing_adjustments(tenant_id,site_id,created_at desc);
alter table public.billing_adjustments enable row level security;
revoke all on table public.billing_adjustments from public, anon, authenticated;
grant select, insert, update, delete on table public.billing_adjustments to service_role;

create or replace function public.powerhub_get_site_billing_policy(p_tenant_id bigint,p_site_id bigint)
returns table(
  minimum_mode text,minimum_consumption_kwh numeric,minimum_invoice_amount numeric,
  automatic_fraction_discount_enabled boolean,automatic_fraction_discount_min_tenth integer,automatic_fraction_discount_max_tenth integer,
  fraction_carry_enabled boolean,fraction_carry_min_tenth integer,fraction_carry_max_tenth integer
)
language plpgsql security invoker set search_path=public,pg_temp as $$
begin
  if not exists(select 1 from public.sites where id=p_site_id and tenant_id=p_tenant_id) then
    raise exception 'SITE_OUT_OF_SCOPE' using errcode='P0001';
  end if;
  return query
  select coalesce(p.minimum_mode,'disabled'),p.minimum_consumption_kwh,p.minimum_invoice_amount,
    coalesce(p.automatic_fraction_discount_enabled,false),coalesce(p.automatic_fraction_discount_min_tenth,1),coalesce(p.automatic_fraction_discount_max_tenth,5),
    coalesce(p.fraction_carry_enabled,false),coalesce(p.fraction_carry_min_tenth,6),coalesce(p.fraction_carry_max_tenth,9)
  from (select 1) as seed
  left join public.site_billing_policies p on p.tenant_id=p_tenant_id and p.site_id=p_site_id;
end;$$;
revoke execute on function public.powerhub_get_site_billing_policy(bigint,bigint) from public,anon,authenticated;
