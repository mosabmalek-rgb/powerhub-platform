-- Maintain a temporal, auditable history of electricity prices.
-- Validity uses half-open intervals [valid_from, valid_to), so adjacent prices cannot overlap.
create table if not exists public.tariff_price_history (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete restrict,
  site_id bigint not null references public.sites(id) on delete restrict,
  tariff_id bigint not null references public.tariffs(id) on delete restrict,
  price_per_kwh numeric not null check (price_per_kwh >= 0),
  fixed_fee numeric not null default 0 check (fixed_fee >= 0),
  tax_rate numeric not null default 0 check (tax_rate between 0 and 100),
  is_active boolean not null,
  valid_from timestamptz not null,
  valid_to timestamptz,
  change_kind text not null check (change_kind in ('created', 'price_changed', 'activated', 'deactivated', 'legacy_snapshot')),
  created_at timestamptz not null default now(),
  constraint tariff_price_history_valid_range_check check (valid_to is null or valid_to > valid_from)
);

alter table public.tariff_price_history enable row level security;
revoke all on table public.tariff_price_history from public, anon, authenticated;
grant select on table public.tariff_price_history to service_role;

create unique index if not exists tariff_price_history_tariff_valid_from_key
  on public.tariff_price_history(tariff_id, valid_from);
create unique index if not exists tariff_price_history_one_open_version
  on public.tariff_price_history(tariff_id) where valid_to is null;
create index if not exists tariff_price_history_site_period_idx
  on public.tariff_price_history(site_id, valid_from desc, id desc);
create index if not exists tariff_price_history_tenant_site_period_idx
  on public.tariff_price_history(tenant_id, site_id, valid_from desc);

-- Recover versions that the prior RPC preserved in before_data/after_data.
-- Historical values that were overwritten without audit data cannot be reconstructed.
insert into public.tariff_price_history(
  tenant_id, site_id, tariff_id, price_per_kwh, fixed_fee, tax_rate, is_active,
  valid_from, valid_to, change_kind, created_at
)
select
  a.tenant_id,
  a.site_id,
  a.entity_id::bigint,
  (a.before_data->>'pricePerKwh')::numeric,
  coalesce((a.before_data->>'fixedFee')::numeric, 0),
  coalesce((a.before_data->>'taxRate')::numeric, 0),
  coalesce((a.before_data->>'isActive')::boolean, true),
  (a.before_data->>'effectiveFrom')::timestamptz,
  (a.after_data->>'effectiveFrom')::timestamptz,
  'legacy_snapshot',
  a.created_at
from public.audit_logs a
where a.entity_type = 'tariff'
  and a.action = 'update'
  and a.entity_id ~ '^[0-9]+$'
  and a.before_data ? 'pricePerKwh'
  and a.before_data ? 'effectiveFrom'
  and a.after_data ? 'effectiveFrom'
  and (a.after_data->>'effectiveFrom')::timestamptz > (a.before_data->>'effectiveFrom')::timestamptz
on conflict (tariff_id, valid_from) do nothing;

-- Preserve the currently stored version for existing tariffs that do not already have a current history row.
insert into public.tariff_price_history(
  tenant_id, site_id, tariff_id, price_per_kwh, fixed_fee, tax_rate, is_active,
  valid_from, valid_to, change_kind, created_at
)
select t.tenant_id, t.site_id, t.id, t.price_per_kwh, t.fixed_fee, t.tax_rate, t.is_active,
       t.effective_from, null, 'legacy_snapshot', t.created_at
from public.tariffs t
where not exists (
  select 1 from public.tariff_price_history h
  where h.tariff_id = t.id and h.valid_to is null
)
on conflict (tariff_id, valid_from) do nothing;

create or replace function public.powerhub_tariff_history_before_update()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
begin
  if new.price_per_kwh is distinct from old.price_per_kwh
     or new.fixed_fee is distinct from old.fixed_fee
     or new.tax_rate is distinct from old.tax_rate
     or new.is_active is distinct from old.is_active then
    new.effective_from := greatest(clock_timestamp(), old.effective_from + interval '1 microsecond');
  else
    -- Metadata-only writes must not reset the effective start of an unchanged price.
    new.effective_from := old.effective_from;
  end if;
  return new;
end;
$function$;

create or replace function public.powerhub_tariff_history_after_write()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  v_closed integer := 0;
  v_kind text;
begin
  if tg_op = 'INSERT' then
    insert into public.tariff_price_history(
      tenant_id, site_id, tariff_id, price_per_kwh, fixed_fee, tax_rate, is_active,
      valid_from, valid_to, change_kind
    ) values (
      new.tenant_id, new.site_id, new.id, new.price_per_kwh, new.fixed_fee, new.tax_rate, new.is_active,
      new.effective_from, null, case when new.is_active then 'created' else 'deactivated' end
    );
    return new;
  end if;

  if old.price_per_kwh is not distinct from new.price_per_kwh
     and old.fixed_fee is not distinct from new.fixed_fee
     and old.tax_rate is not distinct from new.tax_rate
     and old.is_active is not distinct from new.is_active then
    return new;
  end if;

  update public.tariff_price_history
     set valid_to = new.effective_from
   where tariff_id = old.id and valid_to is null;
  get diagnostics v_closed = row_count;

  if v_closed = 0 then
    insert into public.tariff_price_history(
      tenant_id, site_id, tariff_id, price_per_kwh, fixed_fee, tax_rate, is_active,
      valid_from, valid_to, change_kind
    ) values (
      old.tenant_id, old.site_id, old.id, old.price_per_kwh, old.fixed_fee, old.tax_rate, old.is_active,
      old.effective_from, new.effective_from, 'legacy_snapshot'
    );
  end if;

  v_kind := case
    when old.is_active is distinct from new.is_active and new.is_active then 'activated'
    when old.is_active is distinct from new.is_active and not new.is_active then 'deactivated'
    else 'price_changed'
  end;

  insert into public.tariff_price_history(
    tenant_id, site_id, tariff_id, price_per_kwh, fixed_fee, tax_rate, is_active,
    valid_from, valid_to, change_kind
  ) values (
    new.tenant_id, new.site_id, new.id, new.price_per_kwh, new.fixed_fee, new.tax_rate, new.is_active,
    new.effective_from, null, v_kind
  );
  return new;
end;
$function$;

drop trigger if exists powerhub_tariff_history_before_update on public.tariffs;
create trigger powerhub_tariff_history_before_update
before update on public.tariffs
for each row execute function public.powerhub_tariff_history_before_update();

drop trigger if exists powerhub_tariff_history_after_write on public.tariffs;
create trigger powerhub_tariff_history_after_write
after insert or update on public.tariffs
for each row execute function public.powerhub_tariff_history_after_write();

revoke execute on function public.powerhub_tariff_history_before_update() from public, anon, authenticated;
revoke execute on function public.powerhub_tariff_history_after_write() from public, anon, authenticated;
grant execute on function public.powerhub_tariff_history_before_update() to service_role;
grant execute on function public.powerhub_tariff_history_after_write() to service_role;

create or replace function public.powerhub_create_tariff_idempotent(
  p_tenant_id bigint,
  p_site_id bigint,
  p_user_id bigint,
  p_name text,
  p_code text,
  p_price_per_kwh numeric,
  p_fixed_fee numeric,
  p_tax_rate numeric,
  p_client_operation_id text
)
returns table(tariff_id bigint, replayed boolean)
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  v_id bigint;
  v_op public.offline_sync_operations%rowtype;
  v_user public.users%rowtype;
  v_tenant_role text;
  v_staff_role text;
  v_has_permission boolean := false;
  v_platform_role text;
begin
  if nullif(btrim(p_client_operation_id), '') is null then
    raise exception 'CLIENT_OPERATION_REQUIRED' using errcode = 'P0001';
  end if;
  if p_name is null or char_length(btrim(p_name)) < 2
     or p_code is null or char_length(btrim(p_code)) < 2
     or p_price_per_kwh is null or p_price_per_kwh < 0
     or p_fixed_fee is null or p_fixed_fee < 0
     or p_tax_rate is null or p_tax_rate < 0 or p_tax_rate > 100 then
    raise exception 'INVALID_TARIFF_VALUES' using errcode = 'P0001';
  end if;
  select * into v_user from public.users u
  where u.id = p_user_id and u.account_status = 'active'
  limit 1;
  if not found then raise exception 'AUTH_USER_NOT_FOUND' using errcode = 'P0001'; end if;

  if v_user.role = 'admin' and v_user.platform_role in ('platform_owner', 'platform_admin') then
    v_has_permission := true;
  else
    select tm.role into v_tenant_role from public.tenant_members tm
    where tm.tenant_id = p_tenant_id and tm.user_id = p_user_id and tm.role = 'owner'
      and tm.is_active = true and tm.membership_status = 'active' limit 1;
    if v_tenant_role = 'owner' then
      v_has_permission := true;
    else
      select sp.role, (sp.permissions @> '["manageTariffs"]'::jsonb)
        into v_staff_role, v_has_permission
      from public.staff_profiles sp
      where sp.tenant_id = p_tenant_id and sp.user_id = p_user_id and sp.is_active = true
        and (sp.site_id = p_site_id or sp.site_id is null)
      order by case when sp.site_id = p_site_id then 0 else 1 end limit 1;
      if not coalesce(v_has_permission, false) then
        v_has_permission := v_staff_role in ('owner', 'manager', 'accountant');
      end if;
    end if;
  end if;
  if not v_has_permission then raise exception 'TARIFF_MANAGEMENT_FORBIDDEN' using errcode = 'P0001'; end if;

  perform pg_advisory_xact_lock(hashtext('tariff-create:' || p_user_id || ':' || p_client_operation_id)::bigint);
  select * into v_op from public.offline_sync_operations
  where user_id = p_user_id and client_operation_id = p_client_operation_id for update;
  if found then
    if v_op.operation_type <> 'tariff_create' or v_op.tenant_id <> p_tenant_id or v_op.site_id <> p_site_id
       or v_op.response->>'name' <> btrim(p_name) or v_op.response->>'code' <> upper(btrim(p_code))
       or (v_op.response->>'pricePerKwh')::numeric <> p_price_per_kwh
       or (v_op.response->>'fixedFee')::numeric <> p_fixed_fee
       or (v_op.response->>'taxRate')::numeric <> p_tax_rate then
      raise exception 'TARIFF_OPERATION_CONFLICT' using errcode = 'P0001';
    end if;
    return query select (v_op.response->>'tariffId')::bigint, true;
    return;
  end if;

  perform 1 from public.sites where id = p_site_id and tenant_id = p_tenant_id;
  if not found then raise exception 'SITE_OUT_OF_SCOPE' using errcode = 'P0001'; end if;

  insert into public.tariffs(tenant_id, site_id, name, code, price_per_kwh, fixed_fee, tax_rate)
  values (p_tenant_id, p_site_id, btrim(p_name), upper(btrim(p_code)), p_price_per_kwh, p_fixed_fee, p_tax_rate)
  returning id into v_id;

  insert into public.offline_sync_operations(
    tenant_id, site_id, user_id, client_operation_id, operation_type, entity_type, entity_id, response
  ) values (
    p_tenant_id, p_site_id, p_user_id, p_client_operation_id, 'tariff_create', 'tariff', v_id,
    jsonb_build_object('tariffId', v_id, 'name', btrim(p_name), 'code', upper(btrim(p_code)),
      'pricePerKwh', p_price_per_kwh, 'fixedFee', p_fixed_fee, 'taxRate', p_tax_rate)
  );

  select platform_role into v_platform_role from public.users where id = p_user_id;
  insert into public.audit_logs(
    tenant_id, site_id, user_id, actor_platform_role, entity_type, entity_id, action, before_data, after_data, metadata
  ) values (
    p_tenant_id, p_site_id, p_user_id, v_platform_role, 'tariff', v_id::text, 'create', null,
    jsonb_build_object('pricePerKwh', p_price_per_kwh, 'fixedFee', p_fixed_fee, 'taxRate', p_tax_rate, 'isActive', true),
    jsonb_build_object('clientOperationId', p_client_operation_id, 'internalName', btrim(p_name), 'internalCode', upper(btrim(p_code)))
  );

  return query select v_id, false;
exception when unique_violation then
  raise exception 'TARIFF_CODE_EXISTS' using errcode = 'P0001';
end;
$function$;

revoke execute on function public.powerhub_create_tariff_idempotent(bigint,bigint,bigint,text,text,numeric,numeric,numeric,text) from public, anon, authenticated;
grant execute on function public.powerhub_create_tariff_idempotent(bigint,bigint,bigint,text,text,numeric,numeric,numeric,text) to service_role;

create or replace function public.powerhub_update_tariff_price(
  p_tenant_id bigint,
  p_site_id bigint,
  p_user_id bigint,
  p_tariff_id bigint,
  p_price_per_kwh numeric,
  p_fixed_fee numeric,
  p_tax_rate numeric
)
returns table(tariff_id bigint, changed boolean)
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  v_user public.users%rowtype;
  v_tenant_role text;
  v_staff_role text;
  v_has_permission boolean := false;
  v_before public.tariffs%rowtype;
  v_after public.tariffs%rowtype;
  v_platform_role text;
begin
  if p_price_per_kwh is null or p_price_per_kwh < 0
     or p_fixed_fee is null or p_fixed_fee < 0
     or p_tax_rate is null or p_tax_rate < 0 or p_tax_rate > 100 then
    raise exception 'INVALID_TARIFF_VALUES' using errcode = 'P0001';
  end if;

  select * into v_user from public.users u
  where u.id = p_user_id and u.account_status = 'active'
  limit 1;
  if not found then raise exception 'AUTH_USER_NOT_FOUND' using errcode = 'P0001'; end if;

  if v_user.role = 'admin' and v_user.platform_role in ('platform_owner', 'platform_admin') then
    v_has_permission := true;
  else
    select tm.role into v_tenant_role
    from public.tenant_members tm
    where tm.tenant_id = p_tenant_id and tm.user_id = p_user_id and tm.role = 'owner'
      and tm.is_active = true and tm.membership_status = 'active'
    limit 1;
    if v_tenant_role = 'owner' then
      v_has_permission := true;
    else
      select sp.role, (sp.permissions @> '["manageTariffs"]'::jsonb)
        into v_staff_role, v_has_permission
      from public.staff_profiles sp
      where sp.tenant_id = p_tenant_id and sp.user_id = p_user_id and sp.is_active = true
        and (sp.site_id = p_site_id or sp.site_id is null)
      order by case when sp.site_id = p_site_id then 0 else 1 end
      limit 1;
      if not coalesce(v_has_permission, false) then
        v_has_permission := v_staff_role in ('owner', 'manager', 'accountant');
      end if;
    end if;
  end if;
  if not v_has_permission then raise exception 'TARIFF_MANAGEMENT_FORBIDDEN' using errcode = 'P0001'; end if;

  perform pg_advisory_xact_lock(hashtextextended(format('tariff-update:%s:%s', p_tenant_id, p_site_id), 0));

  select * into v_before
  from public.tariffs t
  where t.id = p_tariff_id and t.tenant_id = p_tenant_id and t.site_id = p_site_id and t.is_active = true
  for update;
  if not found then raise exception 'TARIFF_OUT_OF_SCOPE' using errcode = 'P0001'; end if;

  if v_before.price_per_kwh = p_price_per_kwh
     and v_before.fixed_fee = p_fixed_fee
     and v_before.tax_rate = p_tax_rate then
    return query select v_before.id, false;
    return;
  end if;

  update public.tariffs
     set price_per_kwh = p_price_per_kwh,
         fixed_fee = p_fixed_fee,
         tax_rate = p_tax_rate,
         effective_from = clock_timestamp()
   where id = p_tariff_id and tenant_id = p_tenant_id and site_id = p_site_id
   returning * into v_after;

  select platform_role into v_platform_role from public.users where id = p_user_id;
  insert into public.audit_logs(
    tenant_id, site_id, user_id, actor_platform_role, entity_type, entity_id, action, before_data, after_data
  ) values (
    p_tenant_id, p_site_id, p_user_id, v_platform_role, 'tariff', p_tariff_id::text, 'update',
    jsonb_build_object(
      'pricePerKwh', v_before.price_per_kwh, 'fixedFee', v_before.fixed_fee, 'taxRate', v_before.tax_rate,
      'isActive', v_before.is_active, 'effectiveFrom', v_before.effective_from
    ),
    jsonb_build_object(
      'pricePerKwh', v_after.price_per_kwh, 'fixedFee', v_after.fixed_fee, 'taxRate', v_after.tax_rate,
      'isActive', v_after.is_active, 'effectiveFrom', v_after.effective_from
    )
  );
  return query select v_after.id, true;
end;
$function$;

revoke execute on function public.powerhub_update_tariff_price(bigint,bigint,bigint,bigint,numeric,numeric,numeric) from public, anon, authenticated;
grant execute on function public.powerhub_update_tariff_price(bigint,bigint,bigint,bigint,numeric,numeric,numeric) to service_role;
