-- Quota notification semantics:
-- 1) reaching 100% creates one automatic notification/audit per subscription cycle;
-- 2) every subsequent blocked attempt creates its own attempt notification/audit.
-- The server maps these audit records to the owner-facing notification/toast flow.

create table if not exists public.powerhub_quota_alerts (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint references public.sites(id) on delete set null,
  user_id bigint references public.users(id) on delete set null,
  resource text not null check (resource in ('subscribers','platformUser','fieldUser','branch','sms')),
  alert_type text not null check (alert_type in ('reached','blocked_attempt')),
  subscription_id bigint references public.tenant_subscriptions(id) on delete set null,
  current_count integer not null,
  quota_limit integer not null,
  remaining integer not null,
  created_at timestamptz not null default now()
);

create index if not exists powerhub_quota_alerts_owner_idx
  on public.powerhub_quota_alerts(tenant_id,resource,created_at desc);

create unique index if not exists powerhub_quota_alerts_reached_once_uidx
  on public.powerhub_quota_alerts(tenant_id,resource,subscription_id)
  where alert_type='reached';

create or replace function public.powerhub_record_quota_alert(
  p_tenant_id bigint,
  p_site_id bigint,
  p_user_id bigint,
  p_resource text,
  p_alert_type text,
  p_current_count integer,
  p_quota_limit integer,
  p_subscription_id bigint default null
)
returns table(recorded boolean,alert_id bigint)
language plpgsql
security definer
set search_path=public,pg_temp
as $function$
declare
  v_id bigint;
  v_subscription_id bigint;
begin
  if p_resource not in('subscribers','platformUser','fieldUser','branch','sms')
     or p_alert_type not in('reached','blocked_attempt')
     or p_quota_limit < 0 or p_current_count < 0 then
    raise exception 'INVALID_QUOTA_ALERT' using errcode='P0001';
  end if;

  select id into v_subscription_id
  from public.tenant_subscriptions
  where tenant_id=p_tenant_id
    and status in('trial','active')
  order by ends_at desc nulls last,id desc
  limit 1;

  v_subscription_id:=coalesce(p_subscription_id,v_subscription_id);

  if p_alert_type='reached' then
    insert into public.powerhub_quota_alerts(
      tenant_id,site_id,user_id,resource,alert_type,subscription_id,current_count,quota_limit,remaining
    )
    values(p_tenant_id,p_site_id,p_user_id,p_resource,p_alert_type,v_subscription_id,p_current_count,p_quota_limit,greatest(0,p_quota_limit-p_current_count))
    on conflict do nothing
    returning id into v_id;
  else
    insert into public.powerhub_quota_alerts(
      tenant_id,site_id,user_id,resource,alert_type,subscription_id,current_count,quota_limit,remaining
    )
    values(p_tenant_id,p_site_id,p_user_id,p_resource,p_alert_type,v_subscription_id,p_current_count,p_quota_limit,0)
    returning id into v_id;
  end if;

  return query select (v_id is not null),v_id;
end;
$function$;

revoke all on function public.powerhub_record_quota_alert(bigint,bigint,bigint,text,text,integer,integer,bigint) from public,anon,authenticated;
grant execute on function public.powerhub_record_quota_alert(bigint,bigint,bigint,text,text,integer,integer,bigint) to service_role;

-- The quota grant RPC is part of the production contract used by Admin > إدارة الميزات.
-- It is intentionally re-created here so Production cannot drift from the application contract.
create or replace function public.powerhub_admin_grant_tenant_addon(
 p_actor_user_id bigint,p_tenant_id bigint,p_feature_key text,p_quantity integer,
 p_billing_mode text default 'free',p_note text default null,p_request_key uuid default null
)
returns table(success boolean,request_id bigint,tenant_id bigint,feature_key text,addon_code text,quantity integer,display_quantity integer,billing_mode text,starts_at timestamptz,ends_at timestamptz,replayed boolean)
language plpgsql security definer set search_path=public,pg_temp
as $function$
declare
 v_role text; v_type text; v_active boolean; v_package text; v_policy text;
 v_sub public.tenant_subscriptions%rowtype; v_code text; v_qty integer; v_display integer;
 v_site bigint; v_existing public.tenant_addon_requests%rowtype; v_id bigint; v_now timestamptz:=now(); v_days integer;
begin
 select platform_role into v_role from public.users where id=p_actor_user_id and role='admin' and account_status='active' and platform_role in('platform_owner','platform_admin');
 if v_role is null then raise exception 'FORBIDDEN_PLATFORM_ROLE' using errcode='42501'; end if;
 if not exists(select 1 from public.tenants where id=p_tenant_id) then raise exception 'TENANT_NOT_FOUND' using errcode='P0001'; end if;
 if p_quantity is null or p_quantity<1 then raise exception 'INVALID_ADDON_QUANTITY' using errcode='P0001'; end if;
 if p_billing_mode not in('free','paid') then raise exception 'INVALID_BILLING_MODE' using errcode='P0001'; end if;
 select feature_type,is_active into v_type,v_active from public.feature_catalog where feature_key=trim(p_feature_key) limit 1;
 if v_type is null then raise exception 'FEATURE_NOT_FOUND' using errcode='P0001'; end if;
 if not v_active then raise exception 'FEATURE_GLOBALLY_DISABLED' using errcode='P0001'; end if;
 if v_type<>'quota' then raise exception 'FEATURE_NOT_ADDON_MANAGEABLE' using errcode='P0001'; end if;
 select * into v_sub from public.tenant_subscriptions where tenant_id=p_tenant_id and status in('trial','active') and (ends_at is null or ends_at>v_now) order by created_at desc,id desc limit 1 for update;
 if not found or v_sub.ends_at is null then raise exception 'SUBSCRIPTION_REQUIRED' using errcode='P0001'; end if;
 v_package:=v_sub.package_code;
 select policy into v_policy from public.package_feature_policies where package_code=v_package and feature_key=trim(p_feature_key) limit 1;
 if coalesce(v_policy,'none') not in('included','addon') then raise exception 'FEATURE_NOT_AVAILABLE_IN_PACKAGE' using errcode='P0001'; end if;
 v_code:=case trim(p_feature_key) when 'subscriber_management' then 'subscribers50' when 'platform_users' then 'platformUser' when 'field_users' then 'fieldUser' when 'branch_management' then 'branch' when 'sms' then 'sms' else null end;
 if v_code is null then raise exception 'FEATURE_NOT_ADDON_MANAGEABLE' using errcode='P0001'; end if;
 if p_feature_key='subscriber_management' then
   if mod(p_quantity,50)<>0 then raise exception 'SUBSCRIBER_ADDON_QUANTITY_MULTIPLE_REQUIRED' using errcode='P0001'; end if;
   v_qty:=p_quantity/50; v_display:=p_quantity;
 else v_qty:=p_quantity; v_display:=p_quantity; end if;
 select id into v_site from public.sites where tenant_id=p_tenant_id and status<>'archived' order by id limit 1;
 if v_site is null then raise exception 'TENANT_SITE_REQUIRED_FOR_AUDIT' using errcode='P0001'; end if;
 if p_request_key is not null then
   select * into v_existing from public.tenant_addon_requests where request_key=p_request_key for update;
   if found then
     if v_existing.tenant_id<>p_tenant_id or v_existing.addon_code<>v_code or v_existing.quantity<>v_qty or v_existing.billing_mode<>p_billing_mode then raise exception 'ADDON_REQUEST_KEY_REUSED' using errcode='P0001'; end if;
     return query select true,v_existing.id,v_existing.tenant_id,trim(p_feature_key),v_existing.addon_code,v_existing.quantity,v_display,v_existing.billing_mode,v_existing.starts_at,v_existing.ends_at,true; return;
   end if;
 end if;
 v_days:=greatest(1,ceil(extract(epoch from (v_sub.ends_at-v_now))/86400.0)::integer);
 insert into public.tenant_addon_requests(tenant_id,site_id,requested_by_user_id,addon_code,quantity,status,note,created_at,reviewed_at,reviewed_by_user_id,review_note,duration_days,starts_at,ends_at,billing_mode,source,request_key)
 values(p_tenant_id,v_site,p_actor_user_id,v_code,v_qty,'approved',nullif(btrim(p_note),''),v_now,v_now,p_actor_user_id,'منح مباشر من إدارة الميزات والحدود.',v_days,v_now,v_sub.ends_at,p_billing_mode,'admin_grant',p_request_key)
 returning id into v_id;
 insert into public.audit_logs(tenant_id,site_id,user_id,actor_platform_role,entity_type,entity_id,action,after_data)
 values(p_tenant_id,v_site,p_actor_user_id,v_role,'tenant_addon_request',v_id::text,'grant_addon',jsonb_build_object('featureKey',trim(p_feature_key),'addonCode',v_code,'quantity',v_qty,'displayQuantity',v_display,'billingMode',p_billing_mode,'startsAt',v_now,'endsAt',v_sub.ends_at,'note',p_note));
 return query select true,v_id,p_tenant_id,trim(p_feature_key),v_code,v_qty,v_display,p_billing_mode,v_now,v_sub.ends_at,false;
end;
$function$;

revoke all on function public.powerhub_admin_grant_tenant_addon(bigint,bigint,text,integer,text,text,uuid) from public,anon,authenticated;
grant execute on function public.powerhub_admin_grant_tenant_addon(bigint,bigint,text,integer,text,text,uuid) to service_role;
