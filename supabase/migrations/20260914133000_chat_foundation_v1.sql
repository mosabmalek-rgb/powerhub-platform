-- PowerHub Smart Support Chat v1 — database foundation.
-- DESIGN-APPROVED / NOT DEPLOYED TO PRODUCTION.
--
-- Security boundary notes:
-- * Chat identity is always resolved from auth.uid() at the RLS/RPC boundary.
-- * Browser-supplied actor/user IDs must never be trusted for authorization.
-- * chat_participants are human participants only; AI is not a security principal.
-- * Support authorization is a platform capability and is intentionally NOT part of tenant RBAC.
-- * Chat attachments use the existing private `powerhub-private` Storage bucket.
-- * No AI provider keys or secrets belong in these tables.
-- * RLS and Realtime authorization are separate follow-up migrations; this migration
--   intentionally does not open table access to clients.

create table public.chat_conversations (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  conversation_type text not null check (conversation_type in ('assistant', 'support')),
  status text not null default 'AI_ACTIVE' check (status in (
    'AI_ACTIVE', 'SUPPORT_PENDING', 'SUPPORT_ACTIVE', 'WAITING_USER', 'RESOLVED', 'CLOSED'
  )),
  subject text,
  priority text not null default 'normal' check (priority in ('low', 'normal', 'high', 'urgent')),
  last_message_at timestamptz,
  resolved_at timestamptz,
  closed_at timestamptz,
  created_by_user_id bigint not null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, tenant_id),
  check (closed_at is null or status = 'CLOSED'),
  check (resolved_at is null or status in ('RESOLVED', 'CLOSED'))
);

create table public.chat_participants (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null,
  tenant_id bigint not null,
  user_id bigint not null references public.users(id) on delete cascade,
  participant_role text not null check (participant_role in ('owner', 'support', 'platform_admin')),
  joined_at timestamptz not null default now(),
  left_at timestamptz,
  last_read_message_id bigint,
  last_read_at timestamptz,
  muted_at timestamptz,
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (conversation_id, tenant_id)
    references public.chat_conversations(id, tenant_id) on delete cascade,
  unique (conversation_id, user_id),
  check (left_at is null or left_at >= joined_at)
);

create table public.chat_messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null,
  tenant_id bigint not null,
  sender_user_id bigint references public.users(id) on delete set null,
  sender_type text not null check (sender_type in ('human', 'assistant', 'system')),
  message_type text not null default 'text' check (message_type in ('text', 'system', 'handoff', 'attachment')),
  body text,
  reply_to_message_id bigint,
  metadata jsonb not null default '{}'::jsonb,
  client_message_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  edited_at timestamptz,
  deleted_at timestamptz,
  foreign key (conversation_id, tenant_id)
    references public.chat_conversations(id, tenant_id) on delete cascade,
  foreign key (reply_to_message_id)
    references public.chat_messages(id) on delete set null,
  unique (conversation_id, client_message_id),
  check (body is not null or message_type in ('attachment', 'system', 'handoff')),
  check (edited_at is null or edited_at >= created_at),
  check (deleted_at is null or deleted_at >= created_at)
);

create table public.chat_message_attachments (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null,
  conversation_id bigint not null,
  message_id bigint not null,
  storage_bucket text not null default 'powerhub-private' check (storage_bucket = 'powerhub-private'),
  storage_path text not null,
  original_name text not null,
  mime_type text not null,
  size_bytes bigint not null check (size_bytes > 0 and size_bytes <= 10485760),
  checksum text,
  created_by_user_id bigint not null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  foreign key (conversation_id, tenant_id)
    references public.chat_conversations(id, tenant_id) on delete cascade,
  foreign key (message_id)
    references public.chat_messages(id) on delete cascade,
  check (mime_type in ('image/jpeg', 'image/png', 'image/webp', 'application/pdf')),
  check (storage_path like ('chat/' || tenant_id::text || '/' || conversation_id::text || '/%')),
  unique (storage_bucket, storage_path)
);

create table public.chat_support_assignments (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null,
  tenant_id bigint not null,
  assigned_user_id bigint not null references public.users(id) on delete restrict,
  assigned_by_user_id bigint not null references public.users(id) on delete restrict,
  status text not null default 'pending' check (status in ('pending', 'active', 'released')),
  assigned_at timestamptz not null default now(),
  accepted_at timestamptz,
  released_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (conversation_id, tenant_id)
    references public.chat_conversations(id, tenant_id) on delete cascade,
  check (accepted_at is null or accepted_at >= assigned_at),
  check (released_at is null or released_at >= assigned_at),
  check (status <> 'active' or accepted_at is not null),
  check (status <> 'released' or released_at is not null)
);

create table public.chat_knowledge_articles (
  id bigint generated by default as identity primary key,
  title text not null,
  primary_question text not null,
  alternative_questions jsonb not null default '[]'::jsonb,
  answer text not null,
  category text not null,
  linked_route text,
  related_operation text,
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  version integer not null default 1 check (version > 0),
  published_at timestamptz,
  created_by_user_id bigint not null references public.users(id) on delete restrict,
  updated_by_user_id bigint not null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (status <> 'published' or published_at is not null)
);

-- Embeddings intentionally avoid a fixed vector dimension until the approved
-- embedding provider/model is selected. Publication is independent of embedding generation.
create table public.chat_knowledge_embeddings (
  id bigint generated by default as identity primary key,
  article_id bigint not null references public.chat_knowledge_articles(id) on delete cascade,
  content_hash text not null,
  embedding_model text not null,
  embedding jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (article_id, content_hash, embedding_model)
);

create table public.chat_bot_handoffs (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null,
  tenant_id bigint not null,
  trigger text not null check (trigger in ('unknown', 'insufficient_knowledge', 'sensitive', 'user_requested', 'repeated_failure')),
  reason text not null,
  user_message_id bigint,
  ai_message_id bigint,
  summary text,
  category text,
  priority text not null default 'normal' check (priority in ('low', 'normal', 'high', 'urgent')),
  current_page text,
  context_snapshot jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  foreign key (conversation_id, tenant_id)
    references public.chat_conversations(id, tenant_id) on delete cascade,
  foreign key (user_message_id)
    references public.chat_messages(id) on delete set null,
  foreign key (ai_message_id)
    references public.chat_messages(id) on delete set null,
  check (completed_at is null or completed_at >= created_at)
);

create table public.chat_bot_feedback (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null,
  message_id bigint not null,
  user_id bigint not null references public.users(id) on delete cascade,
  rating text not null check (rating in ('positive', 'negative')),
  feedback_text text,
  created_at timestamptz not null default now(),
  foreign key (conversation_id)
    references public.chat_conversations(id) on delete cascade,
  foreign key (message_id)
    references public.chat_messages(id) on delete cascade,
  unique (message_id, user_id)
);

create index chat_conversations_tenant_status_last_message_idx
  on public.chat_conversations (tenant_id, status, last_message_at desc);

create index chat_participants_user_conversation_idx
  on public.chat_participants (user_id, conversation_id);

create index chat_messages_conversation_created_idx
  on public.chat_messages (conversation_id, created_at desc);

create index chat_messages_conversation_client_message_idx
  on public.chat_messages (conversation_id, client_message_id);

create index chat_support_assignments_assignee_status_idx
  on public.chat_support_assignments (assigned_user_id, status);

create index chat_support_assignments_conversation_status_idx
  on public.chat_support_assignments (conversation_id, status);

create index chat_bot_handoffs_tenant_created_idx
  on public.chat_bot_handoffs (tenant_id, created_at desc);

create index chat_bot_feedback_message_user_idx
  on public.chat_bot_feedback (message_id, user_id);

create index chat_knowledge_articles_status_category_idx
  on public.chat_knowledge_articles (status, category);

create unique index chat_support_assignments_one_open_per_conversation_idx
  on public.chat_support_assignments (conversation_id)
  where status in ('pending', 'active');

