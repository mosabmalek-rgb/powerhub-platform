create or replace function public.chat_support_metrics(
  p_from timestamptz,
  p_to timestamptz
)
returns table(
  open_count bigint,
  resolved_count bigint,
  closed_count bigint,
  average_first_response_minutes numeric,
  average_resolution_minutes numeric,
  first_response_breaches bigint,
  resolution_breaches bigint,
  average_rating numeric,
  rating_count bigint,
  reopened_count bigint
)
language plpgsql
security definer
set search_path=''
stable
as $$
begin
  if private.chat_current_user_id() is null then raise exception 'UNAUTHORIZED'; end if;
  if not private.powerhub_has_platform_capability('manageSupportChat') then raise exception 'FORBIDDEN'; end if;
  return query
  select
    count(*) filter (where c.status in ('SUPPORT_PENDING','SUPPORT_ACTIVE','WAITING_USER')),
    count(*) filter (where c.status='RESOLVED'),
