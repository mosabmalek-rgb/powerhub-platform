create or replace function private.chat_send_message(
  p_conversation_id bigint,
  p_body text,
  p_client_message_id uuid,
  p_reply_to_message_id bigint default null
)
returns public.chat_messages
language plpgsql
security definer
set search_path=''
volatile
as $$
declare
  v_user_id bigint;
  v_conversation public.chat_conversations;
  v_row public.chat_messages;
  v_existing public.chat_messages;
  v_is_support boolean;
  v_reopen_window integer;
  v_old_status text;
begin
  v_user_id := private.chat_current_user_id();
  if v_user_id is null then raise exception 'UNAUTHORIZED'; end if;

  select * into v_conversation from public.chat_conversations where id=p_conversation_id;
  if not found then raise exception 'NOT_FOUND'; end if;
  if not private.chat_can_access_conversation(p_conversation_id) then raise exception 'FORBIDDEN'; end if;
  if nullif(btrim(p_body),'') is null then raise exception 'INVALID_BODY'; end if;
  if length(p_body)>8000 then raise exception 'BODY_TOO_LONG'; end if;
  if p_client_message_id is null then raise exception 'CLIENT_MESSAGE_ID_REQUIRED'; end if;

  if p_reply_to_message_id is not null and not exists(
    select 1 from public.chat_messages m
    where m.id=p_reply_to_message_id and m.conversation_id=p_conversation_id and m.visibility='public'
  ) then raise exception 'INVALID_REPLY_TARGET'; end if;

  select * into v_existing
  from public.chat_messages
  where conversation_id=p_conversation_id and client_message_id=p_client_message_id;
  if found then
    if v_existing.sender_user_id is distinct from v_user_id then raise exception 'IDEMPOTENCY_CONFLICT'; end if;
    return v_existing;
  end if;

  if not private.chat_rate_limit_consume(v_user_id,'messages:global',60,30) then
    raise exception using errcode='P0001',message='RATE_LIMITED';
  end if;
  if not private.chat_rate_limit_consume(v_user_id,format('messages:conversation:%s',p_conversation_id),60,20) then
    raise exception using errcode='P0001',message='RATE_LIMITED';
  end if;

  v_is_support := private.powerhub_has_platform_capability('manageSupportChat');
  v_old_status := v_conversation.status;

  if not v_is_support and v_conversation.status in ('RESOLVED','CLOSED') then
    select reopen_window_minutes into v_reopen_window from public.chat_support_settings where id=true;
    if coalesce(v_conversation.resolved_at,v_conversation.closed_at) >= now() - (coalesce(v_reopen_window,10080) * interval '1 minute') then
      update public.chat_conversations
      set status='SUPPORT_ACTIVE', reopened_at=now(), resolved_at=null, closed_at=null,
          auto_close_at=null, closed_by_user_id=null, close_reason=null, updated_at=now()
      where id=p_conversation_id;
      v_conversation.status := 'SUPPORT_ACTIVE';
      perform private.chat_log_ticket_event(p_conversation_id,'reopened',jsonb_build_object('reason','customer_message_after_resolution'),v_old_status,'SUPPORT_ACTIVE',null,null,v_user_id);
    else
      raise exception 'TICKET_CLOSED';
    end if;
  elsif v_is_support and v_conversation.status='SUPPORT_PENDING' then
    update public.chat_conversations
    set status='SUPPORT_ACTIVE',updated_at=now()
    where id=p_conversation_id;
    v_conversation.status := 'SUPPORT_ACTIVE';
  elsif not v_is_support and v_conversation.status='WAITING_USER' then
    update public.chat_conversations
    set status='SUPPORT_ACTIVE',updated_at=now()
    where id=p_conversation_id;
    v_conversation.status := 'SUPPORT_ACTIVE';
    perform private.chat_log_ticket_event(p_conversation_id,'status_changed',jsonb_build_object('reason','customer_reply'),v_old_status,'SUPPORT_ACTIVE',null,null,v_user_id);
  end if;

  insert into public.chat_messages(
    conversation_id,tenant_id,sender_user_id,sender_type,message_type,visibility,body,reply_to_message_id,client_message_id
  ) values (
    v_conversation.id,v_conversation.tenant_id,v_user_id,'human','text','public',
    btrim(p_body),p_reply_to_message_id,p_client_message_id
  )
  returning * into v_row;

  update public.chat_conversations
  set last_message_at=v_row.created_at,
      last_customer_message_at=case when not v_is_support then v_row.created_at else last_customer_message_at end,
      last_support_message_at=case when v_is_support then v_row.created_at else last_support_message_at end,
      first_response_at=case
        when v_is_support and first_response_at is null then v_row.created_at
        else first_response_at
      end,
      first_response_breached_at=case
        when v_is_support and first_response_at is null and first_response_due_at is not null and v_row.created_at>first_response_due_at then v_row.created_at
        else first_response_breached_at
      end,
      updated_at=now()
  where id=v_conversation.id;

  if v_is_support and v_conversation.first_response_at is null then
    perform private.chat_log_ticket_event(v_conversation.id,'first_response',jsonb_build_object('message_id',v_row.id),null,null,null,null,v_user_id);
  end if;

  perform private.chat_apply_sla(v_conversation.id);
  return v_row;
end;
$$;

