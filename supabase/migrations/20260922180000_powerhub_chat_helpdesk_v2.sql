  perform private.chat_apply_sla(p_conversation_id);

  perform private.chat_log_ticket_event(
    p_conversation_id,
    case when v_old_assignee is null then 'assigned' else 'reassigned' end,
    jsonb_build_object('assigned_user_id',p_assigned_user_id,'previous_assignee_id',v_old_assignee),
