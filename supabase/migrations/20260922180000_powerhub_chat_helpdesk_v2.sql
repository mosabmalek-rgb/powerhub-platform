create or replace function private.chat_process_support_sla()
returns integer
language plpgsql
security definer
set search_path=''
volatile
as $$
declare
  v_count integer := 0;
  v_row record;
begin
  for v_row in
    select id,assigned_user_id,ticket_number,tenant_id,first_response_at,first_response_due_at,resolution_due_at,first_response_breached_at,resolution_breached_at
    from public.chat_conversations
    where conversation_type='support'
      and status not in ('RESOLVED','CLOSED')
      and (
        (first_response_at is null and first_response_due_at is not null and first_response_due_at<now() and first_response_breached_at is null)
        or (resolved_at is null and resolution_due_at is not null and resolution_due_at<now() and resolution_breached_at is null)
      )
  loop
    if v_row.first_response_at is null and v_row.first_response_due_at is not null and v_row.first_response_due_at<now() and v_row.first_response_breached_at is null then
      update public.chat_conversations
      set first_response_breached_at=now(),updated_at=now()
      where id=v_row.id;
      perform private.chat_log_ticket_event(v_row.id,'sla_first_response_breached',jsonb_build_object('ticket_number',v_row.ticket_number,'due_at',v_row.first_response_due_at),null,null,null,null,null);
      if v_row.assigned_user_id is not null then
        insert into public.chat_inbox_notifications(user_id,tenant_id,conversation_id,message_id,notification_type,title,body)
        values(v_row.assigned_user_id,v_row.tenant_id,v_row.id,null,'support_update','تجاوز مهلة أول استجابة',coalesce(v_row.ticket_number,'تذكرة دعم'));
      end if;
      v_count := v_count+1;
    end if;

    if v_row.resolution_due_at is not null and v_row.resolution_due_at<now() and v_row.resolution_breached_at is null then
      update public.chat_conversations
      set resolution_breached_at=now(),updated_at=now()
      where id=v_row.id;
      perform private.chat_log_ticket_event(v_row.id,'sla_resolution_breached',jsonb_build_object('ticket_number',v_row.ticket_number,'due_at',v_row.resolution_due_at),null,null,null,null,null);
      if v_row.assigned_user_id is not null then
        insert into public.chat_inbox_notifications(user_id,tenant_id,conversation_id,message_id,notification_type,title,body)
        values(v_row.assigned_user_id,v_row.tenant_id,v_row.id,null,'support_update','تجاوز مهلة الحل',coalesce(v_row.ticket_number,'تذكرة دعم'));
      end if;
      v_count := v_count+1;
    end if;
  end loop;
  return v_count;
end;
$$;

create or replace function private.chat_auto_close_resolved()
returns integer
language plpgsql
security definer
set search_path=''
volatile
as $$
declare
  v_count integer := 0;
  v_row record;
begin
  for v_row in
    select id from public.chat_conversations
    where conversation_type='support' and status='RESOLVED'
      and auto_close_at is not null and auto_close_at<=now()
  loop
    update public.chat_conversations
    set status='CLOSED',closed_at=now(),auto_close_at=null,close_reason='auto_close',
        updated_at=now()
    where id=v_row.id and status='RESOLVED'
    returning id into v_row.id;
    if found then
      perform private.chat_log_ticket_event(v_row.id,'closed',jsonb_build_object('reason','auto_close'));
      v_count := v_count+1;
    end if;
  end loop;
  return v_count;
end;
$$;

