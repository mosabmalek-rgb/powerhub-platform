create or replace function private.chat_support_set_metadata(
  p_conversation_id bigint,
  p_subject text default null,
  p_priority text default null,
  p_category_code text default null
)
returns public.chat_conversations
language plpgsql
security definer
set search_path=''
volatile
as $$
declare
  v_actor bigint;
  v_current public.chat_conversations;
  v_result public.chat_conversations;
  v_category text;
  v_priority text;
begin
  v_actor := private.chat_current_user_id();
  if v_actor is null then raise exception 'UNAUTHORIZED'; end if;
  if not private.powerhub_has_platform_capability('manageSupportChat') then raise exception 'FORBIDDEN'; end if;

  select * into v_current from public.chat_conversations where id=p_conversation_id;
  if not found then raise exception 'NOT_FOUND'; end if;
  if v_current.conversation_type <> 'support' then raise exception 'NOT_SUPPORT_CONVERSATION'; end if;

  v_priority := coalesce(p_priority,v_current.priority);
  v_category := coalesce(p_category_code,v_current.category_code,'other');

  if v_priority not in ('low','normal','high','urgent') then raise exception 'INVALID_PRIORITY'; end if;
  if not exists(select 1 from public.chat_support_categories where code=v_category and is_active) then raise exception 'INVALID_CATEGORY'; end if;

  update public.chat_conversations
  set subject=coalesce(nullif(btrim(p_subject),''),subject),
      priority=v_priority,
      category_code=v_category,
      updated_at=now()
  where id=p_conversation_id
  returning * into v_result;

  if v_current.priority is distinct from v_priority then
    perform private.chat_log_ticket_event(p_conversation_id,'priority_changed',jsonb_build_object('by',v_actor),v_current.status,v_result.status,v_current.priority,v_priority,v_actor);
  end if;
  if v_current.category_code is distinct from v_category then
    perform private.chat_log_ticket_event(p_conversation_id,'category_changed',jsonb_build_object('by',v_actor,'category_code',v_category),null,null,null,null,v_actor);
  end if;

  perform private.chat_apply_sla(p_conversation_id);
  return v_result;
end;
$$;

