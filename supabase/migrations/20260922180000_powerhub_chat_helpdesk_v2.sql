-- PowerHub Chat / Helpdesk v2
-- Extends the existing Smart Support Chat with ticketing, SLA, categorisation,
-- internal notes, tags, canned replies, CSAT, queue RPCs and automated lifecycle.
-- Identity is always derived from auth.uid() through the existing private helpers.

create sequence if not exists public.chat_support_ticket_seq;

create table if not exists public.chat_support_categories (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  description text,
  default_first_response_minutes integer not null default 60 check (default_first_response_minutes > 0),
  default_resolution_minutes integer not null default 1440 check (default_resolution_minutes > 0),
  is_active boolean not null default true,
  sort_order integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.chat_support_sla_policies (
  priority text primary key check (priority in ('low', 'normal', 'high', 'urgent')),
  multiplier numeric(6,3) not null check (multiplier > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.chat_support_settings (
  id boolean primary key default true check (id = true),
  auto_close_after_minutes integer not null default 2880 check (auto_close_after_minutes >= 0),
  reopen_window_minutes integer not null default 10080 check (reopen_window_minutes > 0),
  updated_by_user_id bigint references public.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.chat_support_quick_replies (
  id bigint generated by default as identity primary key,
  category_code text references public.chat_support_categories(code) on delete set null,
  shortcut text not null unique,
  title text not null,
  body text not null,
  is_active boolean not null default true,
  created_by_user_id bigint references public.users(id) on delete set null,
  updated_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.chat_support_tags (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  color text not null default '#64748B',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.chat_conversation_tags (
  conversation_id bigint not null references public.chat_conversations(id) on delete cascade,
  tag_id bigint not null references public.chat_support_tags(id) on delete cascade,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  created_by_user_id bigint not null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  primary key (conversation_id, tag_id)
);

create table if not exists public.chat_ticket_events (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.chat_conversations(id) on delete cascade,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  actor_user_id bigint references public.users(id) on delete set null,
  event_type text not null check (event_type in (
    'created','assigned','reassigned','released','accepted','status_changed',
    'priority_changed','category_changed','tag_added','tag_removed',
    'internal_note','first_response','sla_first_response_breached',
    'sla_resolution_breached','reopened','resolved','closed','customer_rated'
  )),
  from_status text,
  to_status text,
  from_priority text,
  to_priority text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.chat_support_feedback (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.chat_conversations(id) on delete cascade,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  comment text,
  created_at timestamptz not null default now(),
  unique (conversation_id, user_id)
);

