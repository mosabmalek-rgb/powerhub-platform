    count(f.id),
    count(*) filter (where c.reopened_at is not null)
  from public.chat_conversations c
  left join public.chat_support_feedback f on f.conversation_id=c.id
  where c.conversation_type='support'
    and c.created_at >= coalesce(p_from,'1970-01-01'::timestamptz)
    and c.created_at < coalesce(p_to,now());
end;
$$;

