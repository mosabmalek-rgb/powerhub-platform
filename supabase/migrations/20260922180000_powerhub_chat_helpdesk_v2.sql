create or replace function private.chat_priority_multiplier(p_priority text)
returns numeric
language sql
stable
set search_path=''
as $$
  select coalesce((select multiplier from public.chat_support_sla_policies where priority=p_priority),1.0);
$$;

create or replace function private.chat_apply_sla(p_conversation_id bigint)
returns void
language plpgsql
security definer
set search_path=''
volatile
as $$
declare
  v_conversation public.chat_conversations;
  v_category public.chat_support_categories;
  v_first integer;
  v_resolution integer;
  v_mult numeric;
begin
  select * into v_conversation from public.chat_conversations where id=p_conversation_id;
  if not found or v_conversation.conversation_type <> 'support' then return; end if;

  select * into v_category
  from public.chat_support_categories
  where code=coalesce(v_conversation.category_code,'other');

  v_first := greatest(1, ceil(v_category.default_first_response_minutes * private.chat_priority_multiplier(v_conversation.priority))::integer);
  v_resolution := greatest(1, ceil(v_category.default_resolution_minutes * private.chat_priority_multiplier(v_conversation.priority))::integer);

  update public.chat_conversations
  set first_response_due_at = case
        when first_response_at is null and status not in ('RESOLVED','CLOSED')
          then coalesce(last_customer_message_at, created_at) + (v_first * interval '1 minute')
        else first_response_due_at
      end,
      resolution_due_at = case
        when resolved_at is null and status not in ('CLOSED')
          then coalesce(last_customer_message_at, created_at) + (v_resolution * interval '1 minute')
        else resolution_due_at
      end,
      updated_at=now()
  where id=p_conversation_id;
end;
$$;

revoke all on function private.chat_priority_multiplier(text) from public, anon, authenticated;
revoke all on function private.chat_apply_sla(bigint) from public, anon, authenticated;

create or replace function private.chat_log_ticket_event(
  p_conversation_id bigint,
  p_event_type text,
  p_metadata jsonb default '{}'::jsonb,
  p_from_status text default null,
  p_to_status text default null,
  p_from_priority text default null,
  p_to_priority text default null,
  p_actor_user_id bigint default null
)
returns void
language plpgsql
security definer
set search_path=''
volatile
as $$
declare v_tenant_id bigint; v_actor bigint;
begin
  select tenant_id into v_tenant_id from public.chat_conversations where id=p_conversation_id;
  if v_tenant_id is null then return; end if;
  v_actor := coalesce(p_actor_user_id, private.chat_current_user_id());
  insert into public.chat_ticket_events(
    conversation_id,tenant_id,actor_user_id,event_type,
    from_status,to_status,from_priority,to_priority,metadata
  ) values (
    p_conversation_id,v_tenant_id,v_actor,p_event_type,
    p_from_status,p_to_status,p_from_priority,p_to_priority,coalesce(p_metadata,'{}'::jsonb)
  );
end;
$$;

revoke all on function private.chat_log_ticket_event(bigint,text,jsonb,text,text,text,text,bigint) from public, anon, authenticated;

create or replace function private.chat_prepare_support_conversation()
returns trigger
language plpgsql
security definer
set search_path=''
volatile
as $$
declare
  v_category text;
begin
  if new.conversation_type <> 'support' then
    return new;
  end if;

  if new.ticket_number is null then
    new.ticket_number := private.chat_support_ticket_number();
  end if;

  v_category := coalesce(new.category_code,'other');
  new.category_code := v_category;
  new.source := coalesce(nullif(new.source,''),'manual');
  new.last_customer_message_at := coalesce(new.last_customer_message_at,new.last_message_at,new.created_at,now());
  return new;
end;
$$;

