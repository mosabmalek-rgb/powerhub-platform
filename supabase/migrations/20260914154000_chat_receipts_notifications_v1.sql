-- Smart Support Chat v1: delivery/read receipts + in-app notifications.
-- Browser roles remain read-only on these tables; state changes use RPCs.

create table public.chat_message_receipts (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null,
  conversation_id bigint not null,
  message_id bigint not null,
  user_id bigint not null references public.users(id) on delete cascade,
  delivered_at timestamptz,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (conversation_id, tenant_id) references public.chat_conversations(id, tenant_id) on delete cascade,
  foreign key (message_id) references public.chat_messages(id) on delete cascade,
  unique (message_id, user_id),
  check (read_at is null or delivered_at is not null),
  check (updated_at >= created_at)
);

create index chat_message_receipts_user_message_idx on public.chat_message_receipts (user_id, message_id);
create index chat_message_receipts_conversation_message_idx on public.chat_message_receipts (conversation_id, message_id);

create table public.chat_inbox_notifications (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  tenant_id bigint not null,
  conversation_id bigint not null,
  message_id bigint,
  notification_type text not null check (notification_type in ('chat_message','chat_mention','support_update')),
  title text not null,
  body text,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  foreign key (conversation_id, tenant_id) references public.chat_conversations(id, tenant_id) on delete cascade,
  foreign key (message_id) references public.chat_messages(id) on delete set null,
  unique (user_id, message_id, notification_type)
);

create index chat_inbox_notifications_user_unread_idx on public.chat_inbox_notifications (user_id, read_at, created_at desc);
create index chat_inbox_notifications_conversation_idx on public.chat_inbox_notifications (conversation_id, created_at desc);

alter table public.chat_message_receipts enable row level security;
alter table public.chat_inbox_notifications enable row level security;

create policy chat_message_receipts_select_access on public.chat_message_receipts for select to authenticated
using (
  user_id = powerhub_private.current_user_id()
  or exists (select 1 from public.chat_messages m where m.id=chat_message_receipts.message_id and m.sender_user_id=powerhub_private.current_user_id())
  or private.powerhub_has_platform_capability('manageSupportChat')
);

create policy chat_inbox_notifications_select_own on public.chat_inbox_notifications for select to authenticated
using (user_id = powerhub_private.current_user_id());

revoke all on table public.chat_message_receipts, public.chat_inbox_notifications from anon, authenticated;
grant select on public.chat_message_receipts, public.chat_inbox_notifications to authenticated;

create or replace function private.chat_mark_delivered(p_message_id bigint)
returns public.chat_message_receipts
language plpgsql security definer set search_path = '' volatile
as $$
declare v_user_id bigint; v_receipt public.chat_message_receipts; v_msg public.chat_messages;
begin
  v_user_id := private.chat_current_user_id();
  if v_user_id is null then raise exception 'UNAUTHORIZED'; end if;
  select * into v_msg from public.chat_messages where id=p_message_id;
  if not found then raise exception 'NOT_FOUND'; end if;
  if not private.chat_can_access_conversation(v_msg.conversation_id) then raise exception 'FORBIDDEN'; end if;
  if v_msg.sender_user_id = v_user_id then raise exception 'INVALID_RECIPIENT'; end if;
  insert into public.chat_message_receipts(tenant_id,conversation_id,message_id,user_id,delivered_at)
  values(v_msg.tenant_id,v_msg.conversation_id,v_msg.id,v_user_id,now())
  on conflict (message_id,user_id) do update set delivered_at=coalesce(public.chat_message_receipts.delivered_at,excluded.delivered_at), updated_at=now()
  returning * into v_receipt;
  return v_receipt;
end;
$$;

create or replace function private.chat_mark_read(p_message_id bigint)
returns public.chat_message_receipts
language plpgsql security definer set search_path = '' volatile
as $$
declare v_user_id bigint; v_receipt public.chat_message_receipts; v_msg public.chat_messages; v_participant public.chat_participants;
begin
  v_user_id := private.chat_current_user_id();
  if v_user_id is null then raise exception 'UNAUTHORIZED'; end if;
  select * into v_msg from public.chat_messages where id=p_message_id;
  if not found then raise exception 'NOT_FOUND'; end if;
  select * into v_participant from public.chat_participants where conversation_id=v_msg.conversation_id and user_id=v_user_id and left_at is null;
  if not found and not private.powerhub_has_platform_capability('manageSupportChat') then raise exception 'FORBIDDEN'; end if;
  if v_msg.sender_user_id = v_user_id then raise exception 'INVALID_RECIPIENT'; end if;
  insert into public.chat_message_receipts(tenant_id,conversation_id,message_id,user_id,delivered_at,read_at)
  values(v_msg.tenant_id,v_msg.conversation_id,v_msg.id,v_user_id,now(),now())
  on conflict (message_id,user_id) do update set delivered_at=coalesce(public.chat_message_receipts.delivered_at,now()), read_at=coalesce(public.chat_message_receipts.read_at,now()), updated_at=now()
  returning * into v_receipt;
  update public.chat_participants set last_read_message_id=v_msg.id,last_read_at=now(),updated_at=now() where conversation_id=v_msg.conversation_id and user_id=v_user_id and left_at is null;
  return v_receipt;
end;
$$;

create or replace function public.chat_mark_delivered(p_message_id bigint)
returns public.chat_message_receipts language sql security invoker set search_path='' as $$ select private.chat_mark_delivered($1); $$;
create or replace function public.chat_mark_read(p_message_id bigint)
returns public.chat_message_receipts language sql security invoker set search_path='' as $$ select private.chat_mark_read($1); $$;
revoke execute on function public.chat_mark_delivered(bigint), public.chat_mark_read(bigint) from public, anon;
grant execute on function public.chat_mark_delivered(bigint), public.chat_mark_read(bigint) to authenticated;

create or replace function private.chat_support_user_ids()
returns setof bigint language sql security definer set search_path='' stable
as $$
  select u.id
  from public.users u
  join private.platform_capability_policies p
    on p.platform_role = u.platform_role
   and p.capability = 'manageSupportChat'
   and p.is_allowed = true
  where u.account_status = 'active';
$$;

create or replace function private.chat_create_inbox_notification_for_message()
returns trigger language plpgsql security definer set search_path='' volatile
as $$
declare v_recipient bigint;
begin
  if new.sender_user_id is null then return new; end if;
  for v_recipient in
    select cp.user_id from public.chat_participants cp
    where cp.conversation_id=new.conversation_id and cp.user_id<>new.sender_user_id and cp.left_at is null
    union
    select s.id from private.chat_support_user_ids() s
  loop
    if v_recipient is not null and v_recipient <> new.sender_user_id then
      insert into public.chat_inbox_notifications(user_id,tenant_id,conversation_id,message_id,notification_type,title,body)
      values(v_recipient,new.tenant_id,new.conversation_id,new.id,'chat_message','رسالة جديدة في PowerHub',left(coalesce(new.body,'لديك رسالة جديدة في الدردشة.'),180))
      on conflict do nothing;
    end if;
  end loop;
  return new;
end;
$$;

drop trigger if exists chat_create_inbox_notification_after_message on public.chat_messages;
create trigger chat_create_inbox_notification_after_message after insert on public.chat_messages for each row execute function private.chat_create_inbox_notification_for_message();

create or replace function public.chat_mark_notification_read(p_notification_id bigint)
returns public.chat_inbox_notifications language plpgsql security definer set search_path='' volatile
as $$
declare v_user_id bigint; v_row public.chat_inbox_notifications;
begin
  v_user_id := private.chat_current_user_id();
  if v_user_id is null then raise exception 'UNAUTHORIZED'; end if;
  update public.chat_inbox_notifications set read_at=coalesce(read_at,now()) where id=p_notification_id and user_id=v_user_id returning * into v_row;
  if not found then raise exception 'NOT_FOUND'; end if;
  return v_row;
end;
$$;
revoke execute on function public.chat_mark_notification_read(bigint) from public, anon;
grant execute on function public.chat_mark_notification_read(bigint) to authenticated;

