-- Feature-control separation and auditable global toggles.
create table if not exists public.feature_global_control_audit (
  id bigint generated by default as identity primary key,
  feature_key text not null references public.feature_catalog(feature_key) on delete cascade,
  actor_user_id bigint references public.users(id) on delete set null,
  before_is_active boolean,
  after_is_active boolean not null,
  created_at timestamptz not null default now()
);
alter table public.feature_global_control_audit enable row level security;
revoke all on public.feature_global_control_audit from anon, authenticated;

create or replace function public.powerhub_admin_set_feature_global(
  p_actor_user_id bigint,
  p_feature_key text,
  p_is_active boolean
)
returns table(feature_key text,is_active boolean)
language plpgsql security definer set search_path to 'public','pg_temp'
as $$
declare v_role text; v_setting_key text; v_before boolean;
begin
  select platform_role into v_role from public.users
  where id=p_actor_user_id and role='admin' and platform_role in ('platform_owner','platform_admin') and account_status='active';
  if not found then raise exception 'PLATFORM_ADMIN_FORBIDDEN' using errcode='P0001'; end if;
  select is_active into v_before from public.feature_catalog where feature_key=p_feature_key;
  if not found then raise exception 'FEATURE_NOT_FOUND' using errcode='P0001'; end if;

  insert into public.feature_global_control_audit(feature_key,actor_user_id,before_is_active,after_is_active)
  values(p_feature_key,p_actor_user_id,v_before,p_is_active);

  update public.feature_catalog set is_active=p_is_active,updated_at=now() where feature_key=p_feature_key;
  v_setting_key:=case p_feature_key when 'subscriber_portal_logo' then 'subscriber_portal_logo' when 'payment_documentation' then 'payment_documentation' when 'branch_management' then 'branch_feature' else null end;
  if v_setting_key is not null then
    insert into public.platform_settings(setting_key,is_enabled,value,message,updated_at)
    values(v_setting_key,p_is_active,jsonb_build_object('feature',p_feature_key),'إدارة إتاحة الميزة من مركز الميزات والحدود.',now())
    on conflict(setting_key) do update set is_enabled=excluded.is_enabled,message=excluded.message,updated_at=now();
  end if;
  return query select p_feature_key,p_is_active;
end; $$;

revoke all on function public.powerhub_admin_set_feature_global(bigint,text,boolean) from public,anon,authenticated;
grant execute on function public.powerhub_admin_set_feature_global(bigint,text,boolean) to service_role;
