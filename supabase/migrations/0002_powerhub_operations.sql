-- PowerHub operational, finance, messaging, payroll, and platform settings schema.

create table public.platform_sms_plans (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  description text,
  included_messages integer not null default 0 check (included_messages >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.tenant_subscriptions (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null unique references public.tenants(id) on delete cascade,
  plan text not null default 'starter' check (plan in ('starter', 'professional', 'enterprise')),
  status text not null default 'trial' check (status in ('trial', 'active', 'overdue', 'suspended', 'cancelled')),
  billing_cycle text not null default 'monthly' check (billing_cycle in ('monthly', 'yearly')),
  started_at timestamptz not null default now(),
  ends_at timestamptz not null,
  auto_renew boolean not null default false,
  renewal_count integer not null default 0,
  last_renewed_at timestamptz,
  notes text,
  sms_plan_id bigint references public.platform_sms_plans(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.tenant_branch_settings (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null unique references public.tenants(id) on delete cascade,
  is_enabled_override boolean,
  max_branches_override integer check (max_branches_override is null or max_branches_override >= 0),
  disabled_behavior text not null default 'read_only' check (disabled_behavior in ('read_only', 'suspended')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.sms_package_requests (
  id bigint generated by default as identity primary key,
