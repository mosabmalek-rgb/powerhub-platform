create table public.financial_settlements (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint not null references public.sites(id) on delete restrict,
  period_start timestamptz not null,
  period_end timestamptz not null,
  total_collected numeric(14,2) not null default 0,
  total_expenses numeric(14,2) not null default 0,
  book_profit numeric(14,2) not null default 0,
  actual_cash numeric(14,2),
  difference numeric(14,2),
