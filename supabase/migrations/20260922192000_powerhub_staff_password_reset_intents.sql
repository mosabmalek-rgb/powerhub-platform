-- Secure staff password reset intent + Supabase Auth completion flow.
create table if not exists public.staff_password_reset_intents (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint not null references public.sites(id) on delete cascade,
  actor_user_id bigint not null references public.users(id) on delete restrict,
  target_profile_id bigint not null references public.staff_profiles(id) on delete cascade,
  target_user_id bigint not null references public.users(id) on delete cascade,
  auth_user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','completed','failed','expired')),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '15 minutes'),
  completed_at timestamptz,
  failed_at timestamptz,
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists staff_password_reset_intents_tenant_idx
  on public.staff_password_reset_intents (tenant_id, created_at desc);

create unique index if not exists staff_password_reset_intents_active_target_uidx
  on public.staff_password_reset_intents (target_user_id)
  where status = 'pending';

revoke all on table public.staff_password_reset_intents from public, anon, authenticated;

create or replace function public.powerhub_staff_reset_password_begin(
  p_tenant_id bigint,
  p_site_id bigint,
  p_actor_user_id bigint,
  p_profile_id bigint
)
returns table(intent_id bigint, auth_user_id uuid, target_user_id bigint, expires_at timestamptz)
language plpgsql security invoker set search_path=public,pg_temp
as $$
declare
  v_actor_role text;
  v_actor_platform_role text;
  v_actor_tenant_role text;
  v_target_user_id bigint;
  v_auth_user_id uuid;
  v_profile_role text;
  v_expires_at timestamptz;
  v_before jsonb;
begin
  if not exists (select 1 from public.sites where id=p_site_id and tenant_id=p_tenant_id) then
    raise exception 'SITE_OUT_OF_SCOPE' using errcode='P0001';
  end if;

  select role, platform_role into v_actor_role, v_actor_platform_role
  from public.users where id=p_actor_user_id and account_status='active';
  if not found then raise exception 'ACTOR_NOT_FOUND' using errcode='P0001'; end if;
  if v_actor_role='admin' then raise exception 'STAFF_PASSWORD_RESET_FORBIDDEN' using errcode='P0001'; end if;

  select role into v_actor_tenant_role
  from public.tenant_members
  where tenant_id=p_tenant_id and user_id=p_actor_user_id and is_active=true and membership_status='active';
  if v_actor_tenant_role <> 'owner' then raise exception 'STAFF_PASSWORD_RESET_FORBIDDEN' using errcode='P0001'; end if;

  perform pg_advisory_xact_lock(p_tenant_id, hashtext('staff-password-reset'));

  update public.staff_password_reset_intents
  set status='expired', failed_at=coalesce(failed_at,now()),
      metadata=metadata || jsonb_build_object('reason','expired_before_new_request')
  where tenant_id=p_tenant_id and status='pending' and expires_at<=now();

  if exists (
    select 1 from public.staff_password_reset_intents
    where tenant_id=p_tenant_id and target_profile_id=p_profile_id and status='pending'
  ) then
    raise exception 'RESET_ALREADY_PENDING' using errcode='P0001';
  end if;

  select profile.user_id, profile.role, to_jsonb(profile)
    into v_target_user_id, v_profile_role, v_before
  from public.staff_profiles profile
  where profile.id=p_profile_id and profile.tenant_id=p_tenant_id
    and (profile.site_id=p_site_id or profile.site_id is null)
    and profile.is_active=true
  for update;
  if not found then raise exception 'STAFF_PROFILE_OUT_OF_SCOPE' using errcode='P0001'; end if;
  if v_profile_role='owner' then raise exception 'STAFF_PASSWORD_RESET_FORBIDDEN' using errcode='P0001'; end if;

  select auth_user_id into v_auth_user_id
  from public.users where id=v_target_user_id and account_status<>'disabled';
  if v_auth_user_id is null then raise exception 'STAFF_AUTH_USER_MISSING' using errcode='P0001'; end if;

  insert into public.staff_password_reset_intents(
    tenant_id,site_id,actor_user_id,target_profile_id,target_user_id,auth_user_id,status,expires_at
  )
  values (
    p_tenant_id,p_site_id,p_actor_user_id,p_profile_id,v_target_user_id,v_auth_user_id,'pending',now()+interval '15 minutes'
  )
  returning id, staff_password_reset_intents.expires_at into intent_id,v_expires_at;

  insert into public.audit_logs(
    tenant_id,site_id,user_id,actor_platform_role,actor_tenant_role,entity_type,entity_id,action,before_data,after_data,metadata
  ) values (
    p_tenant_id,p_site_id,p_actor_user_id,v_actor_platform_role,v_actor_tenant_role,
    'staff_password_reset',intent_id::text,'request',v_before,
    jsonb_build_object('targetUserId',v_target_user_id,'targetProfileId',p_profile_id),
    jsonb_build_object('expiresAt',v_expires_at)
  );

  return query select intent_id,v_auth_user_id,v_target_user_id,v_expires_at;
end;
$$;

create or replace function public.powerhub_staff_reset_password_complete(
  p_tenant_id bigint,
  p_site_id bigint,
  p_actor_user_id bigint,
  p_intent_id bigint,
  p_success boolean
)
returns table(intent_id bigint,status text,target_user_id bigint)
language plpgsql security invoker set search_path=public,pg_temp
as $$
declare
  v_intent public.staff_password_reset_intents%rowtype;
  v_actor_role text;
  v_actor_platform_role text;
  v_actor_tenant_role text;
  v_before jsonb;
begin
  select * into v_intent
  from public.staff_password_reset_intents
  where id=p_intent_id and tenant_id=p_tenant_id and site_id=p_site_id
  for update;
  if not found then raise exception 'RESET_INTENT_NOT_FOUND' using errcode='P0001'; end if;

  select role,platform_role into v_actor_role,v_actor_platform_role
  from public.users where id=p_actor_user_id and account_status='active';
  if v_actor_role is distinct from 'user' then raise exception 'STAFF_PASSWORD_RESET_FORBIDDEN' using errcode='P0001'; end if;

  select role into v_actor_tenant_role
  from public.tenant_members
  where tenant_id=p_tenant_id and user_id=p_actor_user_id and is_active=true and membership_status='active';
  if v_actor_tenant_role <> 'owner' then raise exception 'STAFF_PASSWORD_RESET_FORBIDDEN' using errcode='P0001'; end if;

  v_before:=jsonb_build_object('status',v_intent.status,'targetUserId',v_intent.target_user_id);

  if v_intent.status='completed' then
    return query select v_intent.id,v_intent.status,v_intent.target_user_id;
    return;
  end if;

  if v_intent.status<>'pending' then raise exception 'RESET_INTENT_NOT_PENDING' using errcode='P0001'; end if;

  if not p_success then
    update public.staff_password_reset_intents
    set status='failed',failed_at=now(),metadata=metadata || jsonb_build_object('reason','auth_update_failed')
    where id=v_intent.id;
    insert into public.audit_logs(
      tenant_id,site_id,user_id,actor_platform_role,actor_tenant_role,entity_type,entity_id,action,before_data,after_data
    ) values (
      p_tenant_id,p_site_id,p_actor_user_id,v_actor_platform_role,v_actor_tenant_role,
      'staff_password_reset',v_intent.id::text,'failed',v_before,
      jsonb_build_object('status','failed','targetUserId',v_intent.target_user_id)
    );
    return query select v_intent.id,'failed'::text,v_intent.target_user_id;
    return;
  end if;

  update public.users
  set must_change_password=true,temporary_password_issued_at=now(),updated_at=now()
  where id=v_intent.target_user_id and auth_user_id=v_intent.auth_user_id;
  if not found then raise exception 'TARGET_USER_PROFILE_MISSING' using errcode='P0001'; end if;

  update public.staff_password_reset_intents set status='completed',completed_at=now() where id=v_intent.id;

  insert into public.audit_logs(
    tenant_id,site_id,user_id,actor_platform_role,actor_tenant_role,entity_type,entity_id,action,before_data,after_data,metadata
  ) values (
    p_tenant_id,p_site_id,p_actor_user_id,v_actor_platform_role,v_actor_tenant_role,
    'staff_password_reset',v_intent.id::text,'complete',v_before,
    jsonb_build_object('status','completed','targetUserId',v_intent.target_user_id),
    jsonb_build_object('completedAt',now())
  );

  return query select v_intent.id,'completed'::text,v_intent.target_user_id;
end;
$$;

revoke all on function public.powerhub_staff_reset_password_begin(bigint,bigint,bigint,bigint) from public,anon,authenticated;
revoke all on function public.powerhub_staff_reset_password_complete(bigint,bigint,bigint,bigint,boolean) from public,anon,authenticated;
grant execute on function public.powerhub_staff_reset_password_begin(bigint,bigint,bigint,bigint) to service_role;
grant execute on function public.powerhub_staff_reset_password_complete(bigint,bigint,bigint,bigint,boolean) to service_role;

alter table public.staff_password_reset_intents enable row level security;
