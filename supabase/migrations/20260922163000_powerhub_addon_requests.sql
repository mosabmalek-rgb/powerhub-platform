-- Owner-selectable add-on requests. Add-ons do not change the subscription package.
create table if not exists public.tenant_addon_requests (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  site_id bigint references public.sites(id) on delete set null,
  requested_by_user_id bigint not null references public.users(id),
  addon_code text not null check (addon_code in ('fieldUser','platformUser','subscribers50','branch','sms')),
  quantity integer not null default 1 check (quantity > 0 and quantity <= 1000),
  status text not null default 'pending' check (status in ('pending','reviewing','approved','rejected','cancelled')),
  note text,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by_user_id bigint references public.users(id),
  review_note text
);

create index if not exists tenant_addon_requests_tenant_status_idx
on public.tenant_addon_requests(tenant_id,status,created_at desc);

create or replace function public.powerhub_request_tenant_addon(
  p_tenant_id bigint,
  p_site_id bigint,
  p_user_id bigint,
  p_addon_code text,
  p_quantity integer default 1,
  p_note text default null
)
returns table(request_id bigint, addon_code text, quantity integer, already_requested boolean)
language plpgsql security invoker set search_path=public,pg_temp
as $$
declare
  v_existing_id bigint;
  v_existing_qty integer;
begin
  if p_addon_code not in ('fieldUser','platformUser','subscribers50','branch','sms') then
    raise exception 'INVALID_ADDON_CODE' using errcode='P0001';
  end if;
  if p_quantity is null or p_quantity < 1 or p_quantity > 1000 then
    raise exception 'INVALID_ADDON_QUANTITY' using errcode='P0001';
  end if;
  if p_site_id is not null and not exists (
    select 1 from public.sites where id=p_site_id and tenant_id=p_tenant_id and status<>'archived'
  ) then
    raise exception 'SITE_OUT_OF_SCOPE' using errcode='P0001';
  end if;

  select id,quantity into v_existing_id,v_existing_qty
  from public.tenant_addon_requests
  where tenant_id=p_tenant_id and addon_code=p_addon_code and status in ('pending','reviewing')
  order by created_at desc limit 1 for update;

  if found then
    return query select v_existing_id,p_addon_code,v_existing_qty,true;
    return;
  end if;

  insert into public.tenant_addon_requests(tenant_id,site_id,requested_by_user_id,addon_code,quantity,note)
  values(p_tenant_id,p_site_id,p_user_id,p_addon_code,p_quantity,p_note)
  returning id into v_existing_id;

  insert into public.audit_logs(tenant_id,site_id,user_id,entity_type,entity_id,action,after_data)
  values(p_tenant_id,p_site_id,p_user_id,'tenant_addon_request',v_existing_id::text,'request_addon',
    jsonb_build_object('addonCode',p_addon_code,'quantity',p_quantity,'note',p_note));

  return query select v_existing_id,p_addon_code,p_quantity,false;
end;
$$;

revoke execute on function public.powerhub_request_tenant_addon(bigint,bigint,bigint,text,integer,text) from public,anon,authenticated;
grant execute on function public.powerhub_request_tenant_addon(bigint,bigint,bigint,text,integer,text) to service_role;

create or replace function public.powerhub_admin_tenant_addon_requests()
returns table(
 id bigint, tenant_id bigint, site_id bigint, addon_code text, quantity integer, status text,
 note text, created_at timestamptz, reviewed_at timestamptz, tenant_name text, owner_name text, owner_email text
)
language sql security definer set search_path=public,pg_temp
as $$
 select r.id,r.tenant_id,r.site_id,r.addon_code,r.quantity,r.status,r.note,r.created_at,r.reviewed_at,
        t.name,op.full_name,op.email
 from public.tenant_addon_requests r
 join public.tenants t on t.id=r.tenant_id
 left join public.tenant_owner_profiles op on op.tenant_id=r.tenant_id
 order by r.created_at desc limit 500
$$;

revoke all on function public.powerhub_admin_tenant_addon_requests() from public,anon,authenticated;
grant execute on function public.powerhub_admin_tenant_addon_requests() to service_role;

create or replace function public.powerhub_admin_review_tenant_addon_request(
 p_actor_user_id bigint,p_request_id bigint,p_decision text,p_note text default null
)
returns table(success boolean,status text)
language plpgsql security definer set search_path=public,pg_temp
as $$
begin
 if p_decision not in ('approved','rejected') then raise exception 'INVALID_DECISION' using errcode='P0001'; end if;
 update public.tenant_addon_requests
 set status=p_decision,reviewed_at=now(),reviewed_by_user_id=p_actor_user_id,review_note=p_note
 where id=p_request_id and status in ('pending','reviewing');
 if not found then raise exception 'ADDON_REQUEST_NOT_PENDING' using errcode='P0001'; end if;
 return query select true,p_decision;
end;
$$;

revoke all on function public.powerhub_admin_review_tenant_addon_request(bigint,bigint,text,text) from public,anon,authenticated;
grant execute on function public.powerhub_admin_review_tenant_addon_request(bigint,bigint,text,text) to service_role;
