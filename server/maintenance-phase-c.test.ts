    expect(integration).toContain("MAINTENANCE_COMPLETION_CORRECTION_COST_FAILED");
    expect(integration).toContain("MAINTENANCE_COMPLETION_CORRECTION_IDEMPOTENCY_PAYLOAD_CONFLICT_ACCEPTED");
